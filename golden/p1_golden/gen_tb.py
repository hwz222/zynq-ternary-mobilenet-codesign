# -*- coding: utf-8 -*-
"""gen_tb.py -- turn P1's golden vectors into self-contained Verilog testbenches.

Follows the convention already in rtl/tb/: the stimulus and the expected values are
BAKED IN as literals rather than read from files at simulation time. Two reasons that
convention exists in this repo and still applies here:

  - the testbench file name is the module name, so a testbench can never be silently
    replaced by a same-named twin already sitting in the shared xsim library
  - a $readmemh path that resolves differently on two machines is a whole class of
    "passes here, fails there" that literals simply do not have

What this emits is the DATA half of a testbench: geometry parameters, activations,
packed ternary weights, requant constants, and the expected output row, plus a clearly
marked stub where P2/P3 wires the module under test. The DUT half is deliberately left
open because twn_tern_array and twn_dw_array do not exist yet -- P1's job is to make
sure that when they do, there is nothing to invent.

  python gen_tb.py --list
  python gen_tb.py --tern <block> <e|p> [--row N] [-o out.v]
  python gen_tb.py --dw   <block>       [--row N] [-o out.v]
"""
import io, json, os, struct, sys

VEC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vec")
MAN = os.path.join(VEC, "p1_manifest.json")


def load():
    if not os.path.exists(MAN):
        sys.exit("no manifest at %s -- run run_p1.sh first" % MAN)
    return json.load(io.open(MAN, encoding="utf-8"))


def blob(name):
    return open(os.path.join(VEC, name + ".bin"), "rb").read()


def i8(b):
    return [x - 256 if x > 127 else x for x in b]


def rq_table(name, oc):
    """oc x int32 M0, then oc x int64 bias, then oc x uint8 shift (already narrowed)."""
    d = blob(name)
    m0 = list(struct.unpack("<%di" % oc, d[: 4 * oc]))
    bs = list(struct.unpack("<%dq" % oc, d[4 * oc : 4 * oc + 8 * oc]))
    sh = list(d[4 * oc + 8 * oc :])
    return m0, bs, sh


NL = chr(10)


def hexlit(v, bits):
    return "%d'h%0*x" % (bits, (bits + 3) // 4, v & ((1 << bits) - 1))


HEADER = """// AUTO-GENERATED by golden/p1_golden/gen_tb.py from the P1 golden vectors -- do not edit.
// Source: %s   (manifest %s)
// The values below come from the model itself through the path that passed P0,
// not from random stimulus: a mismatch here is the design disagreeing with the
// network, which is the only disagreement that matters.
`timescale 1ns/1ps
"""


def emit_tern(man, bi, stage, row, out):
    b = man["blocks"][bi]
    pk = b["pack_e"] if stage == "e" else b["pack_p"]
    n_eff, npass, pack, words = pk["n_eff"], pk["passes"], pk["pack"], pk["words_per_group"]
    # stage e reads the block input and writes the mid tensor;
    # stage p reads the depthwise output and writes the project output.
    if stage == "e":
        src, dst = "b%02d_in" % bi, "b%02d_e" % bi
        sc, sh_, sw = b["in"]["c"], b["in"]["h"], b["in"]["w"]
        dc, dh, dw = b["mid"]["c"], b["mid"]["h"], b["mid"]["w"]
        rq, off, clamp, relu = "b%02d_rqe" % bi, b["rq_off"]["e"], b["clamp"]["e"], b["relu"]["e"]
        wt, stride = "b%02d_wte" % bi, b["expand_stride"]
    else:
        src, dst = "b%02d_d" % bi, ("b%02d_p" % bi if b["has_residual"] else "b%02d_out" % bi)
        sc, sh_, sw = b["mid"]["c"], b["out"]["h"], b["out"]["w"]
        dc, dh, dw = b["out"]["c"], b["out"]["h"], b["out"]["w"]
        rq, off, clamp, relu = "b%02d_rqp" % bi, b["rq_off"]["p"], b["clamp"]["p"], b["relu"]["p"]
        wt, stride = "b%02d_wtp" % bi, 1

    X, Y, W = i8(blob(src)), i8(blob(dst)), blob(wt)
    m0, bs, shv = rq_table(rq, dc)
    mod = os.path.splitext(os.path.basename(out))[0]

    L = [HEADER % (dst + ".bin", "p1_manifest.json")]
    L.append("module %s;\n" % mod)
    L.append("  // ---- geometry (block %d, %s stage) ----" % (bi, "expand/stem" if stage == "e" else "project"))
    for k, v in [("BLOCK", bi), ("IC", sc), ("OC", dc), ("IH", sh_), ("IW", sw),
                 ("OH", dh), ("OW", dw), ("STRIDE", stride), ("N_EFF", n_eff),
                 ("N_PASS", npass), ("PACK", pack), ("WORDS", words),
                 ("N_SEG", (n_eff + 127) // 128), ("RELU", relu),
                 ("CLAMP_LO", clamp[0]), ("CLAMP_HI", clamp[1]), ("RQ_OFF", off),
                 ("TEST_ROW", row)]:
        L.append("  localparam integer %-9s = %d;" % (k, v))
    L.append("")
    iy = row * stride
    L.append("  // ---- activations ----")
    L.append("  // output row %d <- input row %d. A 1x1 stage reads ONE row; the 3x3 stem" % (row, iy))
    L.append("  // reads one row per pass (rows %d, %d, %d), which is exactly why the" % (iy - 1, iy, iy + 1))
    L.append("  // per-kernel-row schedule fits tern_uop's single address field (§3.5).")
    L.append("  // One 1024-bit word per pixel, lane order = input channel index.")
    for x in range(min(dw, 4)):                      # first 4 pixels only
        ix = x * stride
        vals = [X[(c * sh_ + iy) * sw + ix] if iy < sh_ and ix < sw else 0 for c in range(sc)]
        v = 0
        for k, a in enumerate(vals[:128]):
            v |= (a & 0xFF) << (8 * k)
        L.append("  localparam [1023:0] ACT_PX%d = %s;" % (x, hexlit(v, 1024)))
    L.append("")
    L.append("  // ---- packed ternary weights, one 128-lane word per output-channel group ----")
    ngrp = (dc + pack - 1) // pack
    show = min(ngrp * npass, 8)
    for g in range(show):
        w = int.from_bytes(W[g * words * 32:(g + 1) * words * 32], "little")
        L.append("  localparam [%d:0] WT%d = %s;" % (words * 256 - 1, g, hexlit(w, words * 256)))
    if ngrp * npass > show:
        L.append("  // ... %d more groups in %s.bin (%d bytes total)"
                 % (ngrp * npass - show, wt, len(W)))
    L.append("")
    L.append("  // ---- requant constants, narrowed to the hardware widths 18/40/6 ----")
    L.append("  localparam integer NARROW_M0 = 18, NARROW_BIAS = 40, NARROW_SH = 6;")
    # the sign goes outside the sized literal: -40'sd165357, not 40'sd-165357
    def sv(v, bits):
        return "%s%d'sd%d" % ("-" if v < 0 else "", bits, abs(v))
    for c in range(min(dc, 8)):
        L.append("  localparam signed [17:0] M0_%-3d = %s;   localparam signed [39:0] BIAS_%-3d = %s;   localparam [5:0] SH_%-3d = 6'd%d;"
                 % (c, sv(m0[c], 18), c, sv(bs[c], 40), c, shv[c]))
    if dc > 8:
        L.append("  // ... %d more channels in %s.bin" % (dc - 8, rq))
    L.append("")
    L.append("  // ---- expected output row %d ----" % row)
    for c in range(min(dc, 8)):
        vals = [Y[(c * dh + row) * dw + x] for x in range(min(dw, 16))]
        L.append("  // oc %-3d : %s%s" % (c, " ".join("%4d" % v for v in vals),
                                          " ..." if dw > 16 else ""))
    L.append("  reg signed [7:0] expected [0:OC*OW-1];")
    L.append("  initial begin")
    for c in range(dc):
        for x in range(dw):
            v = Y[(c * dh + row) * dw + x]
            L.append("    expected[%d] = %s8'sd%d;" % (c * dw + x, "-" if v < 0 else " ", abs(v)))
    L.append("  end")
    L.append("")
    L.append("""  // ==== DUT: wire twn_tern_array here (§5.5's port table) ====================
  // The module does not exist yet -- P2 builds it. Everything it needs to be driven
  // with, and everything it must produce, is above. The uop fields for this case:
  //   role      = %d          (0 = first ternary conv, 1 = second)
  //   n_seg     = %d
  //   n_ocg     = %d
  //   pack      = %d
  //   n_pass    = %d          (3 only for the 3x3 stem, 1 otherwise)
  //   clamp     = [%d, %d], relu = %d
  //   rq_base   = %d
  // ===========================================================================
  initial begin
    $display("%%m: block %d %s stage, row %d -- data package only, no DUT wired yet");
    $finish;
  end
endmodule""" % (0 if stage == "e" else 1, (n_eff + 127) // 128, ngrp, pack, npass,
                clamp[0], clamp[1], relu, off, bi, stage, row))
    io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    return out, len(L)


def emit_dw(man, bi, row, out):
    b = man["blocks"][bi]
    C = b["mid"]["c"]
    IH, IW = b["mid"]["h"], b["mid"]["w"]
    OH, OW = b["out"]["h"], b["out"]["w"]
    s = b["dw_stride"]
    X, Y = i8(blob("b%02d_e" % bi)), i8(blob("b%02d_d" % bi))
    Wd = i8(blob("b%02d_wdw" % bi))
    m0, bs, shv = rq_table("b%02d_rqd" % bi, C)
    mod = os.path.splitext(os.path.basename(out))[0]
    rows = [row * s - 1, row * s, row * s + 1]

    L = [HEADER % ("b%02d_d.bin" % bi, "p1_manifest.json")]
    L.append("module %s;\n" % mod)
    L.append("  // ---- geometry (block %d depthwise, stride %d) ----" % (bi, s))
    for k, v in [("BLOCK", bi), ("C", C), ("IH", IH), ("IW", IW), ("OH", OH), ("OW", OW),
                 ("STRIDE", s), ("RELU", b["relu"]["d"]),
                 ("CLAMP_LO", b["clamp"]["d"][0]), ("CLAMP_HI", b["clamp"]["d"][1]),
                 ("TEST_ROW", row)]:
        L.append("  localparam integer %-9s = %d;" % (k, v))
    L.append("")
    L.append("  // output row %d needs input rows %s" % (row, rows))
    L.append("  // rows outside [0, IH) are the ZERO PAD -- %s"
             % ("both edges present in this vector" if row in (0, OH - 1) else
                "this row is interior; regenerate with --row 0 or --row %d for the edges" % (OH - 1)))
    L.append("  localparam PAD_TOP = %d, PAD_BOT = %d;"
             % (1 if rows[0] < 0 else 0, 1 if rows[2] >= IH else 0))
    L.append("")
    L.append("  // ---- the three input rows, one 8-bit lane per channel ----")
    for r, iy in enumerate(rows):
        for x in range(min(IW, 2)):
            v = 0
            for c in range(min(C, 128)):
                a = X[(c * IH + iy) * IW + x] if 0 <= iy < IH else 0
                v |= (a & 0xFF) << (8 * c)
            L.append("  localparam [1023:0] ROW%d_PX%d = %s;" % (r, x, hexlit(v, 1024)))
    L.append("  // (full rows in b%02d_e.bin -- %d channels x %d pixels)" % (bi, C, IW))
    L.append("")
    L.append("  // ---- 3x3 int8 weights, channel-major ----")
    for c in range(min(C, 4)):
        L.append("  // ch %-3d : %s" % (c, " ".join("%4d" % Wd[c * 9 + k] for k in range(9))))
    L.append("  reg signed [7:0] wdw [0:C*9-1];")
    L.append("  initial begin")
    for c in range(C):
        for k in range(9):
            L.append("    wdw[%d] = %s8'sd%d;" % (c * 9 + k, "-" if Wd[c*9+k] < 0 else " ", abs(Wd[c*9+k])))
    L.append("  end")
    L.append("")
    L.append("  // ---- expected output row %d ----" % row)
    L.append("  reg signed [7:0] expected [0:C*OW-1];")
    L.append("  initial begin")
    for c in range(C):
        for x in range(OW):
            v = Y[(c * OH + row) * OW + x]
            L.append("    expected[%d] = %s8'sd%d;" % (c * OW + x, "-" if v < 0 else " ", abs(v)))
    L.append("  end")
    L.append("")
    # ---- the three FULL input rows, as 1024-bit words: [row][chgroup][pixel] ----
    # 1024 bits = 128 channels x 8 bit of ONE pixel. Blocks wider than 128
    # channels use several groups; the window read is the same address in all
    # three rows, so the group index simply extends the word address.
    NG = (C + 127) // 128
    hexname = mod + "_in.hex"
    with open(os.path.join(os.path.dirname(out) or ".", hexname), "w") as hf:
        for r, iy in enumerate(rows):
            for g in range(NG):
                for x in range(IW):
                    v = 0
                    for c in range(g * 128, min(C, (g + 1) * 128)):
                        a = X[(c * IH + iy) * IW + x] if 0 <= iy < IH else 0
                        v |= (a & 0xFF) << (8 * (c - g * 128))
                    hf.write("%0256x" % v + chr(10))

    L.append("  // ---- requant, per channel ----")
    L.append("  reg signed [17:0] rq_m0 [0:C-1];")
    L.append("  reg signed [31:0] rq_bs [0:C-1];")
    L.append("  reg [5:0]         rq_sh [0:C-1];")
    L.append("  initial begin")
    for c in range(C):
        L.append("    rq_m0[%d] = %s18'sd%d; rq_bs[%d] = %s32'sd%d; rq_sh[%d] = 6'd%d;"
                 % (c, "-" if m0[c] < 0 else " ", abs(m0[c]),
                    c, "-" if bs[c] < 0 else " ", abs(bs[c]), c, shv[c]))
    L.append("  end")
    L.append("")
    L.append(DRIVER % dict(hexname=hexname, ng=NG, bi=bi, row=row, s=s))
    io.open(out, "w", encoding="utf-8", newline=NL).write(NL.join(L) + NL)
    return out, len(L)


DRIVER = """
  // ==== driver + checker: twn_dw_array against the P1 golden row ==============
  // The row buffer supplies the three rows; here they are played straight in,
  // which is the point of testing the array first. tb_p3_dw_ring.v covers the
  // buffer's own pointer behaviour, and tb_rowptr_rule.v covers the rules.
  localparam integer NG = %(ng)d;                 // channel groups of 128
  reg [1023:0] inrow [0:3*NG*IW-1];
  initial $readmemh("%(hexname)s", inrow);

  reg clk = 0; always #5 clk = ~clk;
  reg rst = 1;

  reg  v_i, first_i, last_i;
  reg  [7:0] x_i;
  reg  [7:0] tag_i;
  reg  [63:0] rt_i, rm_i, rb_i;   // ONE lane group, sliced by the caller
  reg  [8*9*8-1:0] wt_i;
  reg  [8*18-1:0]  m0_i;
  reg  [8*32-1:0]  bs_i;
  reg  [8*6-1:0]   sh_i;
  wire ov; wire [63:0] od; wire [7:0] ox; wire [7:0] otag;

  twn_dw_array #(.DW_LANES(8), .ROW_BITS(1024)) DUT (
    .clk(clk), .rst(rst),
    .n_ch(C[9:0]), .w_out(OW[7:0]), .stride(STRIDE == 2),
    .clamp_lo(CLAMP_LO[15:0]), .clamp_hi(CLAMP_HI[15:0]),
    .in_valid(v_i), .row_t(rt_i), .row_m(rm_i), .row_b(rb_i),
    .in_x(x_i), .in_first(first_i), .in_last(last_i), .in_tag(tag_i),
    .w_taps(wt_i), .m0(m0_i), .bias(bs_i), .sh(sh_i),
    .out_valid(ov), .out_data(od), .out_x(ox), .out_tag(otag));

  integer g, l0, x, k, L2, ch, errors, checked;
  reg signed [7:0] got, want;

  initial begin
    errors = 0; checked = 0;
    @(negedge clk); rst = 0;

    for (g = 0; g < NG; g = g + 1)
      for (l0 = 0; l0 < 128 && g*128 + l0 < C; l0 = l0 + 8) begin
        // per-lane weights and requant for this group of 8 channels
        for (L2 = 0; L2 < 8; L2 = L2 + 1) begin
          ch = g*128 + l0 + L2;
          for (k = 0; k < 9; k = k + 1)
            wt_i[(L2*9 + k)*8 +: 8] = (ch < C) ? wdw[ch*9 + k] : 8'sd0;
          m0_i[L2*18 +: 18] = (ch < C) ? rq_m0[ch] : 18'sd0;
          bs_i[L2*32 +: 32] = (ch < C) ? rq_bs[ch] : 32'sd0;
          sh_i[L2*6  +: 6 ] = (ch < C) ? rq_sh[ch] : 6'd0;
        end

        // columns 0..IW-1, then ONE extra so the last window completes
        for (x = 0; x <= IW; x = x + 1) begin
          @(negedge clk);
          v_i     = (x < IW);
          x_i     = x[7:0];
          first_i = (x == 0);
          last_i  = (x == IW-1);
          tag_i   = {g[3:0], l0[6:3]};   // group AND lane group ride the tag
          // The extra cycle carries the row's FIRST pixel rather than zeros.
          // Feeding zeros there makes the right-hand pad mask redundant -- the
          // tap would read zero whether or not the mask exists -- and the
          // DW_NO_HPAD ablation showed that: it failed on only 8 values per
          // case, all of them at x=0, because x=W-1 was never actually testing
          // anything. A real row buffer presents whatever the next address
          // holds, so the test presents something too.
          rt_i = inrow[(0*NG + g)*IW + (x < IW ? x : 0)][l0*8 +: 64];
          rm_i = inrow[(1*NG + g)*IW + (x < IW ? x : 0)][l0*8 +: 64];
          rb_i = inrow[(2*NG + g)*IW + (x < IW ? x : 0)][l0*8 +: 64];
        end
        // Hold this group's weights until its last column has cleared S1.
        // Changing them at the top of the next iteration computes the tail of
        // this group with the next group's constants -- see the weight-hold
        // contract in twn_dw_array.v.
        v_i = 0;
        repeat (5) @(negedge clk);   // S1a and S1c added stages; the hold covers both
      end
    @(negedge clk); v_i = 0;
    // Drain. This was 8, which covered S0+S1a+S1b+S1c+S2+S3 with two to spare.
    // Moving the requant into twn_fuse_requant made the tail two stages deeper
    // and 8 stopped being enough -- and a short drain does NOT fail, it just
    // checks fewer values, which is the quietest way for a gate to stop testing.
    // Hence both the larger number and the count assertion below.
    repeat (24) @(negedge clk);

    $display("%%m: block %(bi)d dw, output row %(row)d, stride %(s)d -- %%0d values checked, %%0d errors",
             checked, errors);
    // A gate that checked the wrong NUMBER of values is not a gate. Every
    // output pixel of every channel must have been compared exactly once.
    if (checked != C*OW) begin
        $display("%%m: *** CHECKED %%0d VALUES, EXPECTED %%0d -- the drain is too short or beats went missing ***",
                 checked, C*OW);
        $display("%%m: %%0d FAIL", errors + (C*OW - checked));
        $finish;
    end
    if (errors == 0) $display("%%m: ALL PASS");
    else             $display("%%m: %%0d FAIL", errors);
    $finish;
  end

  // checker: every emitted beat is compared against the golden row.
  // The lane group comes from the DUT's own tag (out_lane0), not from the
  // driver's loop variables: the driver has already moved on by
  // the time the last beats of this one emerge, and attributing those beats to
  // the new group is what the first run of this test actually caught.
  always @(posedge clk) if (!rst && ov) begin
    for (L2 = 0; L2 < 8; L2 = L2 + 1) begin
      ch = otag[7:4]*128 + otag[3:0]*8 + L2;
      if (ch < C && ox < OW) begin
        got  = od[L2*8 +: 8];
        want = expected[ch*OW + ox];
        checked = checked + 1;
        if (got !== want) begin
          errors = errors + 1;
          if (errors <= 10)
            $display("  MISMATCH ch=%%0d x=%%0d  got %%0d  want %%0d", ch, ox, got, want);
        end
      end
    end
  end
endmodule
"""


def do_list(man):
    print("P1 vectors: %d blocks, fixture %s" % (len(man["blocks"]), man["fixture"]))
    print()
    print("  blk   ternary: expand         ternary: project      depthwise")
    print("  ---   --------------------    -------------------   -------------------")
    for i, b in enumerate(man["blocks"]):
        e, p = b["pack_e"], b["pack_p"]
        print("  %3d   n_eff=%-4d pack=%d p=%-2d   n_eff=%-4d pack=%d      C=%-4d stride=%d %s"
              % (i, e["n_eff"], e["pack"], e["passes"], p["n_eff"], p["pack"],
                 b["mid"]["c"], b["dw_stride"], "residual" if b["has_residual"] else ""))
    print()
    print("  python gen_tb.py --tern <blk> e|p [--row N]   -> ternary array data package")
    print("  python gen_tb.py --dw   <blk>     [--row N]   -> depthwise data package")


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a or a[0] == "--list":
        do_list(load()); sys.exit(0)
    man = load()
    row = 0
    if "--row" in a:
        row = int(a[a.index("--row") + 1])
    out = None
    if "-o" in a:
        out = a[a.index("-o") + 1]
    if a[0] == "--tern":
        bi, st = int(a[1]), a[2]
        out = out or "tb_p1_tern_b%02d%s_r%d.v" % (bi, st, row)
        f, n = emit_tern(man, bi, st, row, out)
    elif a[0] == "--dw":
        bi = int(a[1])
        out = out or "tb_p1_dw_b%02d_r%d.v" % (bi, row)
        f, n = emit_dw(man, bi, row, out)
    else:
        sys.exit(__doc__)
    print("wrote %s (%d lines)" % (f, n))

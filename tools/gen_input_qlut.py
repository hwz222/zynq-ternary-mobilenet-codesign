#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""gen_input_qlut.py -- generate sw/app/input_qlut.h, the int8 input quantizer table.

Training and export quantize the ImageNet-normalised tensor:
    q(v, c) = clip(round(((v/255) - MEAN[c]) / STD[c] / INPUT_SCALE), IN_LO, 127)
The board app (sw/app/main_cam.c) indexes this per-channel 256-entry table instead
of computing the arithmetic at runtime, so numpy's round-half-to-even is used
once, here.

Reads:   models/mbv2_pose/model_meta.c   INPUT_SCALE is parsed from it (--meta to use another)
Writes:  sw/app/input_qlut.h     (--out to change)

    python tools/gen_input_qlut.py [--meta model_meta.c] [--in-lo -127] [--out FILE]
    python tools/gen_input_qlut.py --check    verify the existing header, write nothing
                                              (exit 1 if missing or stale)

IN_LO is -127 for the strict-int8 arm, -128 otherwise. The ImageNet mean/std below
are repeated here (the training config is not in this tree); the top-blue check in
main() fails if INPUT_SCALE and the normalisation come from different models.
"""
import argparse
import io
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Standard ImageNet statistics.
IMAGE_MEAN = (0.485, 0.456, 0.406)
IMAGE_STD = (0.229, 0.224, 0.225)


def read_input_scale(meta_c):
    s = io.open(meta_c, encoding="utf-8", errors="replace").read()
    m = re.search(r"const\s+double\s+INPUT_SCALE\s*=\s*([0-9.eE+-]+)\s*;", s)
    if not m:
        raise SystemExit("no INPUT_SCALE in %s" % meta_c)
    return float(m.group(1))


def build(scale, in_lo):
    v = np.arange(256)
    t = np.empty((3, 256), dtype=np.int64)
    for c in range(3):
        x = ((v / 255.0) - IMAGE_MEAN[c]) / IMAGE_STD[c] / scale
        t[c] = np.clip(np.round(x), in_lo, 127)
    return t


def main():
    ap = argparse.ArgumentParser()
    # The default meta file is the one the committed sw/app/input_qlut.h records.
    ap.add_argument("--meta", default=os.path.join(ROOT, "models", "mbv2_pose", "model_meta.c"),
                    help="model_meta.c of the DEPLOYED export; INPUT_SCALE is read from it "
                         "(default models/mbv2_pose/model_meta.c, the one sw/app/input_qlut.h records)")
    ap.add_argument("--in-lo", type=int, default=-127,
                    help="clamp floor: -127 for the strict-int8 arm (what ships), -128 otherwise")
    ap.add_argument("--out", default=os.path.join(ROOT, "sw", "app", "input_qlut.h"))
    ap.add_argument("--check", action="store_true", help="verify the existing header, write nothing")
    a = ap.parse_args()

    scale = read_input_scale(a.meta)
    t = build(scale, a.in_lo)

    # Fingerprint: INPUT_SCALE was calibrated on the normalised tensor, so the
    # brightest blue pixel must land within half an LSB of the int8 ceiling.
    top_blue = (1.0 - IMAGE_MEAN[2]) / IMAGE_STD[2] / scale
    if not (126.5 <= top_blue <= 128.5):
        raise SystemExit("INPUT_SCALE %r puts the brightest blue at %.3f, not on the int8 "
                         "ceiling -- scale and normalisation disagree" % (scale, top_blue))
    assert t.min() >= a.in_lo and t.max() <= 127
    assert (t[:, 1:] >= t[:, :-1]).all(), "the table must be monotonic in the input byte"

    rel = os.path.relpath(a.meta, ROOT).replace("\\", "/")
    lines = []
    w = lines.append
    w("/* input_qlut.h -- GENERATED by tools/gen_input_qlut.py. Do not edit. */")
    w("/*")
    w(" * The int8 input for each of the 256 possible byte values, per channel:")
    w(" *")
    w(" *     q(v, c) = clip(round(((v/255) - MEAN[c]) / STD[c] / INPUT_SCALE), %d, 127)" % a.in_lo)
    w(" *")
    w(" * MEAN = %s, STD = %s" % (list(IMAGE_MEAN), list(IMAGE_STD)))
    w(" * INPUT_SCALE = %r   parsed from %s" % (scale, rel))
    w(" * IN_LO = %d" % a.in_lo)
    w(" *")
    w(" * round() is numpy's round-half-to-even, which is why this is a generated")
    w(" * table and not runtime arithmetic.")
    w(" */")
    w("#ifndef INPUT_QLUT_H")
    w("#define INPUT_QLUT_H")
    w("#include <stdint.h>")
    w("")
    w("/* plane 0 = R, plane 1 = G, plane 2 = B -- the order yuyv_to_rgb() and TJPF_RGB")
    w(" * both produce, and the order the planes are written in. */")
    w("static const int8_t INPUT_QLUT[3][256] = {")
    for c, nm in enumerate("RGB"):
        w("  { /* %s: [%d, %d] */" % (nm, int(t[c].min()), int(t[c].max())))
        for i in range(0, 256, 16):
            w("    " + ", ".join("%4d" % x for x in t[c][i:i + 16]) + ",")
        w("  },")
    w("};")
    w("")
    w("/* Fingerprints of THIS model's table, so a stale or truncated header fails loudly")
    w(" * instead of quietly feeding the network the wrong range. Cheap enough to call")
    w(" * unconditionally at startup. */")
    w("#define INPUT_QLUT_R_MIN (%d)" % int(t[0].min()))
    w("#define INPUT_QLUT_B_MAX (%d)" % int(t[2].max()))
    w("static inline int input_qlut_selfcheck(void) {")
    w("    if (INPUT_QLUT[0][0]   != INPUT_QLUT_R_MIN) return 1;")
    w("    if (INPUT_QLUT[2][255] != INPUT_QLUT_B_MAX) return 2;")
    w("    for (int c = 0; c < 3; c++)")
    w("        for (int v = 1; v < 256; v++)")
    w("            if (INPUT_QLUT[c][v] < INPUT_QLUT[c][v-1]) return 3;   /* monotonic */")
    w("    return 0;")
    w("}")
    w("#endif")
    text = "\n".join(lines) + "\n"

    if a.check:
        if not os.path.exists(a.out):
            print("MISSING %s" % a.out)
            return 1
        cur = io.open(a.out, encoding="utf-8", newline="").read()
        same = (cur == text)
        print("%s: %s" % (os.path.relpath(a.out, ROOT), "up to date" if same else "STALE"))
        return 0 if same else 1

    io.open(a.out, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s" % a.out)
    for c, nm in enumerate("RGB"):
        print("  %s: [%4d, %4d]   (the raw-byte table it replaces was [   0,  %3d] on all three)"
              % (nm, int(t[c].min()), int(t[c].max()), int(round(255.0 / (255.0 * scale)))))
    return 0


if __name__ == "__main__":
    sys.exit(main())

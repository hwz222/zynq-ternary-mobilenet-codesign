# -*- coding: utf-8 -*-
"""gen_wfetch_tb.py -- the DDR image and descriptors tb_wfetch.v runs against.

The fetcher's gate is that it reproduces the packed file in the memories (right
words, addresses, order, every block); matching the goldens is already checked by
pack_fuse_weights.py --verify. The testbench derives what it expects from the same
DDR image it serves.

Reads:   golden/p1_golden/vec/fuse_weights.bin, fuse_weights_index.json (from
         tools/pack_fuse_weights.py; the first candidate directory below is a
         leftover path of the older repo and is skipped when absent)
Writes (next to this file):
  tb_wfetch_ddr.hex    the packed file as 128-bit beats (little-endian within a beat)
  tb_wfetch_desc.vh    the per-block descriptors, from the packer's index

usage:  python rtl/fuse/tb/gen_wfetch_tb.py
"""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
VEC  = os.path.join(ROOT, "golden", "p1_golden", "vec")

blob = io.open(os.path.join(VEC, "fuse_weights.bin"), "rb").read()
idx  = json.load(io.open(os.path.join(VEC, "fuse_weights_index.json"), encoding="utf-8"))
B    = idx["blocks"]

# ---- the DDR image, 128-bit beats ----
if len(blob) % 16:
    blob += bytes(16 - len(blob) % 16)
with io.open(os.path.join(HERE, "tb_wfetch_ddr.hex"), "w") as f:
    for i in range(0, len(blob), 16):
        f.write("%032x\n" % int.from_bytes(blob[i:i + 16], "little"))

# ---- the descriptors ----
L = []
L.append("// generated by gen_wfetch_tb.py -- do not edit")
L.append("localparam integer NBLK  = %d;" % len(B))
L.append("localparam integer NBEAT = %d;" % (len(blob) // 16))
for name, key, field, w in (
    ("OFF_TERN", "tern", "off",      32), ("OFF_DW",  "dw",  "off",      32),
    ("OFF_RQA",  "rqa",  "off",      32), ("OFF_RQD", "rqd", "off",      32),
    ("N_TERN",   "tern", "words",    16), ("N_DW",    "dw",  "words",    16),
    ("N_RQA",    "rqa",  "words",    16), ("N_RQD",   "rqd", "words",    16),
    ("MB_TERN",  "tern", "mem_base", 14), ("MB_DW",   "dw",  "mem_base", 10),
    ("MB_RQA",   "rqa",  "mem_base", 13), ("MB_RQD",  "rqd", "mem_base", 13),
    ("WB_TERN",  "tern", "word_bytes", 8), ("WB_DW",  "dw",  "word_bytes", 8),
    ("WB_RQA",   "rqa",  "word_bytes", 8), ("WB_RQD", "rqd", "word_bytes", 8),
):
    # concatenations are MSB-first, so block 0 must be written last
    L.append("localparam [%d*NBLK-1:0] %s = {%s};" % (w, name, ", ".join(reversed(
        ["%d'd%d" % (w, e[key][field]) for e in B]))))
io.open(os.path.join(HERE, "tb_wfetch_desc.vh"), "w", newline="\n").write("\n".join(L) + "\n")

print("tb_wfetch_ddr.hex   %d beats (%d bytes)" % (len(blob) // 16, len(blob)))
print("tb_wfetch_desc.vh   %d blocks" % len(B))
print("  words to be written per block, summed: tern %d  dw %d  rqa %d  rqd %d"
      % tuple(sum(e[k]["words"] for e in B) for k in ("tern", "dw", "rqa", "rqd")))

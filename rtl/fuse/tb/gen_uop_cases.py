# -*- coding: utf-8 -*-
"""gen_uop_cases.py -- the seventeen blocks' micro-op inputs and the expected
base fields, for tb_uop_enc.

Reads:   golden/p1_golden/vec/p1_manifest.json, fuse_weights_index.json, fuse_weights.bin,
         b??_wte.bin, b??_wtp.bin (from golden/p1_golden/run_p1.sh and tools/pack_fuse_weights.py);
         tools/tailpack.py (and so tools/gather_cost.json, twn_fuse_array.v,
         twn_uop_enc.v);
         the requant memory images <tb_p4_block[_bNN]>_rqem0.hex / _rqpm0.hex that
         gen_p4_block.py writes. When they are not next to this file they are
         generated by running gen_p4_block.py per block into a temporary directory;
         --p4dir DIR points at an existing set instead.
Writes:  tb_uop_cases.vh next to this file
Run:     python rtl/fuse/tb/gen_uop_cases.py [--p4dir DIR]

The expected bases are computed by routes that do not pass through twn_uop_enc,
so the gate is not the encoder agreeing with itself:
  region base         fuse_weights_index.json `mem_base` (the field gen_desctab.py
                      puts in descriptor words 9 and 10)
  expand ternary run  size of b??_wte.bin / 32
  project ternary base  located in the packed blob: the block's tern region must
                      start with b??_wte.bin and b??_wtp.bin is searched for after
                      it word by word; the offset found is the expected base
  expand requant run  line count of the gate's requant memory image, asserted
                      equal to ceil(c / OCMAX) (dense layout)
  pack0_e / pack0_p   tailpack.pack0_for(), as gen_desctab.py and
                      pack_fuse_weights.py call it; asserted against the blob (a
                      stage has appended words exactly when its pack0 is non-zero)
  msg_e / msg_p       the manifest
The project requant base is also read from the packer's index (rqbp_idx) and
asserted equal to the image-derived one; UC_RQBP_IDX is emitted so tb_uop_enc
checks the encoder against the packer's number directly.

Every block is covered because the varying fields are the ones that break: pack
reaches 4, the project's segment count reaches 8 (hence the minus-one encoding),
and the depthwise stride halves the row width for some blocks.
"""
import io, json, os, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
VEC = os.path.join(ROOT, "golden", "p1_golden", "vec")

man = json.load(io.open(os.path.join(VEC, "p1_manifest.json"), encoding="utf-8"))
idx = json.load(io.open(os.path.join(VEC, "fuse_weights_index.json"), encoding="utf-8"))
B, I = man["blocks"], idx["blocks"]
assert len(B) == len(I), (len(B), len(I))
BLOB = open(os.path.join(VEC, "fuse_weights.bin"), "rb").read()

# the same module gen_desctab.py and pack_fuse_weights.py ask which stages
# tail-pack: the encoder's inputs are what the descriptor carries
_TOOLS = os.path.join(ROOT, "tools")
sys.path.insert(0, os.path.normpath(_TOOLS))
import tailpack as _tp

TERN_WORD_BYTES = 32          # twn_wmem's mem_tern is 256 bits
OCMAX           = 4           # requant entries per 256-bit group: 4 x (18+40+6)
lg = {1: 0, 2: 1, 4: 2, 8: 3}


def nlines(path):
    with io.open(path) as f:
        return sum(1 for ln in f if ln.strip())


def tbstem(bi):
    """gen_p4_block.py names block 1's files without the suffix."""
    return "tb_p4_block" if bi == 1 else "tb_p4_block_b%02d" % bi


# ---- where the P5 gate's requant memory images are ---------------------------
P4DIR, _tmp = None, None
if "--p4dir" in sys.argv:
    P4DIR = sys.argv[sys.argv.index("--p4dir") + 1]
elif all(os.path.exists(os.path.join(HERE, tbstem(b["block"]) + "_rqem0.hex")) for b in B):
    P4DIR = HERE
else:
    _tmp = P4DIR = tempfile.mkdtemp(prefix="gen_uop_p4_")
    for b in B:
        bi = b["block"]
        r = subprocess.run([sys.executable, os.path.join(HERE, "gen_p4_block.py"),
                            "--block", str(bi),
                            "-o", os.path.join(P4DIR, tbstem(bi) + ".v")],
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        if r.returncode != 0:
            raise SystemExit("gen_p4_block.py --block %d failed:\n%s"
                             % (bi, r.stdout.decode("utf-8", "replace")))
    print("requant images: generated by gen_p4_block.py into a temporary directory")


rows = []
for b, e in zip(B, I):
    bi = b["block"]
    assert e["block"] == bi, (bi, e["block"])
    c_mid, c_out = b["mid"]["c"], b["out"]["c"]
    pk_e, pk_p = b["pack_e"]["pack"], b["pack_p"]["pack"]

    assert b["relu"]["e"] == 1, "block %d expand relu is not 1" % bi
    assert b["relu"]["p"] == 0, "block %d project relu is not 0" % bi
    assert c_mid % pk_e == 0, bi
    assert c_out % pk_p == 0, bi

    # The passes multiply in: p1_manifest.json's n_seg_* is ceil(n_eff/128) alone;
    # block 0's stem issues three kernel-row passes per output row, as in
    # gen_p4_block.py. The size assertion below catches a generator that copies
    # the raw field.
    nseg_e = b["n_seg_e"] * b["pack_e"]["passes"]
    nseg_p = b["n_seg_p"] * b["pack_p"]["passes"]
    assert 1 <= nseg_e <= 8 and 1 <= nseg_p <= 8, (bi, nseg_e, nseg_p)

    n_ocg_e, n_ocg_p = c_mid // pk_e, c_out // pk_p

    # ---- the expand's ternary run, measured off the golden file ----
    wte = os.path.getsize(os.path.join(VEC, "b%02d_wte.bin" % bi))
    wtp = os.path.getsize(os.path.join(VEC, "b%02d_wtp.bin" % bi))
    assert wte % TERN_WORD_BYTES == 0 and wtp % TERN_WORD_BYTES == 0, (bi, wte, wtp)
    we_words, wp_words = wte // TERN_WORD_BYTES, wtp // TERN_WORD_BYTES
    # the array reads exactly one word per (output-channel group, segment)
    assert we_words == n_ocg_e * nseg_e, (
        "block %d: bNN_wte.bin is %d words but the array walks n_ocg_e x n_seg_e "
        "= %d x %d = %d. If this is block 0, gen_desctab.py is handing the "
        "encoder the manifest's raw n_seg_e instead of n_seg_e x passes."
        % (bi, we_words, n_ocg_e, nseg_e, n_ocg_e * nseg_e))
    assert wp_words == n_ocg_p * nseg_p, (
        "block %d: bNN_wtp.bin is %d words but the array walks %d x %d = %d"
        % (bi, wp_words, n_ocg_p, nseg_p, n_ocg_p * nseg_p))
    # ---- where the project's run starts: found in the packed blob ----
    # The region is expand, expand's appended tail (if tail-packed), project,
    # project's appended tail.
    t_off, t_words = e["tern"]["off"], e["tern"]["words"]
    assert e["tern"]["word_bytes"] == TERN_WORD_BYTES, (bi, e["tern"]["word_bytes"])
    region = BLOB[t_off:t_off + t_words * TERN_WORD_BYTES]
    assert len(region) == t_words * TERN_WORD_BYTES, (bi, "region runs past the blob")
    wte_b = open(os.path.join(VEC, "b%02d_wte.bin" % bi), "rb").read()
    wtp_b = open(os.path.join(VEC, "b%02d_wtp.bin" % bi), "rb").read()
    assert region[:len(wte_b)] == wte_b, (
        "block %d: the packed tern region does not start with bNN_wte.bin" % bi)
    k = len(wte_b)
    while k + len(wtp_b) <= len(region) and region[k:k + len(wtp_b)] != wtp_b:
        k += TERN_WORD_BYTES
    assert k + len(wtp_b) <= len(region), (
        "block %d: bNN_wtp.bin was not found in the packed tern region" % bi)
    apx_e = (k - len(wte_b)) // TERN_WORD_BYTES         # expand's appended words
    apx_p = (len(region) - k - len(wtp_b)) // TERN_WORD_BYTES

    # ---- the tail fields: the encoder's inputs, as the descriptor carries them
    tg = _tp.gather_cost()["blocks"][str(bi)]["t_gather"]
    p0e = _tp.pack0_for(b["pack_e"]["n_eff"], c_mid, lg[pk_e], t_gather=tg)
    p0p = _tp.pack0_for(b["pack_p"]["n_eff"], c_out, lg[pk_p], t_gather=tg)
    assert (apx_e > 0) == (p0e != 0), (
        "block %d: the expand has %d appended words in the blob but pack0_e is %d"
        % (bi, apx_e, p0e))
    assert (apx_p > 0) == (p0p != 0), (
        "block %d: the project has %d appended words in the blob but pack0_p is %d"
        % (bi, apx_p, p0p))
    msg_e = 1 if b.get("msg_e") else 0
    msg_p = 1 if b.get("msg_p") else 0

    # ---- the requant runs, measured off the gate's memory image ----
    # Dense: the array reads OCMAX = 4 channels per 256-bit group (rq_addr =
    # rq_base + (ocg*pack >> 2), lanes rotated by (ocg*pack) & 3), so a stage
    # occupies ceil(c / OCMAX) groups whatever its pack.
    stem = tbstem(bi)
    ge = nlines(os.path.join(P4DIR, stem + "_rqem0.hex"))
    gp = nlines(os.path.join(P4DIR, stem + "_rqpm0.hex"))
    dense_e = (c_mid + OCMAX - 1) // OCMAX
    dense_p = (c_out + OCMAX - 1) // OCMAX
    assert ge == dense_e, (
        "block %d: the bit-exact gate's expand requant memory holds %d groups; "
        "dense is ceil(c_mid %d / %d) = %d, per-ocg would be %d. If it is the "
        "latter, gen_p4_block.py is still writing the old layout."
        % (bi, ge, c_mid, OCMAX, dense_e, n_ocg_e))
    assert gp == dense_p, (
        "block %d: the bit-exact gate's project requant memory holds %d groups; "
        "dense is ceil(c_out %d / %d) = %d, per-ocg would be %d"
        % (bi, gp, c_out, OCMAX, dense_p, n_ocg_p))

    mb_tern, mb_rqa = e["tern"]["mem_base"], e["rqa"]["mem_base"]
    rows.append(dict(
        b=b, bi=bi, c_mid=c_mid, c_out=c_out, pk_e=pk_e, pk_p=pk_p,
        nseg_e=nseg_e, nseg_p=nseg_p, n_ocg_e=n_ocg_e, n_ocg_p=n_ocg_p,
        mb_tern=mb_tern, mb_rqa=mb_rqa,
        wbe=mb_tern, wbp=mb_tern + k // TERN_WORD_BYTES,
        p0e=p0e, p0p=p0p, msg_e=msg_e, msg_p=msg_p, apx_e=apx_e, apx_p=apx_p,
        rqbe=mb_rqa, rqbp=mb_rqa + ge,
        rqbp_idx=mb_rqa + e["rqa"]["project_group"],
        rqa_words=e["rqa"]["words"], tern_words=e["tern"]["words"],
        raw_nseg_e=b["n_seg_e"]))

# ---- every base fits its field (a silent truncation reads the wrong weights) ----
CAPS = idx["mem_words"]
for r in rows:
    for name, val, bits in (("mb_tern", r["mb_tern"], 14), ("mb_rqa", r["mb_rqa"], 13),
                            ("w_base(expand)",  r["wbe"],  18),
                            ("w_base(project)", r["wbp"],  18),
                            ("rq_base(expand)",  r["rqbe"], 13),
                            ("rq_base(project)", r["rqbp"], 13)):
        assert 0 <= val < (1 << bits), \
            "block %d: %s = %d does not fit %d bits" % (r["bi"], name, val, bits)

L = ["// generated by gen_uop_cases.py -- do not edit",
     "localparam integer NCASE = %d;" % len(rows)]
for name, w, f in (("UC_BLK", 8,  lambda r: r["bi"]),
                   ("UC_CIN", 16, lambda r: r["b"]["in"]["c"]),
                   ("UC_HIN", 16, lambda r: r["b"]["in"]["h"]),
                   ("UC_CMID", 16, lambda r: r["c_mid"]),
                   ("UC_COUT", 16, lambda r: r["c_out"]),
                   ("UC_WIN", 16, lambda r: r["b"]["in"]["w"]),
                   ("UC_SDW", 1,  lambda r: 1 if r["b"]["dw_stride"] == 2 else 0),
                   # the stem halves the width in the expand, not the depthwise,
                   # so it is a separate flag from the stride (block 0 only)
                   ("UC_STEM", 1, lambda r: 1 if r["b"].get("stem") else 0),
                   ("UC_PKE", 4,  lambda r: lg[r["pk_e"]]),
                   ("UC_PKP", 4,  lambda r: lg[r["pk_p"]]),
                   ("UC_NSE", 4,  lambda r: r["nseg_e"]),
                   ("UC_NSP", 4,  lambda r: r["nseg_p"]),
                   # the two DUT inputs
                   ("UC_MBT", 16, lambda r: r["mb_tern"]),
                   ("UC_MBR", 16, lambda r: r["mb_rqa"]),
                   # the tail-packing and mixed-segment inputs
                   ("UC_P0E", 2, lambda r: r["p0e"]),
                   ("UC_P0P", 2, lambda r: r["p0p"]),
                   ("UC_MSGE", 1, lambda r: r["msg_e"]),
                   ("UC_MSGP", 1, lambda r: r["msg_p"]),
                   # the four expected bases, plus the packer's number
                   ("UC_WBE",  18, lambda r: r["wbe"]),
                   ("UC_WBP",  18, lambda r: r["wbp"]),
                   ("UC_RQBE", 13, lambda r: r["rqbe"]),
                   ("UC_RQBP", 13, lambda r: r["rqbp"]),
                   ("UC_RQBP_IDX", 13, lambda r: r["rqbp_idx"])):
    L.append("localparam [%d*NCASE-1:0] %s = {%s};" % (
        w, name, ", ".join("%d'd%d" % (w, f(r)) for r in reversed(rows))))
io.open(os.path.join(HERE, "tb_uop_cases.vh"), "w", newline="\n").write("\n".join(L) + "\n")

if _tmp:
    shutil.rmtree(_tmp, ignore_errors=True)

print("%d blocks; relu and otype constants asserted against the manifest" % len(rows))
print("  tail packing: expand pack0 on blocks %s (appended words %s), project pack0 on blocks %s"
      % ([r["bi"] for r in rows if r["p0e"]], [r["apx_e"] for r in rows if r["p0e"]],
         [r["bi"] for r in rows if r["p0p"]]))
print("  mixed-segment rotation: expand on blocks %s, project on blocks %s"
      % ([r["bi"] for r in rows if r["msg_e"]], [r["bi"] for r in rows if r["msg_p"]]))
print("  project segment counts: %s" % sorted({r["nseg_p"] for r in rows}))
print("  pack factors: expand %s  project %s"
      % (sorted({r["pk_e"] for r in rows}), sorted({r["pk_p"] for r in rows})))
print("  every base fits its field; maxima against the caps in fuse_weights_index.json:")
print("    w_base  max %5d   (18-bit field, TERN_WORDS = %d, mb_tern is 14 bits)"
      % (max(r["wbp"] for r in rows), CAPS["tern"]))
print("    rq_base max %5d   (13-bit field, RQA_WORDS  = %d)"
      % (max(max(r["rqbp"], r["rqbe"]) for r in rows), CAPS["rqa"]))

stem_fix = [r for r in rows if r["nseg_e"] != r["raw_nseg_e"]]
if stem_fix:
    print("\n  gen_desctab.py MUST multiply the passes in -- word 12's n_seg_e:")
    for r in stem_fix:
        print("    block %d: manifest n_seg_e %d x passes %d = %d. At %d the project's "
              "weight base is %d instead of %d."
              % (r["bi"], r["raw_nseg_e"], r["b"]["pack_e"]["passes"], r["nseg_e"],
                 r["raw_nseg_e"], r["mb_tern"] + r["n_ocg_e"] * r["raw_nseg_e"], r["wbp"]))

# ---- the packer's index and the gate's image must give the same layout ----
# Two routes to the project stage's requant base, neither through twn_uop_enc:
# `rqbp` counts the gate's memory image, `rqbp_idx` reads the packer's index.
# An assertion, because tb_p4_block addresses each stage's requant memory from
# zero and so exercises no base at all.
bad = [r for r in rows if r["rqbp"] != r["rqbp_idx"]]
if bad:
    msg = ["pack_fuse_weights.py's RQA grouping disagrees with the requant "
           "memory image on %d of %d blocks." % (len(bad), len(rows)),
           "  blk  pack_e  c_mid  image groups  packer groups   rq_base(project)"]
    for r in bad:
        msg.append("  %3d %6d %6d %13d %14d   %d vs %d"
                   % (r["bi"], r["pk_e"], r["c_mid"],
                      r["rqbp"] - r["mb_rqa"], r["rqbp_idx"] - r["mb_rqa"],
                      r["rqbp"], r["rqbp_idx"]))
    msg.append("The array reads OCMAX = %d channels per group, so both should be "
               "ceil(c_mid / %d)." % (OCMAX, OCMAX))
    msg.append("If the image column is c_mid/pack_e, gen_p4_block.py has been "
               "reverted to the old per-output-channel-group layout.")
    raise AssertionError("\n".join(msg))
print("  the packer's index and the gate's memory image agree on all %d blocks' "
      "requant layout" % len(rows))
print("    dense groups: %d total, worst block %d, worst adjacent pair %d, "
      "RQA_WORDS = %d"
      % (sum(r["rqa_words"] for r in rows),
         max(r["rqa_words"] for r in rows),
         max(rows[i]["rqa_words"] + rows[(i + 1) % len(rows)]["rqa_words"]
             for i in range(len(rows))),
         CAPS["rqa"]))

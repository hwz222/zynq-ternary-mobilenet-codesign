# -*- coding: utf-8 -*-
"""gen_fuse_dp.py -- emit a self-contained testbench for the datapath
(twn_fuse_select + twn_fuse_tree) driven from the P1 golden vectors.

Checks the lane replication network (lane k sees x[k & (L-1)], L = 128/pack) and
the one's-complement correction at the tap (a missing correction is off by exactly
the number of -1 weights in the tap's lanes). The reference accumulators are
computed here from the same packed weight word the testbench drives, decoded
independently.

Reads:   golden/p1_golden/vec/p1_manifest.json, b??_in / b??_d .bin (activations),
         b??_wte / b??_wtp .bin (weights); from golden/p1_golden/run_p1.sh
Writes:  the testbench .v (-o, default tb_fuse_dp_b<NN><e|p>_s<SEG>.v in the
         current directory)

  python gen_fuse_dp.py <block> <e|p> [--row N] [--seg N] [-o out.v]
  python gen_fuse_dp.py --sweep            one case per distinct packing factor,
                                           plus one cross-segment case
"""
import io, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VEC  = os.path.abspath(os.path.join(HERE, "..", "..", "..", "golden", "p1_golden", "vec"))
MAN  = os.path.join(VEC, "p1_manifest.json")
LANES, PIX = 128, 4


def load():
    if not os.path.exists(MAN):
        sys.exit("no P1 manifest at %s -- run golden/p1_golden/run_p1.sh first" % MAN)
    return json.load(io.open(MAN, encoding="utf-8"))


def i8(b):
    return [x - 256 if x > 127 else x for x in b]


def emit(man, bi, stage, row, seg, out):
    b = man["blocks"][bi]
    pk = b["pack_e"] if stage == "e" else b["pack_p"]
    n_eff, npass, pack = pk["n_eff"], pk["passes"], pk["pack"]
    words = pk["words_per_group"]
    L = 128 // pack if pack > 1 else ((n_eff + 127) // 128) * 128
    n_seg = (n_eff + 127) // 128
    if seg >= n_seg:
        sys.exit("block %d %s has only %d segment(s)" % (bi, stage, n_seg))

    if stage == "e":
        src = "b%02d_in" % bi
        sc, sh_, sw = b["in"]["c"], b["in"]["h"], b["in"]["w"]
        oc_tot, ow, stride = b["mid"]["c"], b["mid"]["w"], b["expand_stride"]
        wt = "b%02d_wte" % bi
    else:
        src = "b%02d_d" % bi
        sc, sh_, sw = b["mid"]["c"], b["out"]["h"], b["out"]["w"]
        oc_tot, ow, stride = b["out"]["c"], b["out"]["w"], 1
        wt = "b%02d_wtp" % bi

    X = i8(open(os.path.join(VEC, src + ".bin"), "rb").read())
    W = open(os.path.join(VEC, wt + ".bin"), "rb").read()
    ngrp = (oc_tot + pack - 1) // pack
    grp = 0                                    # the first output-channel group
    ps = 0                                     # the first kernel-row pass
    widx = (ps * ngrp + grp) * words + seg
    word = W[widx * 32:(widx + 1) * 32]
    if len(word) < 32:
        sys.exit("weight word %d out of range in %s" % (widx, wt))

    # --- decode the word back to per-lane ternary
    code = [(word[k >> 2] >> ((k & 3) * 2)) & 3 for k in range(LANES)]
    tern = [0 if c == 0 else (1 if c == 1 else -1) for c in code]

    # --- activations: channels [seg*128, seg*128+128) at lanes 0..127, per pixel
    iy = row * stride
    act = []
    for p in range(PIX):
        ix = p * stride
        lane = []
        for k in range(LANES):
            c = seg * 128 + k
            v = X[(c * sh_ + iy) * sw + ix] if (c < sc and iy < sh_ and ix < sw) else 0
            lane.append(v)
        act.append(lane)

    # --- reference: lane j*L+k sees x[k], so psum[j] = sum_k tern[j*L+k] * x[k]
    ref = []
    for j in range(8):
        row_ = []
        for p in range(PIX):
            if j >= pack:
                row_.append(0)
                continue
            # at pack 1 a channel's n_eff taps span several words; this word holds
            # one segment's 128 lanes, so the reference sums exactly those.
            Lref = min(L, LANES)
            s = 0
            for k in range(Lref):
                s += tern[j * Lref + k] * act[p][k]
            row_.append(s)
        ref.append(row_)
    # A case whose expected sums are all zero passes for any datapath; refuse it.
    if not any(v for r_ in ref[:pack] for v in r_):
        sys.exit("block %d %s row %d seg %d: every expected sum is zero -- this case "
                 "cannot fail; pick another row or stage" % (bi, stage, row, seg))

    nneg = sum(1 for t in tern if t < 0)
    packcode = {1: 0, 2: 1, 4: 2, 8: 3}[pack]

    def bits(vals, w):
        v = 0
        for k, a in enumerate(vals):
            v |= (a & ((1 << w) - 1)) << (w * k)
        return v

    mod = os.path.splitext(os.path.basename(out))[0]
    Lst = []
    A = Lst.append
    A("// AUTO-GENERATED by rtl/fuse/tb/gen_fuse_dp.py from the P1 golden vectors -- do not edit.")
    A("// block %d, %s stage, output row %d, input segment %d of %d." % (bi, stage, row, seg, n_seg))
    A("// n_eff=%d  pack=%d  lane group L=%d  -1 weights in this word=%d" % (n_eff, pack, L, nneg))
    A("// The stimulus is the model's own activations and the model's own packed weights;")
    A("// the expected accumulators are decoded from the SAME word, independently.")
    A("`timescale 1ns/1ps")
    A("module %s;" % mod)
    A("  localparam integer LANES = %d, PIX = %d, OCMAX = 4;" % (LANES, PIX))
    A("  localparam [1:0]   PACK  = 2'd%d;   // pack %d, L = %d" % (packcode, pack, L))
    A("  reg clk = 0; always #2 clk = ~clk;")
    A("  reg ce = 1;")
    A("")
    A("  // activation word: channels %d..%d at lanes 0..127, one word per pixel"
      % (seg * 128, seg * 128 + 127))
    A("  wire [PIX*LANES*8-1:0] act_word = {")
    for p in reversed(range(PIX)):
        A("    %d'h%0256x%s" % (LANES * 8, bits(act[p], 8), "," if p else ""))
    A("  };")
    A("  wire [LANES*2-1:0] w_code = %d'h%064x;" % (LANES * 2, bits(code, 2)))
    A("")
    A("  wire [PIX*LANES*8-1:0] sel;")
    A("  wire [LANES-1:0]       neg;")
    # msg, seg and tag_i are tied off explicitly: an unconnected input is z in
    # plain Verilog and would make lanes 96..127 read x.
    A("  twn_fuse_select #(.LANES(LANES), .PIX(PIX), .OCMAX(OCMAX)) u_sel (")
    A("    .clk(clk), .ce(ce), .pack(PACK), .msg(1'b0), .seg(2'd0),")
    A("    .act_word(act_word), .w_code(w_code), .tag_i({24{1'b0}}),")
    A("    .sel_q(sel), .neg_q(neg), .tag_q());")
    A("")
    # OCMAX is the shipped 4 (twn_fuse_top.v).
    A("  wire [OCMAX*32-1:0] psum [0:PIX-1];")
    A("  genvar p;")
    A("  generate for (p = 0; p < PIX; p = p + 1) begin : G_TREE")
    A("    twn_fuse_tree #(.LANES(LANES), .OCMAX(OCMAX)) u_tree (")
    A("      .clk(clk), .ce(ce), .pack(PACK), .tag_i({24{1'b0}}),")
    A("      .sel(sel[p*LANES*8 +: LANES*8]), .neg(neg), .psum(psum[p]), .tag_o(), .tag_rq());")
    A("  end endgenerate")
    A("")
    A("  integer errs = 0; integer j, q;")
    A("  reg signed [31:0] expect [0:7][0:PIX-1];")
    A("  initial begin")
    for j in range(8):
        for p in range(PIX):
            A("    expect[%d][%d] = %s32'sd%d;" % (j, p, "-" if ref[j][p] < 0 else " ", abs(ref[j][p])))
    A("  end")
    A("")
    A("  initial begin")
    A("    // twn_fuse_select is one register deep, twn_fuse_tree is four; the")
    A("    // stimulus is held constant, so waiting out the whole pipeline is enough.")
    A("    repeat (8) @(posedge clk); #1;")
    A("    if (neg !== %d'h%032x) begin" % (LANES, bits([1 if t < 0 else 0 for t in tern], 1)))
    A("      $display(\"FAIL neg[] mismatch\"); errs = errs + 1;")
    A("    end")
    A("    for (j = 0; j < %d; j = j + 1)" % pack)
    A("      for (q = 0; q < PIX; q = q + 1)")
    A("        if ($signed(psum[q][j*32 +: 32]) !== expect[j][q]) begin")
    A("          $display(\"FAIL oc-in-group %0d pixel %0d: got %0d expected %0d\",")
    A("                   j, q, $signed(psum[q][j*32 +: 32]), expect[j][q]);")
    A("          errs = errs + 1;")
    A("        end")
    A("    if (errs == 0)")
    A("      $display(\"%%m PASS -- block %d %s row %d seg %d, pack %d, %d live outputs x %d pixels, %d negative weights corrected\","
      % (bi, stage, row, seg, pack, pack, PIX, nneg))
    A("               );")
    A("    else $display(\"%m FAIL -- %0d mismatches\", errs);")
    A("    $finish;")
    A("  end")
    A("endmodule")
    io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(Lst) + "\n")
    return out, pack, nneg


if __name__ == "__main__":
    man = load()
    a = sys.argv[1:]
    if a and a[0] == "--sweep":
        # one case per distinct packing factor, plus a cross-segment case
        want, cases = {}, []
        for i, b in enumerate(man["blocks"]):
            for st in ("e", "p"):
                # The stem's expand is not a 1x1 (lanes hold 3 channels x 3 kernel
                # columns), which this generator does not lay out; it is covered by
                # tb_act_gather and gen_fuse_array.py.
                if b["stem"] and st == "e":
                    continue
                pk = b["pack_e"] if st == "e" else b["pack_p"]
                if pk["pack"] not in want:
                    want[pk["pack"]] = (i, st, 0)
                if (pk["n_eff"] + 127) // 128 > 1 and "seg" not in want:
                    want["seg"] = (i, st, 1)
        for key, (i, st, sg) in sorted(want.items(), key=lambda kv: str(kv[0])):
            o = "tb_fuse_dp_b%02d%s_s%d.v" % (i, st, sg)
            f, pack, nneg = emit(man, i, st, 0, sg, o)
            cases.append(o)
            print("wrote %-28s block %2d %s seg %d  pack %d  %3d negative weights"
                  % (f, i, st, sg, pack, nneg))
        print("\n%d cases" % len(cases))
    else:
        bi, st = int(a[0]), a[1]
        row = int(a[a.index("--row") + 1]) if "--row" in a else 0
        seg = int(a[a.index("--seg") + 1]) if "--seg" in a else 0
        out = a[a.index("-o") + 1] if "-o" in a else "tb_fuse_dp_b%02d%s_s%d.v" % (bi, st, seg)
        f, pack, nneg = emit(man, bi, st, row, seg, out)
        print("wrote %s (pack %d, %d negative weights)" % (f, pack, nneg))

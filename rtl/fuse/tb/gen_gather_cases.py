# -*- coding: utf-8 -*-
"""gen_gather_cases.py -- the cases tb_act_gather.v sweeps.

Reads:   golden/p1_golden/vec/p1_manifest.json, b00_in.bin, b00_wte.bin, b00_rqe.bin, b00_e.bin
         (from golden/p1_golden/run_p1.sh)
Writes (next to this file): tb_act_gather_cases.vh, tb_act_gather_stem_row.hex,
         tb_act_gather_stem_act.hex
Run:     python rtl/fuse/tb/gen_gather_cases.py

1x1 sweep: the distinct (C, W) pairs of every block's expand and project, taken from
the manifest because the gather's behaviour depends on C (C < LANES needs zero fill,
C > LANES needs more than one chunk, C against the row-buffer word size decides how
often a run straddles two words).

Stem cases: block 0's 3x3 stride-2 stem is replayed from b00_in.bin's real rows. The
expected 4096-bit activation words are checked, before anything is written, by
convolving them with b00_wte.bin and requantising with b00_rqe.bin; the result must
equal b00_e.bin for the emitted rows. STEM_ROWS assumes block 0 has 128 output rows.
"""
import io, json, os, struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
VEC = os.path.join(ROOT, "golden", "p1_golden", "vec")

man = json.load(io.open(os.path.join(VEC, "p1_manifest.json"), encoding="utf-8"))

cases = []
for b in man["blocks"]:
    cases.append((b["in"]["c"], b["in"]["w"], b["block"], 0))      # expand reads the input
    cases.append((b["mid"]["c"], b["out"]["w"], b["block"], 1))    # project reads the dw output
seen, uniq = set(), []
for c, w, bi, st in cases:
    if (c, w) not in seen:
        seen.add((c, w))
        uniq.append((c, w, bi, st))

L = ["// generated by gen_gather_cases.py -- do not edit",
     "localparam integer NCASE = %d;" % len(uniq)]
for name, i in (("GC_C", 0), ("GC_W", 1)):
    L.append("localparam [16*NCASE-1:0] %s = {%s};" % (
        name, ", ".join("16'd%d" % t[i] for t in reversed(uniq))))

# ===================== block 0's stem =====================================
B0 = man["blocks"][0]
IH, IW, IC = B0["in"]["h"], B0["in"]["w"], B0["in"]["c"]
OW = B0["mid"]["w"]
PIX, LANES, WB = 4, 128, 128            # pixels per word, lanes, row-buffer bytes
NEFF = IC * 3                           # 9 taps per pass
ROWW = 8                                # row-buffer words per case: the row plus
                                        # guard words the last pixel's `target` reads
NXG = OW // PIX

# the input, CHW on disk, HWC in DDR
_chw = io.open(os.path.join(VEC, "b00_in.bin"), "rb").read()
assert len(_chw) == IC * IH * IW, len(_chw)
hwc = bytearray(IH * IW * IC)
for c in range(IC):
    for y in range(IH):
        b = (c * IH + y) * IW
        for x in range(IW):
            hwc[(y * IW + x) * IC + c] = _chw[b + x]

# lane k = c*3 + kx takes the run byte at kx*3 + c (the 3x3 transpose, its own
# inverse), written as the source index per lane.
SRC = [(k % 3) * 3 + k // 3 for k in range(NEFF)]

# Four output rows, all three passes. The gather is handed bytes, so what these
# cover is the pad cases:
#   e_row 0    pass 0 is input row -1 (top pad)
#   e_row 1    interior
#   e_row 63   interior, a different part of the image
#   e_row 127  the last output row (bottom edge)
# Every case sweeps all pixel groups, so the left pad, the last pixel's `target`
# one word past the row, and runs straddling two row-buffer words are in all of them.
STEM_ROWS = [0, 1, 63, 127]
scase, srow_words, sact_words, stem_lanes = [], [], [], {}
for y in STEM_ROWS:
    for seg in range(3):
        iy = 2 * y - 1 + seg
        pad = 1 if (iy < 0 or iy >= IH) else 0
        scase.append((y, seg, pad))
        # ---- the row buffer's contents for this pass ----
        # The pad pass is fed a real row on purpose: a zero-filled buffer would let
        # a gather that ignored stem_pad_row match. twn_fuse_top clamps the row -1
        # read to row 0, so the buffer holds input row 0's bytes and only the run
        # length makes the word zero.
        rb = bytearray(ROWW * WB)
        src = 0 if pad else iy
        rb[0:IW * IC] = hwc[src * IW * IC:(src + 1) * IW * IC]
        for i in range(IW * IC, ROWW * WB):
            rb[i] = 0xA5                # defined, and not a value the run wants
        for i in range(ROWW):
            srow_words.append(int.from_bytes(bytes(rb[i * WB:(i + 1) * WB]), "little"))
        # ---- what the array must be handed ----
        # SRC[k] is lane k's offset into the nine-byte run, ordered kx*3 + c from
        # column 2x - 1: lane k is column 2x - 1 + SRC[k]//3, colour SRC[k]%3.
        lanes = []
        for x in range(OW):
            v = [0] * NEFF
            if not pad:
                for k in range(NEFF):
                    ix = 2 * x - 1 + SRC[k] // 3
                    if 0 <= ix < IW:
                        v[k] = hwc[(iy * IW + ix) * IC + SRC[k] % 3]
            lanes.append(v)
        stem_lanes[(y, seg)] = lanes
        for xg in range(NXG):
            word = 0
            for p in range(PIX):
                for k, a in enumerate(lanes[xg * PIX + p]):
                    word |= a << (8 * (p * LANES + k))
            sact_words.append(word)

# ---- check the vectors against b00_e.bin before writing them ----
# The words come from a lane table in this file, so alone they would be this
# file's opinion; they must reproduce b00_e.bin through the weights and requant.
def _s8(b):
    return [x - 256 if x > 127 else x for x in b]


_OC, _PK, _NPASS = B0["mid"]["c"], B0["pack_e"]["pack"], B0["pack_e"]["passes"]
_L, _NGRP = 128 // _PK, _OC // _PK
_wte = io.open(os.path.join(VEC, "b00_wte.bin"), "rb").read()
_rqe = io.open(os.path.join(VEC, "b00_rqe.bin"), "rb").read()
_gold = _s8(io.open(os.path.join(VEC, "b00_e.bin"), "rb").read())
_m0 = list(struct.unpack("<%di" % _OC, _rqe[:4 * _OC]))
_bias = list(struct.unpack("<%dq" % _OC, _rqe[4 * _OC:12 * _OC]))
_sh = list(_rqe[12 * _OC:])
_lo, _hi = B0["clamp"]["e"]


def _w(g, ps, j, k):
    bit = ((g * _NPASS + ps) * 128 + j * _L + k) * 2
    code = (_wte[bit >> 3] >> (bit & 7)) & 3
    return 0 if code == 0 else (1 if code == 1 else -1)


_bad = 0
for _y in STEM_ROWS:
    _sl = [stem_lanes[(_y, _s)] for _s in range(3)]
    for _g in range(_NGRP):
        for _j in range(_PK):
            _oc = _g * _PK + _j
            _wt = [[_w(_g, _p, _j, _k) for _k in range(NEFF)] for _p in range(3)]
            for _x in range(OW):
                # the row buffer carries BYTES; the array reads them as int8
                _acc = sum(_wt[_p][_k] * (_sl[_p][_x][_k] - 256
                                          if _sl[_p][_x][_k] > 127 else _sl[_p][_x][_k])
                           for _p in range(3) for _k in range(NEFF) if _wt[_p][_k])
                _t = _acc * _m0[_oc] + _bias[_oc]
                _r = (_t + (1 << (_sh[_oc] - 1))) >> _sh[_oc] if _sh[_oc] else _t
                _r = _lo if _r < _lo else (_hi if _r > _hi else _r)
                if _r != _gold[(_oc * B0["mid"]["h"] + _y) * OW + _x]:
                    _bad += 1
if _bad:
    raise SystemExit("gen_gather_cases: the stem activation words do NOT reproduce "
                     "b00_e.bin -- %d of %d values wrong. No vectors written."
                     % (_bad, len(STEM_ROWS) * _OC * OW))
print("stem vectors verified: %d values of b00_e.bin reproduced from them"
      % (len(STEM_ROWS) * _OC * OW))

L.append("")
L.append("// ---- block 0's 3x3 stride-2 stem: %d (row, pass) cases x %d pixel groups ----"
         % (len(scase), NXG))
L.append("localparam integer NSTEM = %d;" % len(scase))
L.append("localparam integer STEM_ROWW = %d, STEM_NXG = %d, STEM_C = %d;" % (ROWW, NXG, IC))
for nm, i in (("ST_ROW", 0), ("ST_SEG", 1), ("ST_PAD", 2)):
    L.append("localparam [16*NSTEM-1:0] %s = {%s};" % (
        nm, ", ".join("16'd%d" % t[i] for t in reversed(scase))))
io.open(os.path.join(HERE, "tb_act_gather_cases.vh"), "w", newline="\n").write(
    "\n".join(L) + "\n")


def hexf(path, vals, bits):
    with io.open(path, "w", newline="\n") as f:
        for v in vals:
            f.write("%0*x\n" % (bits // 4, v))


hexf(os.path.join(HERE, "tb_act_gather_stem_row.hex"), srow_words, 1024)
hexf(os.path.join(HERE, "tb_act_gather_stem_act.hex"), sact_words, PIX * LANES * 8)

print("%d distinct (C, W) pairs from %d blocks x 2 stages" % (len(uniq), len(man["blocks"])))
for c, w, bi, st in uniq:
    print("   C %4d  W %4d   first seen: block %2d %s" % (
        c, w, bi, "expand" if st == 0 else "project"))
print("stem: %d cases, %d row words, %d activation words" % (
    len(scase), len(srow_words), len(sact_words)))
for y, seg, pad in scase:
    print("   e_row %3d  pass %d -> input row %4d %s" % (
        y, seg, 2 * y - 1 + seg, "(PAD, whole word zero)" if pad else ""))

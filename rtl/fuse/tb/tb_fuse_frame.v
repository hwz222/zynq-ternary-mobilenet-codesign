        $display("");
        $display("  twn_res_buf WRITE side: rows the loader completed, and the highest");
        $display("  w_word reached before a row end. w_word SATURATES at ROW_WORDS-1");
        $display("  (95), so a loader delivering more beats per row than the row has");
        $display("  words rewrites that row's LAST word -- which corrupts a row's TAIL.");
        $display("    blk  res   ld rows   max w_word   the row is N words");
        for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
            rp_c = FM_C_IN[bi*10 +: 10];
            rp_w = FM_W_IN[bi*9  +:  9];
            $display("    %3d %4s %9d %12d %13d", bi, FM_HAS_RES[bi] ? "yes" : "-",
                     rb_rows[bi], rb_maxw[bi], (rp_w * rp_c) >> 4);
        end

        // Floor: at least one block must be bit-exact. A frame with nothing
        // bit-exact must not pass whatever the chain rule excuses.
        if (n_pass == 0)
            fail("NOT ONE BLOCK IS BIT-EXACT. Whatever else this report says, the datapath is not computing -- a per-block line that reads 0 errors out of 0 compared bytes, or a chain rule that excuses every block below the first, must never add up to a pass.");
        checks = checks + 1;

        checks = checks + GI_NBLK;
        $display("");
        $display("  %0d of %0d blocks bit-exact", n_pass, GI_NBLK);
        $display("=== tb_fuse_frame: %0d checks, %0d errors, FRAME %0s ===",
                 checks, errors, (errors == 0) ? "PASS" : "FAIL");
        $finish;
    end

    // A hard stop, so a hang cannot run for ever. Not the normal exit: the loop
    // above ends on `done` or on RUN_CYCLES and then reports.
    initial begin
        #(RUN_CYCLES * 4 * 3);
        $display("=== tb_fuse_frame: WATCHDOG -- the run did not reach its own report ===");
        $finish;
    end


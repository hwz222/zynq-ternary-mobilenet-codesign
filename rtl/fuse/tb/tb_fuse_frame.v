    localparam integer RUN_CYCLES = `FUSE_FRAME_CYCLES;

    reg clk = 1'b0, rst = 1'b1;
    always #2 clk = ~clk;

    `include "tb_fuse_env.vh"

    integer checks = 0, errors = 0, nrep = 0;
    integer frame_done = 0;

    task fail;
        input string what;
        begin
            errors = errors + 1;
            if (nrep < 20) begin nrep = nrep + 1; $display("  FAIL: %0s", what); end
        end
    endtask

    `include "tb_fuse_dut.vh"

    // =====================================================================
    //  golden image
    //
    //  $readmemh leaves the array at X when the file is missing; the run
    //  section checks that word 0 is not X before any comparison.
    // =====================================================================
    reg [127:0] gold [0:GI_WORDS_TOTAL-1];
    integer gi_loaded = 0;

    // =====================================================================
    //  write scoreboard
    //
    //  AW gives the address once per burst, so it is carried forward beat by
    //  beat on W. Only INCR bursts are expected; others are counted (bad_burst).
    // =====================================================================
    reg [39:0]  wa;                 // address of the next W beat
    reg [8:0]   wbeats;             // beats left in the burst
    reg         wactive = 1'b0;
    reg [4:0]   wblk;               // the block that owns this burst

    integer bytes_ok  [0:GI_NBLK-1];
    integer bytes_bad [0:GI_NBLK-1];
    integer first_off [0:GI_NBLK-1];
    integer bytes_x   [0:GI_NBLK-1];
    // Wrong bytes by output row, pixel column and channel, per block. HB_C is
    // the widest block output (block 16: 320 channels).
    localparam integer HB_C = 320;
    integer wrong_y [0:GI_NBLK*256-1];
    integer wrong_x [0:GI_NBLK*256-1];
    integer wrong_c [0:GI_NBLK*HB_C-1];
    integer hz, hr, hx, hc, hi2, hn, hrow, hch, hb;
    // Write coverage over all of gold_out.hex: one counter per golden byte,
    // indexed as the golden is.
    reg [7:0] cov [0:GI_WORDS_TOTAL*16-1];
    integer c0, c1, c2, ci;
    // Bytes written past the block's own tensor but inside its slot. They have
    // no golden and are counted here instead of scored.
    integer off_over [0:GI_NBLK-1];
    // DDR rows are padded to 128 B (tools/gen_desctab.py pad_row); the golden
    // is dense. pad_bytes counts padding bytes, which are not scored.
    integer pad_bytes [0:GI_NBLK-1];
    // off_d is 40 bits wide because it is sliced [39:4] below; an integer
    // would give X in bits 39:32.
    integer row_p, row_r, wcol;
    reg [39:0] off_d;
    integer gi_b16, blk_bytes, hball, hbi;
    reg [7:0] first_got [0:GI_NBLK-1];
    reg [7:0] first_want[0:GI_NBLK-1];
    integer stray_writes = 0, wrong_slot = 0, bad_burst = 0, overlap_aw = 0;
`ifdef FUSE_FRAME_BB2HD
    // BB2HD: A_BB2HD[0] = 1 and OUT_PTR = FM_IN_PTR, so the last block must
    // write OUT_PTR + bb_par * 0x10000 and nothing else. Block 0's input
    // region is dead by block 16 and stands in for the head's input slots.
    // bb_par is 0 out of reset, 1 with FUSE_BB2HD_PAR1_INIT.
`ifdef FUSE_BB2HD_PAR1_INIT
    localparam [39:0] BB2HD_BASE = FM_IN_PTR + 40'h10000;
    localparam [31:0] BB2HD_PAR0 = 1;
`else
    localparam [39:0] BB2HD_BASE = FM_IN_PTR;
    localparam [31:0] BB2HD_PAR0 = 0;
`endif
    integer bb2hd_beats = 0;
`endif
    reg sb_hd;                      // this beat is the last block's, to the head slot

    integer bi, k;
    reg [39:0]  off;                // byte offset inside the slot
    reg [31:0]  gword;
    reg [7:0]   gb, db;
    reg [31:0]  tick = 0;

    initial begin
        for (ci = 0; ci < GI_WORDS_TOTAL*16; ci = ci + 1) cov[ci] = 8'd0;
        for (hi2 = 0; hi2 < GI_NBLK*256;  hi2 = hi2 + 1) begin
            wrong_y[hi2] = 0; wrong_x[hi2] = 0;
        end
        for (hi2 = 0; hi2 < GI_NBLK*HB_C; hi2 = hi2 + 1) wrong_c[hi2] = 0;
    end
    initial for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
        bytes_ok[bi] = 0; bytes_bad[bi] = 0; bytes_x[bi] = 0; first_off[bi] = -1;
        first_got[bi] = 8'd0; first_want[bi] = 8'd0; off_over[bi] = 0;
        pad_bytes[bi] = 0;
    end

    always @(posedge clk) if (!rst) begin
        tick <= tick + 32'd1;

        if (a_awvalid && a_awready) begin
            // Assumes one write burst outstanding at a time (twn_act_wr issues
            // one burst per row request). A second AW before the previous
            // burst's W beats finish would corrupt wa/wblk, so it is counted.
            if (wactive && wbeats != 9'd0) begin
                overlap_aw = overlap_aw + 1;
                if (overlap_aw < 3)
                    $display("  a second write burst was accepted with %0d beats of the previous one outstanding -- this scoreboard cannot score that", wbeats);
            end
            wa      <= a_awaddr;
            wbeats  <= {1'b0, a_awlen} + 9'd1;
            wactive <= 1'b1;
            wblk    <= DUT.blk;
            if (a_awburst !== 2'b01) begin
                bad_burst = bad_burst + 1;
                if (bad_burst < 3)
                    $display("  write burst at %010h is burst type %0d, not INCR",
                             a_awaddr, a_awburst);
            end
        end

        if (a_wvalid && a_wready && wactive) begin
            // ---- which block's output, and where in it ----
            if (wa < FM_ACT_BASE) begin
                stray_writes = stray_writes + 1;
            end else if (wblk >= GI_NBLK) begin
                stray_writes = stray_writes + 1;
            end else begin
                sb_hd = 1'b0;
`ifdef FUSE_FRAME_BB2HD
                sb_hd = (wblk == GI_NBLK - 1);
`endif
                if (sb_hd) begin
`ifdef FUSE_FRAME_BB2HD
                    off = wa - BB2HD_BASE;
                    bb2hd_beats = bb2hd_beats + 1;
                    if (wa < BB2HD_BASE || wa >= BB2HD_BASE + 40'h10000) begin
                        wrong_slot = wrong_slot + 1;
                        if (wrong_slot < 3)
                            $display("  blk %0d wrote %010h, outside the head slot %010h..+0x10000",
                                     wblk, wa, BB2HD_BASE);
                    end
`endif
                end else
                off   = (wa - FM_ACT_BASE) & (FM_SLOT_STRIDE - 40'd1);
                // off indexes the padded tensor; re-lay it at the dense golden
                // row stride. Both strides are multiples of 16, so off_d keeps
                // the beat alignment and byte lane k indexes the golden word.
                row_p = FM_ROW_BYTES_OUT[wblk*16 +: 16];
                row_r = FM_ROW_REAL_OUT[wblk*16 +: 16];
                wcol  = off % row_p;
                off_d = (off / row_p) * row_r + wcol;
                gword = GI_WORD_BASE[wblk*32 +: 32] + off_d[39:4];
                // Widened through integers first: a self-determined multiply of
                // part-selects would truncate against the 40-bit off.
                gi_b16    = GI_WORD_BASE[wblk*32 +: 32];
                gi_b16    = gi_b16 * 16;
                blk_bytes = GI_WORDS[wblk*32 +: 32];
                blk_bytes = blk_bytes * 16;
                // the slot the descriptor says this block writes
                if (!sb_hd && ((wa - FM_ACT_BASE) >> FM_SLOT_LOG2) !==
                    {36'd0, GI_OUT_SLOT[wblk*4 +: 4]}) begin
                    wrong_slot = wrong_slot + 1;
                    if (wrong_slot < 3)
                        $display("  blk %0d wrote slot %0d, the descriptor says slot %0d",
                                 wblk, (wa - FM_ACT_BASE) >> FM_SLOT_LOG2,
                                 GI_OUT_SLOT[wblk*4 +: 4]);
                end
                // ---- sixteen bytes, only the enabled ones ----
                // Blocking assignments: the sixteen iterations accumulate into
                // the same counters and first_off, which must see each update.
                for (k = 0; k < 16; k = k + 1) begin
                    if (a_wstrb[k] && ((wcol + k) >= row_r)) begin
                        // Row padding: past the real row width, inside the
                        // stride. The design writes it; the golden has no byte.
                        pad_bytes[wblk] = pad_bytes[wblk] + 1;
                    end else if (a_wstrb[k] && ((off_d + k) >= blk_bytes)) begin
                        // Past this block's tensor, inside its slot: scoring it
                        // would compare against the next block's golden.
                        off_over[wblk] = off_over[wblk] + 1;
                    end else if (a_wstrb[k]) begin
                        db = a_wdata[k*8 +: 8];
                        gb = gold[gword][k*8 +: 8];
                        // off + k: off is the beat's 16-byte-aligned base, k the
                        // byte lane.
                        hball = off_d + k;
                        hball = gi_b16 + hball;
                        if (hball < GI_WORDS_TOTAL*16) cov[hball] = cov[hball] + 1;
                        if (db === gb) bytes_ok[wblk] = bytes_ok[wblk] + 1;
                        else begin
                            bytes_bad[wblk] = bytes_bad[wblk] + 1;
                            // X is an uninitialised read, counted apart from a
                            // wrong value.
                            if (^db === 1'bx) bytes_x[wblk] = bytes_x[wblk] + 1;
                            // Where the wrong byte is: (row, pixel, channel) of the
                            // block's HWC tensor.
                            begin
                                // Bytes per row, through an integer: the product of
                                // the 9- and 10-bit part-selects would truncate.
                                hrow = GI_W_OUT[wblk*9 +: 9];
                                hch  = GI_C_OUT[wblk*10 +: 10];
                                hrow = hrow * hch;                 // bytes per row
                                hb   = off + k;                    // THE BYTE, not the beat
                                hz  = hb / hrow;
                                hr  = hb % hrow;
                                hx  = hr / hch;
                                hc  = hr % hch;
                                // Own variable: hb is still live in hz/hr.
                                hbi = wblk;
                                if (hz < 256)  wrong_y[hbi*256 + hz]  = wrong_y[hbi*256 + hz] + 1;
                                if (hx < 256)  wrong_x[hbi*256 + hx]  = wrong_x[hbi*256 + hx] + 1;
                                if (hc < HB_C) wrong_c[hbi*HB_C + hc] = wrong_c[hbi*HB_C + hc] + 1;
                            end
                            if (first_off[wblk] < 0) begin
                                first_off[wblk]  = off + k;
                                first_got[wblk]  = db;
                                first_want[wblk] = gb;
                            end
                        end
                    end
                end
            end
            wa     <= wa + 40'd16;
            wbeats <= wbeats - 9'd1;
            if (a_wlast || wbeats == 9'd1) wactive <= 1'b0;
        end
    end

`ifdef FUSE_FRAME_STAGE
    // =====================================================================
    //  FUSE_FRAME_STAGE -- per-stage split of one block (block 0 by default:
    //  stem-expand 3x3 s2 3->32, depthwise 3x3, project 1x1 32->16)
    //
    //  The AXI scoreboard sees only the block output. This section snoops the
    //  write ports of RB_T1 (expand output), RB_C (depthwise output, RingC)
    //  and RB_OU (block output) and scores them as the scoreboard does, against
    //  images derived from the C reference (gold_bNN_e.hex, gold_bNN_d.hex).
    //
    //  Buffer layout (HWC, twn_act_gather's [x][c] order; wptr_r is the row):
    //      RB_T1  ROW_BITS 128, LANE_WR 0: byte y*(W*C) + wword*16 + k
    //      RB_C   ROW_BITS 1024, LANE_WR 1: the producer supplies the word
    //             index and a one-hot 8-byte lane:
    //             y*(W*C) + wr_word_i*128 + lane*8
    //      RB_OU  like RB_T1, at the block output's geometry
    //
    //  Sampled on the negedge: the write data, word index and row are then
    //  the values the buffer will use at the next posedge.
    //
    //  Instrument checks, reported before any result is used:
    //   1. every byte of each tensor is written exactly once and the write
    //      count equals the geometry;
    //   2. three probe bytes per image, at HWC offsets that differ from their
    //      CHW offsets;
    //   3. a control: the same arithmetic on RB_OU is reconciled with the AXI
    //      scoreboard's count for the same tensor.
    // =====================================================================
    reg [127:0] gold_e [0:SG_E_WORDS-1];
    reg [127:0] gold_d [0:SG_D_WORDS-1];
    reg [7:0]   cov_e  [0:SG_E_BYTES-1];
    reg [7:0]   cov_d  [0:SG_D_BYTES-1];
    reg [7:0]   cov_o  [0:SG_O_BYTES-1];
    // One flag per pixel: the project is 1x1, so output pixel (y,x) depends on
    // depthwise pixel (y,x) alone, which depends on the expand's
    // (y-1..y+1, x-1..x+1).
    reg         epix [0:SG_E_H*SG_E_W-1];
    reg         dpix [0:SG_D_H*SG_D_W-1];
    reg         opix [0:SG_O_H*SG_O_W-1];
    // Wrong bytes per pixel, so the attribution can be given in bytes.
    integer     eb_pix [0:SG_E_H*SG_E_W-1];
    integer     db_pix [0:SG_D_H*SG_D_W-1];
    integer     ob_pix [0:SG_O_H*SG_O_W-1];

    integer e_ok, e_bad, e_xs, e_wr, e_oob;
    integer d_ok, d_bad, d_xs, d_wr, d_oob;
    integer o_ok, o_bad, o_xs, o_wr, o_oob;
    integer sg_y [0:255];
    integer sg_x [0:255];
    integer sg_c [0:63];
    integer sg_ny [0:255];      // never-written block-output bytes, by row
    integer sg_nx [0:255];      // ... and by pixel column
    // Block-output wrong bytes by row and pixel column: those inherited from
    // the expand (sg_ex*) and those introduced by the depthwise (sg_dw*).
    integer sg_dwy [0:255];     // depthwise-introduced output bytes, by row
    integer sg_dwx [0:255];     // ...and by pixel column
    integer sg_exy [0:255];     // expand-inherited ones, for contrast
    integer sg_exx [0:255];
    // The depthwise tensor's own wrong bytes, by row, column and channel. The
    // channel axis does not survive to the output (the 1x1 project mixes all
    // channels), so it is kept here.
    integer sd_y [0:255], sd_x [0:255], sd_c [0:63];
    // Lane group width of the depthwise; it must equal the design's DW_LANES
    // (checked in the report: dw_rt is DW_LANES*8 bits wide).
    localparam integer TB_DW_LANES = 8;
    localparam integer TB_MAXG     = 8;
    integer sd_xg [0:TB_MAXG*256-1];  // wrong at column x, per lane group
    integer sd_nre, sd_nel;
    integer sd_re_r[0:23], sd_re_x[0:23], sd_re_c[0:23];
    integer sd_el_r[0:23], sd_el_x[0:23], sd_el_c[0:23];
    reg [7:0] sd_re_g[0:23], sd_re_w[0:23], sd_el_g[0:23], sd_el_w[0:23];
    integer sdx, sdc;
    // Right edge (column W-1) and left edge (column 0), kept apart.
    integer sd_ry [0:255], sd_rc [0:63];   // right edge, column W-1, by row / channel
    integer sd_ly [0:255], sd_lc [0:63];   // left  edge, column 0
    // Every wrong block-output byte, so those charged to the project can be
    // listed once dpix is complete.
    localparam integer OBMAX = 20000;
    integer ob_n, ob_ovf;
    integer ob_r [0:OBMAX-1], ob_x [0:OBMAX-1], ob_c [0:OBMAX-1];
    reg [7:0] ob_g [0:OBMAX-1], ob_w [0:OBMAX-1];
    integer sinit;

    initial begin
        e_ok = 0; e_bad = 0; e_xs = 0; e_wr = 0; e_oob = 0;
        d_ok = 0; d_bad = 0; d_xs = 0; d_wr = 0; d_oob = 0;
        o_ok = 0; o_bad = 0; o_xs = 0; o_wr = 0; o_oob = 0;
        for (sinit = 0; sinit < SG_E_BYTES; sinit = sinit + 1) cov_e[sinit] = 8'd0;
        for (sinit = 0; sinit < SG_D_BYTES; sinit = sinit + 1) cov_d[sinit] = 8'd0;
        for (sinit = 0; sinit < SG_O_BYTES; sinit = sinit + 1) cov_o[sinit] = 8'd0;
        for (sinit = 0; sinit < SG_E_H*SG_E_W; sinit = sinit + 1) begin
            epix[sinit] = 1'b0; eb_pix[sinit] = 0;
        end
        for (sinit = 0; sinit < SG_D_H*SG_D_W; sinit = sinit + 1) begin
            dpix[sinit] = 1'b0; db_pix[sinit] = 0;
        end
        for (sinit = 0; sinit < SG_O_H*SG_O_W; sinit = sinit + 1) begin
            opix[sinit] = 1'b0; ob_pix[sinit] = 0;
        end
        for (sinit = 0; sinit < 256; sinit = sinit + 1) begin
            sg_y[sinit] = 0; sg_x[sinit] = 0;
            sg_dwy[sinit] = 0; sg_dwx[sinit] = 0;
            sg_exy[sinit] = 0; sg_exx[sinit] = 0;
            sd_y[sinit] = 0; sd_x[sinit] = 0;
            sd_ry[sinit] = 0; sd_ly[sinit] = 0;
        end
        for (sinit = 0; sinit < TB_MAXG*256; sinit = sinit + 1) sd_xg[sinit] = 0;
        for (sinit = 0; sinit < 64; sinit = sinit + 1) begin
            sd_rc[sinit] = 0; sd_lc[sinit] = 0;
        end
        ob_n = 0; ob_ovf = 0;
        for (sinit = 0; sinit < 64; sinit = sinit + 1) begin
            sg_c[sinit] = 0; sd_c[sinit] = 0;
        end
        sd_nre = 0; sd_nel = 0; sdx = 0; sdc = 0;
    end

    // Blocking assignments throughout: loop iterations accumulate into the
    // same counters.
    integer sr, sw, sl, sb, sk, sgw, snl, srb, sxx, scc;
    integer sq, sq2, spo, sprb, sky, skx, sany, snn;
    integer sc0, sc1, sc2, sn_o, sn_od, sn_d, sn_de, sn_e, sn_oe;
    integer sb_o, sb_od, sb_oe, sb_d, sb_de;
    reg [7:0] s_got, s_want;
    // =====================================================================
    //  Depthwise constants per beat (the stage-split block only)
    //
    //  twn_dw_array reads w_taps one posedge after a column is presented and
    //  m0/bias/sh four posedges after. For each beat the constant word in
    //  flight must be the one twn_wmem was addressed for with the beat's own
    //  lane group (tag). rqa_q / tpa_q hold the previous cycle's addresses.
    // =====================================================================
    reg [12:0] rqa_q;
    reg [9:0]  tpa_q;
    integer tb_rq_bad, tb_tp_bad, tb_rq_beats;
    integer rq_badx [0:255], rq_badg [0:TB_MAXG-1];
    integer tp_badx [0:255];
    integer rqi;
    initial begin
        tb_rq_bad = 0; tb_tp_bad = 0; tb_rq_beats = 0;
        for (rqi = 0; rqi < 256; rqi = rqi + 1) begin
            rq_badx[rqi] = 0; tp_badx[rqi] = 0;
        end
        for (rqi = 0; rqi < TB_MAXG; rqi = rqi + 1) rq_badg[rqi] = 0;
    end
    always @(posedge clk) begin
        rqa_q <= DUT.dws_rqd_addr;
        tpa_q <= DUT.dws_taps_addr;
    end
    always @(negedge clk) if (!rst && DUT.blk === SG_BLK5) begin
        // requant stage: consumes acc and the constants while v_s1b is high;
        // rqa_q is the address whose data is in flight then
        if (DUT.DW.v_s1b === 1'b1) begin
            tb_rq_beats = tb_rq_beats + 1;
            if (rqa_q !== (DUT.mb_rqd + DUT.DW.tag_s1b)) begin
                tb_rq_bad = tb_rq_bad + 1;
                if (DUT.DW.x_s1b < 256) rq_badx[DUT.DW.x_s1b] = rq_badx[DUT.DW.x_s1b] + 1;
                if (DUT.DW.tag_s1b < TB_MAXG)
                    rq_badg[DUT.DW.tag_s1b] = rq_badg[DUT.DW.tag_s1b] + 1;
            end
        end
        // the products are formed on the cycle v_d is high, from w_taps
        if (DUT.DW.v_d === 1'b1) begin
            if (tpa_q !== (DUT.mb_dw + DUT.DW.tag_d)) begin
                tb_tp_bad = tb_tp_bad + 1;
                if (DUT.DW.x_d < 256) tp_badx[DUT.DW.x_d] = tp_badx[DUT.DW.x_d] + 1;
            end
        end
    end

    always @(negedge clk) if (!rst && DUT.blk === SG_BLK5) begin
        // ---------------- the EXPAND, into RB_T1 ----------------
        if (DUT.RB_T1.wr_en === 1'b1) begin
            e_wr = e_wr + 1;
            sr = DUT.RB_T1.wptr_r;
            sw = DUT.RB_T1.wword;
            if (sr >= SG_E_H || sw >= SG_E_RWORDS) e_oob = e_oob + 1;
            else begin
                sgw = sr * SG_E_RWORDS + sw;
                sb  = sgw * 16;
                for (sk = 0; sk < 16; sk = sk + 1) begin
                    cov_e[sb + sk] = cov_e[sb + sk] + 8'd1;
                    s_got  = DUT.RB_T1.wr_data[sk*8 +: 8];
                    s_want = gold_e[sgw][sk*8 +: 8];
                    if (s_got === s_want) e_ok = e_ok + 1;
                    else begin
                        e_bad = e_bad + 1;
                        if (^s_got === 1'bx) e_xs = e_xs + 1;
                        srb = sw*16 + sk;             // byte within the row
                        sxx = srb / SG_E_C;
                        scc = srb % SG_E_C;
                        epix[sr*SG_E_W + sxx] = 1'b1;
                        eb_pix[sr*SG_E_W + sxx] = eb_pix[sr*SG_E_W + sxx] + 1;
                        if (sr  < 256) sg_y[sr]  = sg_y[sr]  + 1;
                        if (sxx < 256) sg_x[sxx] = sg_x[sxx] + 1;
                        if (scc <  64) sg_c[scc] = sg_c[scc] + 1;
                    end
                end
            end
        end

        // ---------------- the DEPTHWISE, into RingC ----------------
        if (DUT.RB_C.wr_en === 1'b1) begin
            d_wr = d_wr + 1;
            sr = DUT.RB_C.wptr_r;
            sw = DUT.RB_C.wr_word_i;
            // The lane enable is one-hot by twn_dw_pack's construction; counted,
            // because a multi-hot enable would write two places.
            sl = 0; snl = 0;
            for (sk = 0; sk < SG_D_LANES; sk = sk + 1)
                if (DUT.RB_C.wr_lane[sk] === 1'b1) begin sl = sk; snl = snl + 1; end
            if (snl != 1 || sr >= SG_D_H || sw >= SG_D_RWORDS) begin
                d_oob = d_oob + 1;
                // What the out-of-range write was, with its position.
                if (d_oob <= 4)
                    $display("    DW OOB write #%0d: RB_C.wptr_r %0d, wr_word_i %0d, lanes hot %0d (lane %0d), while d_row is %0d and dw_out_x %0d tag %0d",
                             d_oob, sr, sw, snl, sl, DUT.d_row,
                             DUT.dw_out_x, DUT.dw_out_tag);
            end
            else begin
                sb = sr*SG_D_ROWB + sw*128 + sl*8;
                for (sk = 0; sk < 8; sk = sk + 1) begin
                    cov_d[sb + sk] = cov_d[sb + sk] + 8'd1;
                    s_got  = DUT.RB_C.wr_data[(sl*64 + sk*8) +: 8];
                    s_want = gold_d[(sb + sk) / 16][((sb + sk) % 16)*8 +: 8];
                    if (s_got === s_want) d_ok = d_ok + 1;
                    else begin
                        d_bad = d_bad + 1;
                        if (^s_got === 1'bx) d_xs = d_xs + 1;
                        srb = sw*128 + sl*8 + sk;
                        dpix[sr*SG_D_W + (srb / SG_D_C)] = 1'b1;
                        db_pix[sr*SG_D_W + (srb / SG_D_C)] =
                            db_pix[sr*SG_D_W + (srb / SG_D_C)] + 1;
                        // ---- the depthwise's own error shape: by row, column,
                        // ---- channel and lane group (twn_dwseq walks lane
                        // ---- groups outer)
                        sdx = srb / SG_D_C;             // pixel column
                        sdc = srb % SG_D_C;             // channel
                        if (sr  < 256) sd_y[sr]  = sd_y[sr]  + 1;
                        if (sdx < 256) sd_x[sdx] = sd_x[sdx] + 1;
                        if (sdc <  64) sd_c[sdc] = sd_c[sdc] + 1;
                        if (sdx < 256 && (sdc / TB_DW_LANES) < TB_MAXG)
                            sd_xg[(sdc / TB_DW_LANES)*256 + sdx] =
                            sd_xg[(sdc / TB_DW_LANES)*256 + sdx] + 1;
                        // ---- the two edge columns, kept apart ----
                        if (sdx == SG_D_W-1) begin
                            if (sr  < 256) sd_ry[sr]  = sd_ry[sr]  + 1;
                            if (sdc <  64) sd_rc[sdc] = sd_rc[sdc] + 1;
                        end
                        if (sdx == 0) begin
                            if (sr  < 256) sd_ly[sr]  = sd_ly[sr]  + 1;
                            if (sdc <  64) sd_lc[sdc] = sd_lc[sdc] + 1;
                        end
                        // a few actual values, at the right edge and elsewhere
                        if (sdx >= SG_D_W-1) begin
                            if (sd_nre < 24) begin
                                sd_re_r[sd_nre] = sr;  sd_re_x[sd_nre] = sdx;
                                sd_re_c[sd_nre] = sdc;
                                sd_re_g[sd_nre] = s_got; sd_re_w[sd_nre] = s_want;
                                sd_nre = sd_nre + 1;
                            end
                        end else begin
                            if (sd_nel < 24) begin
                                sd_el_r[sd_nel] = sr;  sd_el_x[sd_nel] = sdx;
                                sd_el_c[sd_nel] = sdc;
                                sd_el_g[sd_nel] = s_got; sd_el_w[sd_nel] = s_want;
                                sd_nel = sd_nel + 1;
                            end
                        end
                    end
                end
            end
        end

        // ---------------- the CONTROL: the block output, into RB_OU ----------
        if (DUT.RB_OU.wr_en === 1'b1) begin
            o_wr = o_wr + 1;
            sr = DUT.RB_OU.wptr_r;
            sw = DUT.RB_OU.wword;
            if (sr >= SG_O_H || sw >= SG_O_RWORDS) o_oob = o_oob + 1;
            else begin
                sgw = sr * SG_O_RWORDS + sw;
                sb  = sgw * 16;
                for (sk = 0; sk < 16; sk = sk + 1) begin
                    cov_o[sb + sk] = cov_o[sb + sk] + 8'd1;
                    s_got  = DUT.RB_OU.wr_data[sk*8 +: 8];
                    s_want = gold[GI_WORD_BASE[SG_BLK*32 +: 32] + sgw][sk*8 +: 8];
                    if (s_got === s_want) o_ok = o_ok + 1;
                    else begin
                        o_bad = o_bad + 1;
                        if (^s_got === 1'bx) o_xs = o_xs + 1;
                        srb = sw*16 + sk;
                        opix[sr*SG_O_W + (srb / SG_O_C)] = 1'b1;
                        ob_pix[sr*SG_O_W + (srb / SG_O_C)] =
                            ob_pix[sr*SG_O_W + (srb / SG_O_C)] + 1;
                        // kept in full so the project-introduced population can
                        // be enumerated once dpix is complete
                        if (ob_n < OBMAX) begin
                            ob_r[ob_n] = sr;
                            ob_x[ob_n] = srb / SG_O_C;
                            ob_c[ob_n] = srb % SG_O_C;
                            ob_g[ob_n] = s_got; ob_w[ob_n] = s_want;
                            ob_n = ob_n + 1;
                        end else ob_ovf = ob_ovf + 1;
                    end
                end
            end
        end
    end
`endif

`ifdef FUSE_RINGA_PROBE
    // =====================================================================
    //  FUSE_RINGA_PROBE -- is the row the expand asks of RingA resident?
    //
    //  Measurement only; nothing in the design is touched. RingA holds rows
    //  [rptr, wptr) with slot = row % RA_ROWS. A read is out of window when

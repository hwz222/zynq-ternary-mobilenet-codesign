    `elsif FUSE_STAGE_B09
        `include "gold_stage_b09.vh"
    `elsif FUSE_STAGE_B10
        `include "gold_stage_b10.vh"
    `elsif FUSE_STAGE_B11
        `include "gold_stage_b11.vh"
    `elsif FUSE_STAGE_B12
        `include "gold_stage_b12.vh"
    `elsif FUSE_STAGE_B13

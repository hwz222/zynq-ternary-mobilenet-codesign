                fail($sformatf("gold_b00_d.hex probe %0d at byte %0d is %02h, the .bin says %02h",
                     sq, spo, gold_d[spo/16][(spo%16)*8 +: 8], SG_D_PRB_V[sq*8 +: 8]));
            else sprb = sprb + 1;
        end
        checks = checks + sprb;
`endif

        env_init();
        rst = 1'b1;

        // The weight image and the block-0 input image, at their arena addresses.
        $readmemh("ddr_w.hex", DDR_W.mem);
        $readmemh("ddr_in_b00.hex", DDR_A.mem, FM_IN_WORD0);
`ifdef FUSE_FRAME_ISOLATE
        // Block 0 is not injected (its image lives above both slots) but its
        // reference is loaded here so the read-side check covers it too.
        iso_prb_ok = 0; iso_prb_bad = 0; iso_words = 0; iso_for_blk = -1;
        iso_load(0);
`endif

        repeat (8) @(posedge clk);
        rst = 1'b0;
        @(posedge clk);

        fuse_boot(FM_W_BASE, FM_ACT_BASE, FM_IN_PTR, ok);
        errors = errors + env_errors;
        if (!ok) begin
            $display("  the boot sequence failed, so nothing below would mean anything");
            $display("=== tb_fuse_frame: %0d checks, %0d errors, FRAME FAIL ===",
                     checks, errors + 1);
            $finish;
        end
        checks = checks + 1;
`ifdef FUSE_FRAME_BB2HD
        lite_wr(F_OUT_LO, FM_IN_PTR[31:0]);
        lite_wr(F_OUT_HI, {24'd0, FM_IN_PTR[39:32]});
        lite_wr(16'h0060, 32'h1);
        $display("  BB2HD: A_BB2HD = 1, OUT_PTR = %010h, the last block must write %010h",
                 FM_IN_PTR, BB2HD_BASE);
`endif

        // The frame does not start by itself: fuse_boot() loads the
        // descriptors and pointers and checks the table; CTRL_START begins
        // the frame.
        lite_wr(F_CTRL, CTRL_START);

        g = 0;
        while (g < RUN_CYCLES && !done) begin
            @(posedge clk); g = g + 1;
        end
        frame_done = done ? 1 : 0;

        repeat (50) @(negedge clk);

        // =================================================================
        //  the report
        // =================================================================
        $display("");
        if (frame_done)
            $display("  FRAME: completed in %0d cycles", g);
        else begin
            $display("  FRAME: did NOT complete in %0d cycles -- it reached block %0d.",
                     g, DUT.blk);
            $display("         The per-block table below is still valid for the blocks");
            $display("         that finished; the rest simply were not reached.");
            fail("the frame did not complete");
        end

        // ---- cycle counters ----
        // cyc_total is frame-scoped (cleared by ap_start). The gate counts
        // CTRL_START to done; cyc_total counts only the cycles the block
        // sequencer runs, so the two differ by the inter-block gaps.
        $display("  cyc_total (CSR, frame-scoped) = %0d   vs FRAME %0d cycles",
                 DUT.SEQ.cyc_total, g);
        $display("  array %0d  dw %0d  stall_mem %0d  idle_pre %0d  idle_post %0d",
                 DUT.SEQ.cyc_array, DUT.SEQ.cyc_dw, DUT.SEQ.cyc_stall_mem,
                 DUT.SEQ.cyc_idle_pre, DUT.SEQ.cyc_idle_post);
`ifdef FUSE_BLK_CYC
        bc_report;
`endif
`ifdef FUSE_OBS
        $display("  pix_nz  (healthy reference) = %03h   [3:0] array  [7:4] bank wr  [11:8] bank rd",
                 DUT.pix_nz_sticky);
        $display("  arr_cap (healthy reference)  pix0 %08h  pix1 %08h  pix2 %08h  pix3 %08h",
                 DUT.arr_cap[31:0],   DUT.arr_cap[63:32],
                 DUT.arr_cap[95:64],  DUT.arr_cap[127:96]);
`else
        // Without FUSE_OBS the observation registers are compiled out and tied
        // to zero; printing them would report a value that was not measured.
        $display("  pix_nz / arr_cap: observation NOT built (FUSE_OBS undefined).");
        $display("    Rebuild the gate with -d FUSE_OBS to get the healthy reference back.");
`endif

        if (bad_burst != 0)    fail($sformatf("%0d non-INCR write bursts", bad_burst));
        if (stray_writes != 0) fail($sformatf("%0d write beats outside the activation window", stray_writes));
        if (wrong_slot != 0)   fail($sformatf("%0d write beats to the wrong slot", wrong_slot));
`ifdef FUSE_FRAME_BB2HD
        begin : bb2hd_verdict
            reg [31:0] bv;
            checks = checks + 1;
            // block 16's tensor: 8 rows x 2,560 B = 1,280 beats
            if (bb2hd_beats != 1280)
                fail($sformatf("BB2HD: the last block wrote %0d beats to the head slot, not 1280", bb2hd_beats));
            lite_rd(16'h0060, bv);
            $display("  BB2HD: A_BB2HD after the frame = %08h (en %0d, bb_par %0d, coll %0d), %0d beats to the head slot",
                     bv, bv[0], bv[1], bv[3], bb2hd_beats);
            checks = checks + 1;
            if (bv[0] !== 1'b1 || bv[1] !== ~BB2HD_PAR0[0] || bv[3] !== 1'b0)
                fail($sformatf("BB2HD: A_BB2HD reads %08h; want en 1, bb_par flipped to %0d, no collision",
                               bv, ~BB2HD_PAR0[0]));
        end
`endif
        if (overlap_aw != 0)   fail($sformatf("%0d overlapping write bursts -- the scoreboard's own assumption broke, so its per-block numbers below are NOT trustworthy", overlap_aw));

        $display("");
        $display("  per block -- every byte written, against the C reference");
        $display("    blk    bytes ok   bytes wrong   expected   first wrong byte");
        n_pass = 0; n_gap = 0; n_short = 0;
        for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
            want_bytes = GI_WORDS[bi*32 +: 32] * 16;
            // is_gap excuses a block from the chain rule. None by default;
            // FRAME_NEG_GAP0 excuses block 0.
`ifdef FRAME_NEG_GAP0
            is_gap[bi] = (bi == 0);
`else
            is_gap[bi] = 1'b0;
`endif
            if (bytes_bad[bi] == 0 && bytes_ok[bi] == want_bytes) begin
                $display("    %3d %11d %13d %10d   %0s",
                         bi, bytes_ok[bi], bytes_bad[bi], want_bytes,
                         is_gap[bi] ? "PASS (and it was excused -- see is_gap)" : "PASS");
                n_pass = n_pass + 1;
            end else if (bytes_ok[bi] + bytes_bad[bi] < want_bytes) begin
                $display("    %3d %11d %13d %10d   SHORT -- %0d bytes never written",
                         bi, bytes_ok[bi], bytes_bad[bi], want_bytes,
                         want_bytes - bytes_ok[bi] - bytes_bad[bi]);
                n_short = n_short + 1;
            end else begin
                $display("    %3d %11d %13d %10d   at %0d: got %02h want %02h%0s%0s",
                         bi, bytes_ok[bi], bytes_bad[bi], want_bytes,
                         first_off[bi], first_got[bi], first_want[bi],
                         (bytes_x[bi] != 0) ? "  X" : "",
                         is_gap[bi] ? "   (known gap)" : "");
                if (is_gap[bi]) n_gap = n_gap + 1;
            end
        end

        // =================================================================
        //  Per-block verdict table: geometry, residual flag, stride-2
        //  depthwise flag, and the wrong bytes split into wrong values, X (a
        //  row-buffer position nothing had written) and never written (a byte
        //  that never reached DDR).
        // =================================================================
        $display("");
        $display("  ================= PER-BLOCK VERDICT TABLE =================");
`ifdef FUSE_FRAME_ISOLATE
        $display("  Each row computed from the C reference's OWN input for that");
        $display("  block. No row is downstream of any other.");
`else
        $display("  🔴 CHAIN MODE: block b's input is block b-1's ACTUAL output, so");
        $display("  every row below the first wrong one is a consequence and not a");
        $display("  finding. Re-run with -d FUSE_FRAME_INJECT for independent rows.");
`endif
        $display("    blk    CxHxW      res  s2      ok    wrong        X    never    %%ok");
        for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
            want_bytes = GI_WORDS[bi*32 +: 32] * 16;
            db_ch      = GI_C_OUT[bi*10 +: 10];
            db_h       = GI_H_OUT[bi*9  +: 9];
            db_w       = GI_W_OUT[bi*9  +: 9];
            db_never   = want_bytes - bytes_ok[bi] - bytes_bad[bi];
            db_pct     = (want_bytes == 0) ? 0.0
                                           : (100.0 * bytes_ok[bi]) / (1.0 * want_bytes);
            $display("    %3d  %3dx%3dx%3d  %3s %3s %8d %8d %8d %8d %7.3f",
                     bi, db_ch, db_h, db_w,
                     FM_HAS_RES[bi] ? "yes" : "-",
                     FM_S_DW[bi]    ? "yes" : "-",
                     bytes_ok[bi], bytes_bad[bi], bytes_x[bi], db_never, db_pct);
        end

        // ---- and the SHAPE of each wrong block, which is what names a defect --
        for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
            want_bytes = GI_WORDS[bi*32 +: 32] * 16;
            if (bytes_bad[bi] != 0 || bytes_ok[bi] != want_bytes) begin
                db_ch = GI_C_OUT[bi*10 +: 10];
                db_h  = GI_H_OUT[bi*9  +: 9];
                db_w  = GI_W_OUT[bi*9  +: 9];
                db_base = GI_WORD_BASE[bi*32 +: 32];
                db_base = db_base * 16;
                db_c0 = 0; db_c1 = 0; db_c2 = 0;
                for (ci = 0; ci < want_bytes; ci = ci + 1)
                    if      (cov[db_base + ci] == 8'd0) db_c0 = db_c0 + 1;
                    else if (cov[db_base + ci] == 8'd1) db_c1 = db_c1 + 1;
                    else                                db_c2 = db_c2 + 1;
                $display("");
                $display("    ---- block %0d : %0d wrong of %0d (%0d X), %0d never written ----",
                         bi, bytes_bad[bi], want_bytes,
                         bytes_x[bi], want_bytes - bytes_ok[bi] - bytes_bad[bi]);
                $display("      write coverage over its own tensor: %0d never, %0d once, %0d more than once",
                         db_c0, db_c1, db_c2);
                if (db_c2 != 0)
                    $display("        -> the store's ADDRESSING is wrong, not (only) its arithmetic");
                if (off_over[bi] != 0)
                    $display("      %0d write beats landed past this block's tensor but inside its slot", off_over[bi]);
                if (pad_bytes[bi] != 0)
                    $display("      %0d bytes were row padding (stride %0d, real row %0d) and were NOT scored",
                             pad_bytes[bi], FM_ROW_BYTES_OUT[bi*16 +: 16], FM_ROW_REAL_OUT[bi*16 +: 16]);
                if (first_off[bi] >= 0)
                    $display("      first wrong byte at %0d: got %02h want %02h",
                             first_off[bi], first_got[bi], first_want[bi]);
                // rows
                db_n = 0;
                for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1)
                    if (wrong_y[bi*256 + hi2] != 0) db_n = db_n + 1;
                $write("      rows     %0d of %0d :", db_n, db_h);
                db_n2 = 0;
                for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1)
                    if (wrong_y[bi*256 + hi2] != 0) begin
                        if (db_n2 < 16) $write(" %0d:%0d", hi2, wrong_y[bi*256 + hi2]);
                        db_n2 = db_n2 + 1;
                    end
                $display("%0s", (db_n2 > 16) ? " ..." : "");
                // columns
                db_n = 0;
                for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1)
                    if (wrong_x[bi*256 + hi2] != 0) db_n = db_n + 1;
                $write("      columns  %0d of %0d :", db_n, db_w);
                db_n2 = 0;
                for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1)
                    if (wrong_x[bi*256 + hi2] != 0) begin
                        if (db_n2 < 16) $write(" %0d:%0d", hi2, wrong_x[bi*256 + hi2]);
                        db_n2 = db_n2 + 1;
                    end
                $display("%0s", (db_n2 > 16) ? " ..." : "");
                // channels
                db_n = 0;
                for (hi2 = 0; hi2 < HB_C; hi2 = hi2 + 1)
                    if (wrong_c[bi*HB_C + hi2] != 0) db_n = db_n + 1;
                $write("      channels %0d of %0d :", db_n, db_ch);
                db_n2 = 0;
                for (hi2 = 0; hi2 < HB_C; hi2 = hi2 + 1)
                    if (wrong_c[bi*HB_C + hi2] != 0) begin
                        if (db_n2 < 16) $write(" %0d:%0d", hi2, wrong_c[bi*HB_C + hi2]);
                        db_n2 = db_n2 + 1;
                    end
                $display("%0s", (db_n2 > 16) ? " ..." : "");
            end
        end
        $display("  ===========================================================");

        $display("");
        $display("  %0d blocks bit-exact, %0d wrong for a KNOWN reason (block 0's stem),",
                 n_pass, n_gap);
        $display("  %0d short.", n_short);
`ifdef FUSE_FRAME_ISOLATE
        // =================================================================
        //  The injection's report card: nothing in the table above is
        //  evidence unless these hold.
        // =================================================================
        $display("");
        $display("  ============ THE INJECTION, CHECKED ============");
        $display("  reloads              : %0d  (one per block after block 0)", iso_loads);
        $display("  arriving late        : %0d  (while the read master was busy)", iso_late);
        $display("  image probes matched : %0d of %0d  (3 baked bytes per block, at HWC",
                 iso_prb_ok, iso_prb_ok + iso_prb_bad);
        $display("                         offsets the generator asserts differ from CHW)");
        $display("  writes INTO the running block's own input slot : %0d", iso_wr_in);
        // ---- the slot map itself ----
        db_slotbad = 0;
        for (bi = 0; bi < GI_NBLK; bi = bi + 1)
            if (FM_IN_SLOT[bi*4 +: 4] == FM_OUT_SLOT[bi*4 +: 4]) begin
                db_slotbad = db_slotbad + 1;
                $display("  🔴 block %0d reads and writes slot %0d -- injecting its input",
                         bi, FM_IN_SLOT[bi*4 +: 4]);
                $display("     would be scribbling on its own output region");
            end
        $display("  blocks whose input slot IS their output slot  : %0d  (must be 0)",
                 db_slotbad);
        // ---- what the design actually READ ----
        $display("");
        $display("  activation read beats, classified by region. `own' is the block's");
        $display("  own input region and its data is compared against the very array");
        $display("  that was injected -- so a block with 0 own beats was never fed by");
        $display("  this instrument at all, whatever its byte count says:");
        $display("    blk    own beats   wanted   elsewhere   own beats NOT the reference");
        db_n = 0;
        for (bi = 0; bi < GI_NBLK; bi = bi + 1) begin
            db_n2 = FM_IN_WORDS[bi*32 +: 32];
            $display("    %3d %11d %8d %11d %14d%0s",
                     bi, rd_own[bi], db_n2, rd_oth[bi], rd_bad[bi],
                     (rd_own[bi] < db_n2) ? "   <-- SHORT" : "");
            if (rd_own[bi] < db_n2) db_n = db_n + 1;
            if (rd_bad[bi] != 0)
                fail($sformatf("block %0d read %0d beats from its own input region that were NOT the reference image -- the injection did not survive to the point of use, so this block's row in the table above is not evidence", bi, rd_bad[bi]));
        end
        $display("    stragglers (a burst issued before the boundary) : %0d", rd_strag);
        $display("    own-region beats past the end of the image      : %0d", rd_unk);
        $display("    overlapping read bursts / beats below the arena : %0d / %0d",
                 rd_overlap, rd_below);
        if (rd_overlap != 0)
            fail($sformatf("%0d read bursts overlapped -- this tracker cannot score that, so its per-block read classification is NOT trustworthy", rd_overlap));
        if (db_n != 0)
            fail($sformatf("%0d blocks read fewer beats from their own input region than the image has words -- they were not fully fed", db_n));
        $display("  ===============================================");
        if (iso_loads != GI_NBLK - 1)
            fail($sformatf("%0d reloads for %0d blocks after block 0", iso_loads, GI_NBLK - 1));
        if (iso_late != 0)
            fail($sformatf("%0d input reloads landed while the read master was busy", iso_late));
        if (iso_prb_bad != 0)
            fail($sformatf("%0d of the injected images failed their own probe bytes -- the file was missing, stale, or not that block's tensor", iso_prb_bad));
        if (iso_wr_in != 0)
            fail($sformatf("%0d write beats landed in the running block's INPUT slot -- something overwrote the injection while the block was reading it", iso_wr_in));
        if (db_slotbad != 0)
            fail($sformatf("%0d blocks have in_slot == out_slot", db_slotbad));
        checks = checks + 6 + GI_NBLK;
`endif
        // Chain: block b+1's input is block b's output, so the first wrong
        // block makes every later one wrong and X propagates. Only the first
        // wrong block is a finding.
        first_bad = -1;
        for (bi = 0; bi < GI_NBLK; bi = bi + 1)
            if (first_bad < 0 && (bytes_bad[bi] != 0 ||
                                  bytes_ok[bi] + bytes_bad[bi] < GI_WORDS[bi*32 +: 32] * 16))
                first_bad = bi;
`ifdef FUSE_FRAME_ISOLATE
        // ISOLATE: no block is downstream of any other, so every block
        // answers for itself, excused blocks aside.
        for (bi = 0; bi < GI_NBLK; bi = bi + 1)
            if (!is_gap[bi] && bytes_bad[bi] != 0)
                fail($sformatf("block %0d is wrong with its OWN reference input, and is not a known gap", bi));
        if (first_bad >= 0)
            $display("");
`else
        if (first_bad >= 0) begin
            $display("");
            $display("  FIRST WRONG BLOCK: %0d%0s", first_bad,
                     is_gap[first_bad] ? "  -- and it is a KNOWN GAP, so nothing below it is evidence yet" : "");
            c0 = 0; c1 = 0; c2 = 0;
            for (ci = 0; ci < 262144; ci = ci + 1)
                if      (cov[ci] == 8'd0) c0 = c0 + 1;
                else if (cov[ci] == 8'd1) c1 = c1 + 1;
                else                      c2 = c2 + 1;
            $display("    block 0 write coverage: %0d positions never written, %0d once, %0d more than once",
                     c0, c1, c2);
            if (c0 != 0 || c2 != 0)
                $display("      -> the store's ADDRESSING is wrong, not (only) its arithmetic");
            $display("    where block 0's wrong bytes are:");
            hn = 0;
            for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1) if (wrong_y[hi2] != 0) hn = hn + 1;
            $display("      rows with any wrong byte: %0d of 128", hn);
            hn = 0;
            for (hi2 = 0; hi2 < 256; hi2 = hi2 + 1) if (wrong_x[hi2] != 0) hn = hn + 1;
            $display("      pixels with any wrong byte: %0d of 128", hn);
            hn = 0;
            for (hi2 = 0; hi2 < 64; hi2 = hi2 + 1) if (wrong_c[hi2] != 0) hn = hn + 1;
            $display("      channels with any wrong byte: %0d of 16", hn);
            $display("      per channel: %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d",
                     wrong_c[0], wrong_c[1], wrong_c[2],  wrong_c[3],
                     wrong_c[4], wrong_c[5], wrong_c[6],  wrong_c[7],
                     wrong_c[8], wrong_c[9], wrong_c[10], wrong_c[11],
                     wrong_c[12], wrong_c[13], wrong_c[14], wrong_c[15]);
            $display("      first 8 rows: %0d %0d %0d %0d %0d %0d %0d %0d   last: %0d %0d %0d %0d",
                     wrong_y[0], wrong_y[1], wrong_y[2], wrong_y[3],
                     wrong_y[4], wrong_y[5], wrong_y[6], wrong_y[7],
                     wrong_y[124], wrong_y[125], wrong_y[126], wrong_y[127]);
            $display("      first 8 pixels: %0d %0d %0d %0d %0d %0d %0d %0d   last: %0d %0d %0d %0d",
                     wrong_x[0], wrong_x[1], wrong_x[2], wrong_x[3],
                     wrong_x[4], wrong_x[5], wrong_x[6], wrong_x[7],
                     wrong_x[124], wrong_x[125], wrong_x[126], wrong_x[127]);
            if (bytes_x[first_bad] != 0)
                $display("    %0d of its %0d wrong bytes are X, not a wrong value: something it read was never written.",
                         bytes_x[first_bad], bytes_bad[first_bad]);
            for (bi = first_bad + 1; bi < GI_NBLK; bi = bi + 1)
                if (bytes_bad[bi] != 0 || bytes_ok[bi] == 0)
                    $display("    block %0d is downstream of it and is NOT independently diagnosed", bi);
            if (!is_gap[first_bad])
                fail($sformatf("block %0d is the first wrong block and is NOT a known gap", first_bad));
        end
`endif
        // A short block is a failure in both modes.
        for (bi = 0; bi < GI_NBLK; bi = bi + 1)
            if (bytes_ok[bi] + bytes_bad[bi] < GI_WORDS[bi*32 +: 32] * 16)
                fail($sformatf("block %0d wrote only %0d of %0d bytes", bi,
                               bytes_ok[bi] + bytes_bad[bi],
                               GI_WORDS[bi*32 +: 32] * 16));

`ifdef FUSE_FRAME_STAGE
        // =================================================================
        //  Stage split report; the instrument's own checks come first.
        // =================================================================
        $display("");
        $display("  ================ STAGE SPLIT, block %0d ================", SG_BLK);
        $display("  THE INSTRUMENT, BEFORE ITS OUTPUT:");
        $display("    images: %0d of %0d probes matched (each at an HWC offset that",
                 sprb, 2*SG_NPRB);
        $display("            differs from its CHW one, so a no-op transpose fails them)");
        $display("    expand    writes %0d (geometry says %0d), %0d out of range",
                 e_wr, SG_E_BYTES/16, e_oob);
        $display("    depthwise writes %0d (geometry says %0d), %0d out of range or not one-hot",
                 d_wr, SG_D_BYTES/8, d_oob);
        $display("    blockout  writes %0d (geometry says %0d), %0d out of range",
                 o_wr, SG_O_BYTES/16, o_oob);
        // The check is on the writes that landed inside the tensor, not those
        // presented: a stage that writes more than its tensor is a design
        // finding, in-range writes that do not tile it are an instrument fault.
        if (e_wr - e_oob != SG_E_BYTES/16)
            fail($sformatf("the expand landed %0d row-buffer writes inside its tensor, the geometry says %0d -- the instrument's row/word model does not match the design's", e_wr - e_oob, SG_E_BYTES/16));
        if (d_wr - d_oob != SG_D_BYTES/8)
            fail($sformatf("the depthwise landed %0d lane writes inside its tensor, the geometry says %0d", d_wr - d_oob, SG_D_BYTES/8));
        if (e_oob != 0)
            $display("    -> FINDING: the expand presented %0d writes past the end of its tensor.", e_oob);
        if (d_oob != 0)
            $display("    -> FINDING: the depthwise presented %0d writes past the end of its tensor.", d_oob);
        if (o_oob != 0)
            $display("    -> FINDING: the project presented %0d writes past the end of its tensor.", o_oob);

        sc0 = 0; sc1 = 0; sc2 = 0;
        for (sq = 0; sq < SG_E_BYTES; sq = sq + 1)
            if      (cov_e[sq] == 8'd0) sc0 = sc0 + 1;
            else if (cov_e[sq] == 8'd1) sc1 = sc1 + 1;
            else                        sc2 = sc2 + 1;
        $display("    expand    coverage: %0d never written, %0d once, %0d more than once",
                 sc0, sc1, sc2);
        if (sc0 != 0 || sc2 != 0)
            fail($sformatf("the expand's coverage is %0d/%0d/%0d, not 0/%0d/0 -- either the design's addressing is wrong or this instrument's is, and until that is settled its wrong-byte count means nothing", sc0, sc1, sc2, SG_E_BYTES));
        sc0 = 0; sc1 = 0; sc2 = 0;

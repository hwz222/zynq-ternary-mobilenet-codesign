`ifdef FUSE_SCAT_TRACE
    // =====================================================================
    //  FUSE_SCAT_TRACE -- block 0: where a word goes missing on the way to RB_OU
    //
    //      twn_fuse_array  -> twn_act_scatter -> twn_res_add -> RB_OU
    //      arr_out_valid      scat_en            res_out_valid   wr_en
    //
    //  Each is a one-per-word pulse, so the first stage whose count falls
    //  short is the one that drops words. The array's beats per pixel group are
    //  counted too.
    //
    //  One named mechanism is tested: twn_act_scatter restarts its drain on the
    //  beat that completes a pixel group, after the drain block, so when that
    //  beat lands on the drain's last read the restart must win. tr_coll_* counts
    //  completing beats that arrive while a drain runs, tr_kill_* those on the
    //  drain's last read, and tr_lost_* restarts that did not survive (d_run
    //  low on the next cycle). A lost restart drops PIX x nbw = 4 words.
    //
    //  Sampled on the negedge, where the registers read are the values the
    //  scatter evaluates at the next posedge.
    // =====================================================================
    localparam integer TR_PIX = 4;

    integer tr_beat_xg [0:63];      // array beats, per pixel group (project)
    integer tr_ebeat_xg[0:63];      // the same for the expand, as a control
    integer tr_grp_p, tr_grp_e;     // group-complete beats reaching the scatter
    integer tr_coll_p, tr_coll_e;   // ...that arrived while a drain was running
    integer tr_kill_p, tr_kill_e;   // ...on the drain's LAST read: cancelled
    integer tr_scat_p, tr_scat_e;   // scat_en pulses
    integer tr_flush_p, tr_flush_e; // scat_flush_done pulses
    integer tr_res, tr_ouwr;        // res_out_valid, RB_OU.wr_en
    integer tr_row_scat, tr_rowi;   // scat_en since this project row's flush
    integer tr_grpc, tr_killc;      // and groups / kills in this project row
    integer tr_lost_p, tr_lost_e;   // ...and whose restart did NOT survive it
    integer tq, tn;
    reg     tr_gc;
    // tr_pend_*: a collision on the drain's last read, flagged last cycle,
    // whose restart is checked this cycle.
    reg     tr_pend_p, tr_pend_e;

    initial begin
        tr_grp_p = 0; tr_grp_e = 0; tr_coll_p = 0; tr_coll_e = 0;
        tr_kill_p = 0; tr_kill_e = 0; tr_scat_p = 0; tr_scat_e = 0;
        tr_flush_p = 0; tr_flush_e = 0; tr_res = 0; tr_ouwr = 0;
        tr_row_scat = 0; tr_rowi = 0; tr_grpc = 0; tr_killc = 0;
        tr_lost_p = 0; tr_lost_e = 0; tr_pend_p = 1'b0; tr_pend_e = 1'b0;
        for (tq = 0; tq < 64; tq = tq + 1) begin
            tr_beat_xg[tq] = 0; tr_ebeat_xg[tq] = 0;
        end
    end

    always @(negedge clk) if (!rst && DUT.blk === 5'd0) begin
        // ---- did the restart flagged last cycle actually take? ----
        if (tr_pend_p) begin
            if (DUT.SCAT.d_run !== 1'b1) tr_lost_p = tr_lost_p + 1;
            tr_pend_p = 1'b0;
        end
        if (tr_pend_e) begin
            if (DUT.SCAT.d_run !== 1'b1) tr_lost_e = tr_lost_e + 1;
            tr_pend_e = 1'b0;
        end

        // ---- the array's beats, per pixel group ----
        if (DUT.arr_out_valid === 1'b1) begin
            if (DUT.arr_out_dst === 1'b1) begin
                if (DUT.out_xg < 64) tr_beat_xg[DUT.out_xg] = tr_beat_xg[DUT.out_xg] + 1;
            end else begin
                if (DUT.out_xg < 64) tr_ebeat_xg[DUT.out_xg] = tr_ebeat_xg[DUT.out_xg] + 1;
            end
        end

        // ---- the scatter's group-complete trigger, and the collision ----
        tr_gc = (DUT.SCAT.in_valid === 1'b1) &&
                ((DUT.SCAT.ch0 + {7'd0, DUT.SCAT.pack}) >= DUT.SCAT.c_chan);
        if (tr_gc) begin
            if (DUT.arr_out_dst === 1'b1) begin
                tr_grp_p = tr_grp_p + 1; tr_grpc = tr_grpc + 1;
                if (DUT.SCAT.d_run === 1'b1) begin
                    tr_coll_p = tr_coll_p + 1;
                    if (DUT.SCAT.d_cp == (TR_PIX-1) &&
                        (DUT.SCAT.d_w + 10'd1) == DUT.SCAT.nbw) begin
                        tr_kill_p = tr_kill_p + 1; tr_killc = tr_killc + 1;
                        tr_pend_p = 1'b1;
                    end
                end
            end else begin
                tr_grp_e = tr_grp_e + 1;
                if (DUT.SCAT.d_run === 1'b1) begin
                    tr_coll_e = tr_coll_e + 1;
                    if (DUT.SCAT.d_cp == (TR_PIX-1) &&
                        (DUT.SCAT.d_w + 10'd1) == DUT.SCAT.nbw) begin
                        tr_kill_e = tr_kill_e + 1; tr_pend_e = 1'b1;
                    end
                end
            end
        end

        if (DUT.scat_en === 1'b1) begin
            if (DUT.arr_out_dst === 1'b1) begin
                tr_scat_p = tr_scat_p + 1; tr_row_scat = tr_row_scat + 1;
            end else tr_scat_e = tr_scat_e + 1;
        end
        if (DUT.scat_flush_done === 1'b1) begin
            if (DUT.arr_out_dst === 1'b1) begin
                tr_flush_p = tr_flush_p + 1;
                if (tr_rowi < 6)
                    $display("  TRACE project row %0d: %0d scatter words, %0d groups completed, %0d drains cancelled",
                             tr_rowi, tr_row_scat, tr_grpc, tr_killc);
                tr_rowi = tr_rowi + 1;
                tr_row_scat = 0; tr_grpc = 0; tr_killc = 0;
            end else tr_flush_e = tr_flush_e + 1;
        end
        if (DUT.res_out_valid === 1'b1) tr_res  = tr_res  + 1;
        if (DUT.RB_OU.wr_en  === 1'b1)  tr_ouwr = tr_ouwr + 1;
    end

    task tr_report;
        begin
            $display("");
            $display("  ============ SCATTER TRACE, block 0 ============");
            $display("  the four one-per-word pulses on the way to RB_OU:");
            tn = 0;
            for (tq = 0; tq < 64; tq = tq + 1) tn = tn + tr_beat_xg[tq];
            $display("    array beats (project)   %0d   (geometry: 128 rows x 32 groups x 4 ocg = 16384)",
                     tn);
            $display("    scat_en     (project)   %0d   (geometry: 128 rows x 128 words = 16384)",
                     tr_scat_p);
            $display("    res_out_valid           %0d", tr_res);
            $display("    RB_OU.wr_en             %0d", tr_ouwr);
            $display("    scat_flush_done project %0d   expand %0d   (128 rows each)",
                     tr_flush_p, tr_flush_e);
            $display("    scat_en     (expand)    %0d   (geometry: 128 x 256 = 32768)",
                     tr_scat_e);
            $display("");
            $display("  the array's output beats per pixel group (project, n_ocg = 4,");
            $display("  so 4 beats x 128 rows = 512 per group is the geometry):");
            for (tq = 0; tq < 40; tq = tq + 4)
                $display("    xg %2d..%2d : %0d %0d %0d %0d", tq, tq+3,
                         tr_beat_xg[tq], tr_beat_xg[tq+1],
                         tr_beat_xg[tq+2], tr_beat_xg[tq+3]);
            tn = 0;
            for (tq = 0; tq < 64; tq = tq + 1) if (tr_beat_xg[tq] != 0) tn = tn + 1;
            $display("    pixel groups the array emitted at all: %0d", tn);
            $display("");
            $display("  THE NAMED MECHANISM -- a group-complete beat arriving while");
            $display("  the previous group's drain is still running. The COLLISION is");
            $display("  structural and does not go away; what a fix changes is whether");
            $display("  the restart survives it, which is the `lost' column:");
            $display("    project : %0d groups, %0d collided, %0d on the drain's LAST read, %0d restarts LOST",
                     tr_grp_p, tr_coll_p, tr_kill_p, tr_lost_p);
            $display("    expand  : %0d groups, %0d collided, %0d on the drain's LAST read, %0d restarts LOST",
                     tr_grp_e, tr_coll_e, tr_kill_e, tr_lost_e);
            $display("    a lost restart costs PIX x nbw = 4 words, so the scatter should");
            $display("    write 16384 - 4 x %0d = %0d words; it wrote %0d.",
                     tr_lost_p, 16384 - 4*tr_lost_p, tr_scat_p);
            $display("  ===============================================");
        end
    endtask
`endif

`ifdef FUSE_FRAME_ISOLATE
    // =====================================================================
    //  FUSE_FRAME_ISOLATE / INJECT: every block is fed the C reference's input
    //
    //  The frame sequencer advances blk only after the previous block's stores
    //  completed (twn_frameseq waits on blk_done), and the next block's loader
    //  starts only after its descriptor has been read, so the zero-time copy
    //  below lands before the first read. That argument is also measured:
    //
    //   1. Image: three baked bytes per block (tb_fuse_map.vh), at HWC offsets
    //      that differ from their CHW offsets, so a missing file or an
    //      untransposed image fails.
    //   2. Address: every activation read beat is classified by arena region;
    //      beats from the block's own input region are compared against the
    //      injected array. A block with no such beat was never fed.
    //   3. No overwrite: write beats into the running block's input slot are
    //      counted (in_slot(b) is out_slot(b-1), so a late burst of block b-1
    //      would clobber the injection).
    //   4. FM_IN_SLOT != FM_OUT_SLOT for every block.
    //   5. FUSE_NEG_INJECT_ZERO (wrong data) and FUSE_NEG_INJECT_SLOT (wrong
    //      address) must turn the gate red.
    // =====================================================================
    integer iso_loads = 0, iso_late = 0;
    // No declaration initialisers on these four: iso_load(0) runs from the main
    // initial block at time 0 and an initialiser could be scheduled after it.
    // They are set in that block, on the line before the call.
    integer iso_prb_ok, iso_prb_bad;
    integer iso_words, iso_for_blk;
    integer iso_wr_in = 0;                   // writes INTO the running block's input slot
    reg [4:0] iso_blk_q = 5'h1F;
    // The reference image is also kept here, so the read-side check compares
    // against something other than the DDR model's own array.
    reg [127:0] iso_gold [0:(FM_SLOT_STRIDE>>4)-1];
    integer izw, izp, izo, izb;
    reg [7:0] izv;

    // ---- load block b's reference input, and prove it is block b's ----
    task iso_load;
        input integer b;
        begin
            $readmemh($sformatf("ddr_in_b%02d.hex", b), iso_gold);
            iso_for_blk = b;
            iso_words   = FM_IN_WORDS[b*32 +: 32];
            for (izp = 0; izp < FM_NPRB; izp = izp + 1) begin
                izo = FM_PRB_OFF[(b*FM_NPRB + izp)*32 +: 32];
                izv = FM_PRB_V [(b*FM_NPRB + izp)*8  +: 8];
                if (iso_gold[izo/16][(izo%16)*8 +: 8] !== izv) begin
                    iso_prb_bad = iso_prb_bad + 1;
                    if (iso_prb_bad < 8)
                        $display("  INJECT: ddr_in_b%02d.hex probe %0d at byte %0d is %02h, the manifest says %02h -- the file is missing, stale, or not this block's",
                                 b, izp, izo, iso_gold[izo/16][(izo%16)*8 +: 8], izv);
                end else iso_prb_ok = iso_prb_ok + 1;
            end
        end
    endtask

    // ---- push it into the arena, at the slot the descriptor says b reads ----
    task iso_push;
        input integer b;
        integer base;
        begin
            base = FM_IN_SLOT[b*4 +: 4];
`ifdef FUSE_NEG_INJECT_SLOT
            // BREAK: the other slot; the injection becomes a no-op.
            base = base ^ 1;
`endif
            base = base * (FM_SLOT_STRIDE >> 4);
            for (izw = 0; izw < iso_words; izw = izw + 1)
`ifdef FUSE_NEG_INJECT_ZERO
                // BREAK: right address, zero bytes.
                DDR_A.mem[base + izw] = 128'd0;
`else
                DDR_A.mem[base + izw] = iso_gold[izw];
`endif
        end
    endtask

    always @(negedge clk) if (!rst) begin
        if (DUT.blk !== iso_blk_q) begin
            iso_blk_q = DUT.blk;
            if (DUT.blk > 0 && DUT.blk < GI_NBLK) begin
                if (a_arvalid || DUT.ARD.busy) iso_late = iso_late + 1;
                iso_load(DUT.blk);
                iso_push(DUT.blk);
                iso_loads = iso_loads + 1;
            end
        end
    end

    // =====================================================================
    //  Read side: did the design consume the injected bytes?
    //
    //  The AR address is carried to the R beats as AW is on the write side.
    //  The block is latched at AR time; a beat of a burst issued before the
    //  boundary belongs to the previous block and is counted as a straggler.
    //  Regions: block 0's input image (words FM_IN_WORD0.., slot FM_NOSLOT),
    //  slot 0 (words 0..16383), slot 1 (words 16384..32767).
    // =====================================================================
    reg [39:0] ra;  reg [8:0] rbeats;  reg ractive = 1'b0;  reg [4:0] rblk;
    integer rd_own [0:GI_NBLK-1];      // beats from THIS block's input region
    integer rd_oth [0:GI_NBLK-1];      // beats from anywhere else in the arena
    integer rd_bad [0:GI_NBLK-1];      // own-region beats that were NOT the reference
    integer rd_strag = 0, rd_unk = 0, rd_overlap = 0, rd_below = 0;
    integer rrel, rslot, rword, rwant, ri;
    initial for (ri = 0; ri < GI_NBLK; ri = ri + 1) begin
        rd_own[ri] = 0; rd_oth[ri] = 0; rd_bad[ri] = 0;
    end

    always @(posedge clk) if (!rst) begin
        if (a_arvalid && a_arready) begin
            // One outstanding read burst is assumed (tb_ddr_model accepts AR
            // only in R_IDLE); counted rather than trusted.
            if (ractive && rbeats != 9'd0) rd_overlap = rd_overlap + 1;
            ra <= a_araddr; rbeats <= {1'b0, a_arlen} + 9'd1;
            ractive <= 1'b1; rblk <= DUT.blk;
        end
        if (a_rvalid && a_rready && ractive) begin
            if (ra < FM_ACT_BASE) rd_below = rd_below + 1;
            else if (rblk < GI_NBLK) begin
                rrel  = ra - FM_ACT_BASE;
                rword = rrel >> 4;
                rwant = FM_IN_SLOT[rblk*4 +: 4];
                if (rwant == FM_NOSLOT) begin
                    // block 0: its input image sits above both slots
                    rslot = (rword >= FM_IN_WORD0) ? FM_NOSLOT : (rrel >> FM_SLOT_LOG2);
                    rword = rword - FM_IN_WORD0;
                end else begin
                    rslot = rrel >> FM_SLOT_LOG2;
                    rword = (rrel & (FM_SLOT_STRIDE - 1)) >> 4;
                end
                if (rslot !== rwant) rd_oth[rblk] = rd_oth[rblk] + 1;
                else if (rblk !== iso_for_blk) rd_strag = rd_strag + 1;
                else begin
                    rd_own[rblk] = rd_own[rblk] + 1;
                    if (rword < iso_words) begin
                        if (a_rdata !== iso_gold[rword]) rd_bad[rblk] = rd_bad[rblk] + 1;
                    end else rd_unk = rd_unk + 1;
                end
            end
            ra <= ra + 40'd16;
            rbeats <= rbeats - 9'd1;
            if (a_rlast || rbeats == 9'd1) ractive <= 1'b0;
        end
        // ---- nothing may write into the running block's INPUT slot ----
        if (a_awvalid && a_awready && DUT.blk < GI_NBLK) begin
            rwant = FM_IN_SLOT[DUT.blk*4 +: 4];
            if (rwant != FM_NOSLOT &&
                ((a_awaddr - FM_ACT_BASE) >> FM_SLOT_LOG2) == rwant)
                iso_wr_in = iso_wr_in + 1;
        end
    end
`endif

    // =====================================================================
    //  Measurement, not a check: how far the loader runs ahead of the project
    //
    //  A residual block adds its input row r to its output row r, so twn_res_buf
    //  must hold input row r from the loader's fetch until the project emits
    //  output row r. ld_row is the next row to load, so the depth needed is
    //  max(ld_row - p_row) + 1. The component distances ld-e, e-d and d-p are
    //  recorded beside it.
    //
    //  The depth chosen from this is watched: res_stale (twn_res_buf's stale
    //  detector) is counted over the frame. The distance is one schedule under
    //  one DDR latency; BFM_RLAT / BFM_STALL give another.
    // =====================================================================
    integer res_stale_cyc = 0;
    always @(posedge clk) if (!rst && DUT.res_stale) res_stale_cyc = res_stale_cyc + 1;

    // =====================================================================
    //  Residual add operands, at twn_res_add's own inputs
    //
    //    x  DUT.res_x   must equal word w of output row r of the block's own
    //                   input image, read from the DDR model at the block's
    //                   input slot (both modes).
    //    p  DUT.rs_p1   must equal the project's output before the add, from
    //                   tb_p4_block_bNN_goldp.hex (ISOLATE only).
    //
    //  Both operands are one register behind the cycle that presented res_rw,
    //  so the indices are captured on the cycle scat_en & arr_out_dst is high
    //  and used on the next. The words seen must equal h_out * (w_out * c_out
    //  / 16) per block (rp_want_n), or the probe is reported as misaligned.
    //
    //  rp_goldp is filled with X before each load, so a missing file compares
    //  unequal everywhere instead of scoring against the previous block.
    // =====================================================================
    localparam integer RP_MAXB = 98304;      // largest residual block output (block 2)
    reg [7:0] rp_goldp [0:RP_MAXB-1];
    integer   rp_have;                       // which block rp_goldp holds, -1 none
    reg [4:0] rp_blkq;

    integer rp_row;                          // project OUTPUT row being emitted
    integer rp_wq, rp_rq, rp_bq;             // indices captured on the last cycle
    reg     rp_vq, rp_hq;
    integer rp_n    [0:GI_NBLK-1];           // words seen at the adder's input
    integer rp_want_n[0:GI_NBLK-1];          // words the geometry says there are
    integer rp_xbad [0:GI_NBLK-1];           // BYTES whose x was not the input row
    integer rp_pbad [0:GI_NBLK-1];           // BYTES whose p was not the reference's
    integer rp_x0   [0:GI_NBLK-1];           // ...of those, in output row 0
    integer rp_p0   [0:GI_NBLK-1];
    integer rp_xf   [0:GI_NBLK-1];           // first offending row*4096 + byte
    integer rp_pf   [0:GI_NBLK-1];
    integer rp_i, rp_j, rp_idx, rp_xx, rp_cc;
    integer rp_c, rp_w, rp_h, rp_roww, rp_base, rp_slot;
    reg [127:0] rp_wantw;
    reg [7:0]   rp_gp;

    // Shape of the wrong p bytes. The project is 1x1, so p(y,x) depends on
    // depthwise pixel (y,x) across c_mid channels only: clustering by pixel
    // column points at the activation, by channel at the weights or requant.
    // got and want are dumped per byte, not just counted.
    localparam integer RP_WMAX = 64;         // widest residual block, in pixels
    localparam integer RP_CMAX = 160;        // deepest residual block, in channels
    localparam integer RP_DUMP = 40;
    integer rp_pcol [0:GI_NBLK*RP_WMAX-1];
    integer rp_pch  [0:GI_NBLK*RP_CMAX-1];
    integer rp_prow [0:GI_NBLK*RP_WMAX-1];   // h_out == w_out on all ten
    integer rp_dn   [0:GI_NBLK-1];
    integer rp_dr   [0:GI_NBLK*RP_DUMP-1];
    integer rp_dx   [0:GI_NBLK*RP_DUMP-1];
    integer rp_dc   [0:GI_NBLK*RP_DUMP-1];
    integer rp_dg   [0:GI_NBLK*RP_DUMP-1];
    integer rp_dwt  [0:GI_NBLK*RP_DUMP-1];

    initial begin
        rp_have = -1; rp_row = 0; rp_vq = 1'b0; rp_hq = 1'b0;
        rp_wq = 0; rp_rq = 0; rp_bq = 0; rp_blkq = 5'h1F;
        for (rp_i = 0; rp_i < GI_NBLK; rp_i = rp_i + 1) begin
            rp_n[rp_i] = 0; rp_xbad[rp_i] = 0; rp_pbad[rp_i] = 0;
            rp_x0[rp_i] = 0; rp_p0[rp_i] = 0;
            rp_xf[rp_i] = -1; rp_pf[rp_i] = -1;
            rp_c = GI_C_OUT[rp_i*10 +: 10];
            rp_w = GI_W_OUT[rp_i*9  +:  9];
            rp_h = GI_H_OUT[rp_i*9  +:  9];
            rp_want_n[rp_i] = rp_h * ((rp_w * rp_c) >> 4);
            rp_dn[rp_i] = 0;
            for (rp_j = 0; rp_j < RP_WMAX; rp_j = rp_j + 1) begin
                rp_pcol[rp_i*RP_WMAX + rp_j] = 0;
                rp_prow[rp_i*RP_WMAX + rp_j] = 0;
            end
            for (rp_j = 0; rp_j < RP_CMAX; rp_j = rp_j + 1)
                rp_pch[rp_i*RP_CMAX + rp_j] = 0;
        end
    end

`ifdef FUSE_FRAME_ISOLATE
    always @(negedge clk) if (!rst) begin
        if (DUT.blk !== rp_blkq) begin
            rp_blkq = DUT.blk;
            rp_have = -1;
            if (DUT.blk < GI_NBLK && FM_HAS_RES[DUT.blk]) begin
                for (rp_i = 0; rp_i < RP_MAXB; rp_i = rp_i + 1) rp_goldp[rp_i] = 8'hxx;
                $readmemh($sformatf("tb_p4_block_b%02d_goldp.hex", DUT.blk), rp_goldp);
                rp_have = DUT.blk;
            end
        end
    end
`endif

    always @(posedge clk) if (!rst) begin
        // ---- last cycle's indices, now that both operands have arrived ----
        if (rp_vq && rp_hq && rp_bq < GI_NBLK) begin
            // through integer: w_out * c_out does not fit the part-select widths
            rp_c    = GI_C_OUT[rp_bq*10 +: 10];
            rp_w    = GI_W_OUT[rp_bq*9  +:  9];
            rp_h    = GI_H_OUT[rp_bq*9  +:  9];
            rp_roww = (rp_w * rp_c) >> 4;
            rp_slot = FM_IN_SLOT[rp_bq*4 +: 4];
            rp_base = rp_slot * (FM_SLOT_STRIDE >> 4);
`ifdef FUSE_NEG_RESPROBE
            // BREAK: both references taken one row later than asked; the
            // probe must go red on every residual block.
            rp_rq = rp_rq + 1;
`endif
            rp_wantw = DDR_A.mem[rp_base + rp_rq * rp_roww + rp_wq];
            rp_n[rp_bq] = rp_n[rp_bq] + 1;
            for (rp_j = 0; rp_j < 16; rp_j = rp_j + 1) begin
                if (DUT.res_x[rp_j*8 +: 8] !== rp_wantw[rp_j*8 +: 8]) begin
                    rp_xbad[rp_bq] = rp_xbad[rp_bq] + 1;
                    if (rp_rq == 0) rp_x0[rp_bq] = rp_x0[rp_bq] + 1;
                    if (rp_xf[rp_bq] < 0)
                        rp_xf[rp_bq] = rp_rq * 4096 + rp_wq * 16 + rp_j;
                end
`ifdef FUSE_FRAME_ISOLATE
                if (rp_have == rp_bq) begin
                    rp_idx = rp_wq * 16 + rp_j;
                    rp_xx  = rp_idx / rp_c;
                    rp_cc  = rp_idx % rp_c;
                    rp_gp  = rp_goldp[(rp_cc * rp_h + rp_rq) * rp_w + rp_xx];
                    if (DUT.rs_p1[rp_j*8 +: 8] !== rp_gp) begin
                        rp_pbad[rp_bq] = rp_pbad[rp_bq] + 1;
                        if (rp_rq == 0) rp_p0[rp_bq] = rp_p0[rp_bq] + 1;
                        if (rp_pf[rp_bq] < 0)
                            rp_pf[rp_bq] = rp_rq * 4096 + rp_wq * 16 + rp_j;
                        if (rp_xx < RP_WMAX)
                            rp_pcol[rp_bq*RP_WMAX + rp_xx] = rp_pcol[rp_bq*RP_WMAX + rp_xx] + 1;
                        if (rp_rq < RP_WMAX)
                            rp_prow[rp_bq*RP_WMAX + rp_rq] = rp_prow[rp_bq*RP_WMAX + rp_rq] + 1;
                        if (rp_cc < RP_CMAX)
                            rp_pch[rp_bq*RP_CMAX + rp_cc] = rp_pch[rp_bq*RP_CMAX + rp_cc] + 1;
                        if (rp_dn[rp_bq] < RP_DUMP) begin
                            rp_dr [rp_bq*RP_DUMP + rp_dn[rp_bq]] = rp_rq;
                            rp_dx [rp_bq*RP_DUMP + rp_dn[rp_bq]] = rp_xx;
                            rp_dc [rp_bq*RP_DUMP + rp_dn[rp_bq]] = rp_cc;
                            rp_dg [rp_bq*RP_DUMP + rp_dn[rp_bq]] = $signed(DUT.rs_p1[rp_j*8 +: 8]);
                            rp_dwt[rp_bq*RP_DUMP + rp_dn[rp_bq]] = $signed(rp_gp);
                            rp_dn [rp_bq] = rp_dn[rp_bq] + 1;
                        end
                    end
                end
`endif
            end
        end
        // ---- capture this cycle's, for the next one ----
        rp_vq = DUT.scat_en & DUT.arr_out_dst;
        rp_hq = DUT.has_res;
        rp_wq = DUT.res_rw;
        rp_rq = rp_row;
        rp_bq = DUT.blk;
        if (DUT.blk_start)                                 rp_row = 0;
        else if (DUT.scat_flush_done & DUT.arr_out_dst)    rp_row = rp_row + 1;
    end

    // ---- the write side of twn_res_buf ----
    // w_word saturates at ROW_WORDS-1, so a loader delivering more beats per
    // row than the row has words rewrites the row's last word. rb_maxw records
    // the highest w_word reached at each row end.
    // failure being chased, so it is measured rather than argued about.
    integer rb_rows [0:GI_NBLK-1];
    integer rb_maxw [0:GI_NBLK-1];
    integer rb_i, rb_ww;
    initial for (rb_i = 0; rb_i < GI_NBLK; rb_i = rb_i + 1) begin
        rb_rows[rb_i] = 0; rb_maxw[rb_i] = -1;
    end
    // Through an integer: comparing the 16-bit unsigned w_word with an integer
    // holding -1 promotes -1 to 4,294,967,295 and the test is never true.
    always @(posedge clk) if (!rst && DUT.blk < GI_NBLK && DUT.ld_done) begin
        rb_rows[DUT.blk] = rb_rows[DUT.blk] + 1;
        rb_ww = DUT.RESB.w_word;
        if (rb_ww > rb_maxw[DUT.blk]) rb_maxw[DUT.blk] = rb_ww;
    end

    // =====================================================================
    //  Ring geometry the probes reconstruct addresses with
    //
    //  Copies of twn_fuse_top constants, kept independent of the design's own
    //  arithmetic; geom_check compares them with the DUT. At module scope so
    //  that the check runs in every mode.
    // =====================================================================
    localparam integer RC_WORDS = 73;         // twn_fuse_top's C_WORDS
    localparam integer RA_WORDS = 17;         // twn_fuse_top's A_WORDS
`ifdef FUSE_CC_ROWS3
    localparam integer RC_ROWS  = 3;          // twn_fuse_top's CC_ROWS
`else
    localparam integer RC_ROWS  = 2;          // twn_fuse_top's CC_ROWS
`endif
`ifdef FUSE_ARING_D4
    localparam integer RA_ROWS  = 4;          // twn_fuse_top's AC_ROWS
`elsif FUSE_ARING_D8
    localparam integer RA_ROWS  = 8;
`else
    localparam integer RA_ROWS  = 16;
`endif
    // RB_C's MEM_BASE: AC_ROWS * A_WORDS.
    localparam integer RC_BASE   = RA_ROWS * RA_WORDS;
    localparam integer AC_TOT_TB = RA_ROWS * RA_WORDS + RC_ROWS * RC_WORDS;

    task geom_check;
        begin
            if (RA_WORDS != DUT.A_WORDS)
                fail($sformatf("instrument geometry: RA_WORDS %0d but the design's A_WORDS is %0d -- every RingC address this gate computes is wrong", RA_WORDS, DUT.A_WORDS));
            if (RC_WORDS != DUT.C_WORDS)
                fail($sformatf("instrument geometry: RC_WORDS %0d but the design's C_WORDS is %0d", RC_WORDS, DUT.C_WORDS));
            if (RA_ROWS != DUT.AC_ROWS)
                fail($sformatf("instrument geometry: RA_ROWS %0d but the design's AC_ROWS is %0d -- the RingA residency probe will report fabricated overwrites", RA_ROWS, DUT.AC_ROWS));
            if (RC_ROWS != DUT.CC_ROWS)
                fail($sformatf("instrument geometry: RC_ROWS %0d but the design's CC_ROWS is %0d", RC_ROWS, DUT.CC_ROWS));
            if (AC_TOT_TB != DUT.AC_TOT)
                fail($sformatf("instrument geometry: AC_TOT_TB %0d but the design's AC_TOT is %0d -- the zero-fill leaves %0d words X", AC_TOT_TB, DUT.AC_TOT, DUT.AC_TOT - AC_TOT_TB));
            checks = checks + 1;
            // Printed whatever the verdict, so the log carries the geometry used.
            $display("  ring geometry: RingA %0d x %0d @ 0, RingC %0d x %0d @ %0d, array %0d words (checked against the design)",
                     RA_ROWS, RA_WORDS, RC_ROWS, RC_WORDS, RC_BASE, AC_TOT_TB);
        end
    endtask

`ifdef FUSE_FRAME_ISOLATE
    // =====================================================================
    //  Did the project read the right activation? (ISOLATE; measurement)
    //
    //  Compares twn_fuse_array's act_data, on the cycle gath_done is high and
    //  the array latches it, against the depthwise tensor
    //  (tb_p4_block_bNN_goldd.hex) at the request's (row, xg, seg). One
    //  request is assumed outstanding at a time (twn_fuse_array), so the tuple
    //  is captured on act_re and consumed on the valid.
    //
    //  act_data is PIX pixels x LANES channels, byte pix*128 + lane; it is zero
    //  where the channel is >= c_mid or the column >= w. Blocks whose p is clean
    //  are the control for the layout; mismatches there mean the probe is wrong.
    // =====================================================================
    localparam integer AG_MAXD = 589824;      // block 2's depthwise tensor
    localparam integer AG_DUMP = 8;
    reg [7:0] ag_goldd [0:AG_MAXD-1];
    integer   ag_have;
    reg [4:0] ag_blkq;
    integer ag_xg, ag_seg, ag_row, ag_blk;
    reg     ag_role, ag_pend;
    integer ag_n   [0:GI_NBLK-1];             // project activation words checked
    integer ag_bad [0:GI_NBLK-1];             // bytes that were not the depthwise's
    integer ag_r0  [0:GI_NBLK-1];             // ...of those, for output row 0
    integer ag_dn  [0:GI_NBLK-1];
    integer ag_dr  [0:GI_NBLK*AG_DUMP-1], ag_dxg[0:GI_NBLK*AG_DUMP-1];
    integer ag_dsg [0:GI_NBLK*AG_DUMP-1], ag_dby[0:GI_NBLK*AG_DUMP-1];
    integer ag_dgo [0:GI_NBLK*AG_DUMP-1], ag_dwa[0:GI_NBLK*AG_DUMP-1];
    integer ag_i, ag_px, ag_ln, ag_cc, ag_xx, ag_cm, ag_h, ag_w, ag_k;
    reg [7:0] ag_want;

    initial begin
        ag_have = -1; ag_blkq = 5'h1F; ag_pend = 1'b0; ag_role = 1'b0;
        ag_xg = 0; ag_seg = 0; ag_row = 0; ag_blk = 0;
        for (ag_k = 0; ag_k < GI_NBLK; ag_k = ag_k + 1) begin
            ag_n[ag_k] = 0; ag_bad[ag_k] = 0; ag_r0[ag_k] = 0; ag_dn[ag_k] = 0;
        end
    end

    always @(negedge clk) if (!rst) begin
        if (DUT.blk !== ag_blkq) begin
            ag_blkq = DUT.blk;
            ag_have = -1;
            if (DUT.blk < GI_NBLK && FM_HAS_RES[DUT.blk]) begin
                for (ag_k = 0; ag_k < AG_MAXD; ag_k = ag_k + 1) ag_goldd[ag_k] = 8'hxx;
                $readmemh($sformatf("tb_p4_block_b%02d_goldd.hex", DUT.blk), ag_goldd);
                ag_have = DUT.blk;
            end
        end
    end

    always @(posedge clk) if (!rst) begin
        if (ag_pend && (DUT.gath_done === 1'b1)) begin
            if (ag_role && ag_blk < GI_NBLK && ag_have == ag_blk) begin
                ag_cm = FM_C_MID[ag_blk*10 +: 10];
                ag_h  = GI_H_OUT[ag_blk*9  +:  9];
                ag_w  = GI_W_OUT[ag_blk*9  +:  9];
                ag_n[ag_blk] = ag_n[ag_blk] + 1;
                for (ag_i = 0; ag_i < 512; ag_i = ag_i + 1) begin
                    ag_px = ag_i / 128;
                    ag_ln = ag_i % 128;
                    ag_cc = ag_seg * 128 + ag_ln;
                    ag_xx = ag_xg * 4 + ag_px;
                    if (ag_cc >= ag_cm || ag_xx >= ag_w) ag_want = 8'h00;
                    else ag_want = ag_goldd[(ag_cc * ag_h + ag_row) * ag_w + ag_xx];
                    if (DUT.act_data[ag_i*8 +: 8] !== ag_want) begin
                        ag_bad[ag_blk] = ag_bad[ag_blk] + 1;
                        if (ag_row == 0) ag_r0[ag_blk] = ag_r0[ag_blk] + 1;
                        if (ag_dn[ag_blk] < AG_DUMP) begin
                            ag_dr [ag_blk*AG_DUMP + ag_dn[ag_blk]] = ag_row;
                            ag_dxg[ag_blk*AG_DUMP + ag_dn[ag_blk]] = ag_xg;
                            ag_dsg[ag_blk*AG_DUMP + ag_dn[ag_blk]] = ag_seg;
                            ag_dby[ag_blk*AG_DUMP + ag_dn[ag_blk]] = ag_i;
                            ag_dgo[ag_blk*AG_DUMP + ag_dn[ag_blk]] = DUT.act_data[ag_i*8 +: 8];
                            ag_dwa[ag_blk*AG_DUMP + ag_dn[ag_blk]] = ag_want;
                            ag_dn [ag_blk] = ag_dn[ag_blk] + 1;
                        end
                    end
                end
            end
            ag_pend = 1'b0;
        end
        if (DUT.act_re === 1'b1) begin
            ag_pend = 1'b1;
            ag_xg   = DUT.act_xg;
            ag_seg  = DUT.act_seg;
            ag_row  = DUT.p_row;
            ag_role = DUT.role_q;
            ag_blk  = DUT.blk;
        end
    end

    // =====================================================================
    //  The links between the depthwise and the project, one at a time
    //
    //    R0  address model: RingC word w of row r is at
    //        RC_BASE + (r % RC_ROWS)*RC_WORDS + w. Checked against the design's
    //        own write address (c_xwa) on every depthwise write; if it fires,
    //        R1..R3 are measuring the wrong words.
    //    R1  memory: three cycles after RingC declares a row done, it holds
    //        the depthwise's row.                           (write side)
    //    R2  address: a project read goes to the word the gather asked for, in
    //        the slot of p_row.                             (RB_C's decode)
    //    R3  capture: twn_act_gather's lo / hi equal the memory at need_w and
    //        need_w+1 on the emit cycle.                    (fetch and cache)
    //    R4  nothing writes into the RingC row the project owns the array to
    //        read.
    //    R5  (measured) cycles in which RingC has counted fewer rows than the
    //        sequencer.
    //
    //  Blocks whose p is clean are the control for R1..R3.
    // =====================================================================
    localparam integer RC_DUMP  = 10;

    integer rc_wa_bad = 0, rc_ra_bad = 0;     // R0 / R2
    integer rc_ra_n   = 0;
    integer rc_bad [0:GI_NBLK-1];             // R1: bytes of RingC not the row
    integer rc_r0  [0:GI_NBLK-1];             // ... of those, row 0
    integer rc_rows[0:GI_NBLK-1];             // rows scanned
    integer rc_lo  [0:GI_NBLK-1];             // R3: `lo` != memory at need_w
    integer rc_hi  [0:GI_NBLK-1];             // R3: `hi` != memory at need_w+1
    integer rc_idx [0:GI_NBLK-1];             // R3: hi_idx != need_w+1
    integer rc_n3  [0:GI_NBLK-1];             // R3: pixels scored
    integer rc_dn  [0:GI_NBLK-1];
    integer rc_dr  [0:GI_NBLK*RC_DUMP-1], rc_dw [0:GI_NBLK*RC_DUMP-1];
    integer rc_db  [0:GI_NBLK*RC_DUMP-1], rc_dg [0:GI_NBLK*RC_DUMP-1];
    integer rc_dwt [0:GI_NBLK*RC_DUMP-1];
    integer rc_pend, rc_row, rc_blk, rc_k, rc_w, rc_i, rc_off, rc_x, rc_c;
    integer rc_cm, rc_h, rc_ww, rc_nw, rc_ea;
    // R3 has its own temporaries: R1 and R3 are separate always blocks on the
    // same edge and a shared integer would race.
    integer rc_cm3, rc_ww3, rc_nwr;
    reg [7:0] rc_want;

    initial begin
        rc_pend = 0; rc_row = 0; rc_blk = 0;
        for (rc_k = 0; rc_k < GI_NBLK; rc_k = rc_k + 1) begin
            rc_bad[rc_k] = 0; rc_r0[rc_k] = 0; rc_rows[rc_k] = 0;
            rc_lo[rc_k] = 0; rc_hi[rc_k] = 0; rc_idx[rc_k] = 0;
            rc_n3[rc_k] = 0; rc_dn[rc_k] = 0;
        end
    end

    // ---- R0: the address model, against the design's own write address ----
    always @(posedge clk) if (!rst) begin
        if (DUT.c_xwe === 1'b1) begin
            rc_ea = RC_BASE + (DUT.RB_C.wptr_r % RC_ROWS) * RC_WORDS
                  + DUT.dwp_word[$clog2(72)-1:0];
            if (DUT.c_xwa !== rc_ea[15:0]) rc_wa_bad = rc_wa_bad + 1;
        end
        // ---- R2: where a PROJECT read actually goes ----
        if ((DUT.gath_re === 1'b1) && (DUT.role_q === 1'b1)) begin
            rc_ra_n = rc_ra_n + 1;
            rc_ea = RC_BASE + (DUT.p_row % RC_ROWS) * RC_WORDS
                  + DUT.gath_word[$clog2(72)-1:0];
            if (DUT.m_ra !== rc_ea[15:0]) rc_ra_bad = rc_ra_bad + 1;
        end
    end

    // ---- R1: is RingC row r the depthwise's row r, when it is declared done? ----
    always @(posedge clk) if (!rst) begin
        if (rc_pend == 1 && rc_blk < GI_NBLK && ag_have == rc_blk) begin
            rc_cm = FM_C_MID[rc_blk*10 +: 10];
            rc_h  = GI_H_OUT[rc_blk*9  +:  9];
            rc_ww = GI_W_OUT[rc_blk*9  +:  9];
            rc_nw = (rc_ww * rc_cm + 127) / 128;
            rc_rows[rc_blk] = rc_rows[rc_blk] + 1;
            for (rc_w = 0; rc_w < rc_nw; rc_w = rc_w + 1)
              for (rc_i = 0; rc_i < 128; rc_i = rc_i + 1) begin
                rc_off = rc_w * 128 + rc_i;
                if (rc_off < rc_ww * rc_cm) begin
                    rc_x = rc_off / rc_cm;
                    rc_c = rc_off % rc_cm;
                    rc_want = ag_goldd[(rc_c * rc_h + rc_row) * rc_ww + rc_x];
                    if (DUT.acmem[RC_BASE + (rc_row % RC_ROWS) * RC_WORDS + rc_w]
                                 [rc_i*8 +: 8] !== rc_want) begin
                        rc_bad[rc_blk] = rc_bad[rc_blk] + 1;
                        if (rc_row == 0) rc_r0[rc_blk] = rc_r0[rc_blk] + 1;
                        if (rc_dn[rc_blk] < RC_DUMP) begin
                            rc_dr [rc_blk*RC_DUMP + rc_dn[rc_blk]] = rc_row;
                            rc_dw [rc_blk*RC_DUMP + rc_dn[rc_blk]] = rc_w;
                            rc_db [rc_blk*RC_DUMP + rc_dn[rc_blk]] = rc_i;
                            rc_dg [rc_blk*RC_DUMP + rc_dn[rc_blk]] =
                                DUT.acmem[RC_BASE + (rc_row % RC_ROWS) * RC_WORDS + rc_w][rc_i*8 +: 8];
                            rc_dwt[rc_blk*RC_DUMP + rc_dn[rc_blk]] = rc_want;
                            rc_dn [rc_blk] = rc_dn[rc_blk] + 1;
                        end
                    end
                end
              end
        end
        if (rc_pend > 0) rc_pend = rc_pend - 1;
        if (DUT.dwp_row_done === 1'b1) begin
            rc_row = DUT.RB_C.wptr_r; rc_blk = DUT.blk; rc_pend = 3;
        end
    end

    // ---- R3: does the gather hold the memory's own two words? ----
    // S_EMIT (GATH.st == 4) with j == 0 is the first cycle of a pixel's emit,
    // where hi_idx is expected to equal need_w + 1: `lo` is the run's first
    // word and `hi` the next. The word past the row's end is not scored (the
    // gather fetches it unconditionally; its bytes are beyond run_len).
    //
    // A mismatch is either stale (the word was written after the capture) or
    // wrong bytes. w_last records the cycle of each acmem word's last write and
    // cap_lo_c / cap_hi_c the cycle each of lo / hi was captured, so the two
    // can be told apart. R4 asks the same question without that mirror.
    integer rc_cyc = 0;
    integer w_last [0:AC_TOT_TB-1];           // cycle of the last write, per word
    integer cap_hi_c, cap_lo_c;               // cycle `hi` / `lo` were captured
    integer rc_wr_live [0:GI_NBLK-1];         // R4
    integer rc_cdn [0:GI_NBLK-1];             // capture dumps printed, per block
    integer rc_a, rc_nb, rc_fb, rc_bt, rc_wl, rc_cc, rc_lorow;
    integer rc_i3, rc_z;
    integer rc_skew_n = 0, rc_skew_run = 0, rc_skew_max = 0;   // R5
    reg [1023:0] rc_mem;

    initial begin
        cap_hi_c = -1; cap_lo_c = -1;
        for (rc_z = 0; rc_z < AC_TOT_TB; rc_z = rc_z + 1) w_last[rc_z] = -1;
        for (rc_z = 0; rc_z < GI_NBLK; rc_z = rc_z + 1) begin
            rc_wr_live[rc_z] = 0; rc_cdn[rc_z] = 0;
        end
    end

    always @(posedge clk) if (!rst) begin
        rc_cyc = rc_cyc + 1;

        // ---- R3, read BEFORE this cycle's ledger updates ----
        if ((DUT.GATH.st === 3'd4) && (DUT.GATH.j === 2'd0) &&
            (DUT.role_q === 1'b1) && (DUT.blk < GI_NBLK) && (ag_have == DUT.blk)) begin
            rc_cm3 = FM_C_MID[DUT.blk*10 +: 10];
            rc_ww3 = GI_W_OUT[DUT.blk*9  +:  9];
            rc_nwr = (rc_ww3 * rc_cm3 + 127) / 128;
            rc_lorow = RC_BASE + (DUT.p_row % RC_ROWS) * RC_WORDS;
            rc_n3[DUT.blk] = rc_n3[DUT.blk] + 1;
            if (DUT.GATH.hi_idx !== (DUT.GATH.need_w + 16'd1))
                rc_idx[DUT.blk] = rc_idx[DUT.blk] + 1;
            for (rc_i3 = 0; rc_i3 < 2; rc_i3 = rc_i3 + 1) begin
                rc_a  = rc_lorow + DUT.GATH.need_w + rc_i3;
                rc_cc = (rc_i3 == 0) ? cap_lo_c : cap_hi_c;
                if ((DUT.GATH.need_w + rc_i3) < rc_nwr) begin
                    rc_mem = DUT.acmem[rc_a];
                    if ((rc_i3 == 0) ? (DUT.GATH.lo !== rc_mem)
                                     : (DUT.GATH.hi !== rc_mem)) begin
                        if (rc_i3 == 0) rc_lo[DUT.blk] = rc_lo[DUT.blk] + 1;
                        else            rc_hi[DUT.blk] = rc_hi[DUT.blk] + 1;
                        rc_nb = 0; rc_fb = -1;
                        for (rc_z = 0; rc_z < 128; rc_z = rc_z + 1) begin
                            rc_bt = (rc_i3 == 0) ? DUT.GATH.lo[rc_z*8 +: 8]
                                                 : DUT.GATH.hi[rc_z*8 +: 8];
                            if (rc_bt !== rc_mem[rc_z*8 +: 8]) begin
                                rc_nb = rc_nb + 1;
                                if (rc_fb < 0) rc_fb = rc_z;
                            end
                        end
                        rc_wl = w_last[rc_a];
                        if (rc_cdn[DUT.blk] < RC_DUMP) begin
                            $display("    CAPTURE blk %0d %0s p_row %0d xg %0d seg %0d pix %0d need_w %0d addr %0d : %0d of 128 bytes differ, first byte %0d (lane %0d) -- captured on cycle %0d, that word was last written on cycle %0d, now %0d; d_row %0d dw_wptr %0d",
                                     DUT.blk, (rc_i3 == 0) ? "lo" : "hi",
                                     DUT.p_row, DUT.act_xg, DUT.act_seg, DUT.GATH.p,
                                     DUT.GATH.need_w + rc_i3, rc_a, rc_nb, rc_fb,
                                     rc_fb / 8, rc_cc, rc_wl, rc_cyc,
                                     DUT.d_row, DUT.dw_wptr);
                            rc_cdn[DUT.blk] = rc_cdn[DUT.blk] + 1;
                        end
                    end
                end
            end
        end

        // ---- the capture mirror: `hi` takes the memory, `lo` takes the old `hi` ----
        if ((DUT.GATH.st === 3'd3) && (DUT.GATH.rb_re_d === 1'b1)) begin
            cap_lo_c = cap_hi_c; cap_hi_c = rc_cyc;
        end

        // ---- the write ledger, and R4 ----
        if (DUT.m_we === 1'b1) begin
            w_last[DUT.m_wa] = rc_cyc;
            if ((DUT.SEQ.own_p === 1'b1) && (DUT.blk < GI_NBLK)) begin
                rc_lorow = RC_BASE + (DUT.p_row % RC_ROWS) * RC_WORDS;
                if ((DUT.m_wa >= rc_lorow) && (DUT.m_wa < (rc_lorow + RC_WORDS)))
                    rc_wr_live[DUT.blk] = rc_wr_live[DUT.blk] + 1;
            end
        end

        // ---- R5: d_row counts rows the depthwise has finished, dw_wptr rows
        //      RingC has taken; they differ only while a row end is in flight.
        //      The width of that window is measured per row end. ----
        if (DUT.seq_busy === 1'b1) begin
            if (DUT.dw_wptr < DUT.d_row) begin
                rc_skew_n   = rc_skew_n + 1;
                rc_skew_run = rc_skew_run + 1;
                if (rc_skew_run > rc_skew_max) rc_skew_max = rc_skew_run;
            end else rc_skew_run = 0;
        end else rc_skew_run = 0;
    end

    // =====================================================================
    //  FUSE_RBC_READ -- RB_C's own read port (inside FUSE_FRAME_ISOLATE)
    //
    //  Checks the 1024-bit ac_rd at (p_row, gath_word) against bytes
    //  row*(W*c_mid) + word*128 .. +127 of the depthwise tensor, to separate a
    //  wrong ring read from a wrong assembly in the gather. The read latency
    //  is not assumed: lags 0..3 are scored side by side, and the lag whose
    //  count is zero on the blocks with clean p is taken as calibrated; if
    //  none is, the probe fails and its result is withheld. Opt-in; the
    //  runner's header lists it as not yet calibrated. ac_rd is shared with
    //  RingA, so only requests that were project reads are scored.
    // =====================================================================
`ifdef FUSE_RBC_READ
    localparam integer CR_LAGS = 4;           // lags 0..3
    integer cr_row [0:CR_LAGS];               // request pipeline, one per cycle
    integer cr_wd  [0:CR_LAGS];
    integer cr_bk  [0:CR_LAGS];
    reg     cr_v   [0:CR_LAGS];
    integer cr_bad [0:GI_NBLK*CR_LAGS-1];
    integer cr_n   [0:GI_NBLK*CR_LAGS-1];
    integer cr_i, cr_j, cr_off, cr_c, cr_x, cr_cm, cr_h, cr_w;
    reg [7:0] cr_want;

    initial begin
        for (cr_i = 0; cr_i <= CR_LAGS; cr_i = cr_i + 1) begin
            cr_row[cr_i] = 0; cr_wd[cr_i] = 0; cr_bk[cr_i] = 0; cr_v[cr_i] = 1'b0;
        end
        for (cr_i = 0; cr_i < GI_NBLK*CR_LAGS; cr_i = cr_i + 1) begin
            cr_bad[cr_i] = 0; cr_n[cr_i] = 0;
        end
    end

    always @(posedge clk) if (!rst) begin
        for (cr_j = 0; cr_j < CR_LAGS; cr_j = cr_j + 1)
          if (cr_v[cr_j] && cr_bk[cr_j] < GI_NBLK && ag_have == cr_bk[cr_j]) begin
            cr_cm = FM_C_MID[cr_bk[cr_j]*10 +: 10];
            cr_h  = GI_H_OUT[cr_bk[cr_j]*9  +:  9];
            cr_w  = GI_W_OUT[cr_bk[cr_j]*9  +:  9];
            cr_n[cr_bk[cr_j]*CR_LAGS + cr_j] = cr_n[cr_bk[cr_j]*CR_LAGS + cr_j] + 1;
            for (cr_i = 0; cr_i < 128; cr_i = cr_i + 1) begin
                cr_off = cr_wd[cr_j] * 128 + cr_i;
                if (cr_off >= cr_w * cr_cm) cr_want = 8'h00;
                else begin
                    cr_x = cr_off / cr_cm;
                    cr_c = cr_off % cr_cm;
                    cr_want = ag_goldd[(cr_c * cr_h + cr_row[cr_j]) * cr_w + cr_x];
                end
                if (DUT.ac_rd[cr_i*8 +: 8] !== cr_want)
                    cr_bad[cr_bk[cr_j]*CR_LAGS + cr_j] =
                        cr_bad[cr_bk[cr_j]*CR_LAGS + cr_j] + 1;
            end
        end
        for (cr_j = CR_LAGS; cr_j > 0; cr_j = cr_j - 1) begin
            cr_row[cr_j] = cr_row[cr_j-1]; cr_wd[cr_j] = cr_wd[cr_j-1];
            cr_bk [cr_j] = cr_bk [cr_j-1]; cr_v [cr_j] = cr_v [cr_j-1];
        end
        cr_v[0]   = (DUT.gath_re === 1'b1) && (DUT.role_q === 1'b1);
        cr_row[0] = DUT.p_row;
        cr_wd[0]  = DUT.gath_word;
        cr_bk[0]  = DUT.blk;
    end
`endif
`endif

    // =====================================================================
    //  The delayed RingC row end is conserved
    //
    //  twn_fuse_top delays d_done by one cycle into RB_C's wr_row_done
    //  (dwp_row_done), and blk_start clears that register: a row end in flight
    //  at a block boundary would be swallowed and RingC's write pointer left
    //  one row short. Over the frame the two counts must be equal.
    // =====================================================================
    integer dd_n = 0, dwpd_n = 0;
    always @(posedge clk) if (!rst) begin
        if (DUT.d_done)        dd_n   = dd_n   + 1;
        if (DUT.dwp_row_done)  dwpd_n = dwpd_n + 1;
    end

    integer maxd_blk [0:GI_NBLK-1];       // ld_row - p_row, per block
    integer maxle_blk[0:GI_NBLK-1];       // ld_row - e_row
    integer maxed_blk[0:GI_NBLK-1];       // e_row  - d_row
    integer maxdp_blk[0:GI_NBLK-1];       // d_row  - p_row
    integer maxd_all, mq, dd;

    initial begin
        maxd_all = 0;
        for (mq = 0; mq < GI_NBLK; mq = mq + 1) begin
            maxd_blk[mq]  = 0; maxle_blk[mq] = 0;
            maxed_blk[mq] = 0; maxdp_blk[mq] = 0;
        end
    end

    // seq_busy, so the cycles between blocks -- where every counter is zero and
    // one of them has already been reset -- cannot contribute a spurious maximum.
    always @(posedge clk) if (!rst && DUT.seq_busy && DUT.blk < GI_NBLK) begin
        dd = DUT.ld_row - DUT.p_row;
        if (dd > maxd_blk[DUT.blk]) maxd_blk[DUT.blk] = dd;
        // Worst case over the blocks that have a residual only: twn_res_buf
        // is read only when has_res.
        if (FM_HAS_RES[DUT.blk] && dd > maxd_all) maxd_all = dd;
        dd = DUT.ld_row - DUT.e_row;
        if (dd > maxle_blk[DUT.blk]) maxle_blk[DUT.blk] = dd;
        dd = DUT.e_row - DUT.d_row;
        if (dd > maxed_blk[DUT.blk]) maxed_blk[DUT.blk] = dd;
        dd = DUT.d_row - DUT.p_row;
        if (dd > maxdp_blk[DUT.blk]) maxdp_blk[DUT.blk] = dd;
    end

    // =====================================================================
    //  RingA residency gate -- every block, every expand read
    //
    //  RingA is DEPTH AC_ROWS with slot = row % AC_ROWS, so row n is resident
    //  for wptr - AC_ROWS <= n < wptr. A read outside it is early (not yet
    //  written) or overwritten (the row AC_ROWS later took its slot). The
    //  window is stated against the write pointer, not against `free`.
    //
    //  rptr is checked separately: a read below rptr is of a row the
    //  bookkeeping has already released, so the loader may overwrite it
    //  whether or not it did in this run.
    //
    //  ra_deep = max(wptr-1 - row) is how far back the expand reaches;
    //  AC_ROWS must exceed it. The stem's top-pad pass is excluded: the
    //  gather zeroes those bytes.
    // =====================================================================
    // RingA's depth; geom_check ties RA_ROWS to the design's AC_ROWS.
    localparam integer RA_DEPTH = RA_ROWS;    // twn_fuse_top's AC_ROWS
    integer ra_rd  [0:GI_NBLK-1];             // expand reads of RingA
    integer ra_ovr [0:GI_NBLK-1];             // ... of a row already overwritten
    integer ra_erl [0:GI_NBLK-1];             // ... of a row not yet written
    integer ra_rel [0:GI_NBLK-1];             // ... of a row rptr has released
    integer ra_deep[0:GI_NBLK-1];             // max(wptr-1 - rd_row), rows back
    integer ra_i, ra_row, ra_wp, ra_rp, ra_d, ra_bad, ra_relbad;
    initial for (ra_i = 0; ra_i < GI_NBLK; ra_i = ra_i + 1) begin
        ra_rd[ra_i] = 0; ra_ovr[ra_i] = 0; ra_erl[ra_i] = 0;
        ra_rel[ra_i] = 0; ra_deep[ra_i] = -1;
    end

    always @(posedge clk)
        if (!rst && DUT.seq_busy && (DUT.blk < GI_NBLK) &&
            (DUT.gath_re === 1'b1) && (DUT.role_q === 1'b0) &&
            (DUT.e_top_pad !== 1'b1)) begin
            // through `integer` first: these are 10-bit unsigned wires and the
            // differences below are meant to be able to go negative.
            ra_row = DUT.e_rd_row;
            ra_wp  = DUT.in_wptr;
            ra_rp  = DUT.RB_A.rptr_r;
            ra_rd[DUT.blk] = ra_rd[DUT.blk] + 1;
            if (ra_row >= ra_wp)                    ra_erl[DUT.blk] = ra_erl[DUT.blk] + 1;
            else if ((ra_wp - ra_row) > RA_DEPTH)   ra_ovr[DUT.blk] = ra_ovr[DUT.blk] + 1;
            if (ra_row < ra_rp)                     ra_rel[DUT.blk] = ra_rel[DUT.blk] + 1;
            ra_d = ra_wp - 1 - ra_row;
            if (ra_d > ra_deep[DUT.blk]) ra_deep[DUT.blk] = ra_d;
        end

`ifdef FUSE_BLK_CYC
    // =====================================================================
    //  FUSE_BLK_CYC -- per-block attribution of the array's idle time
    //
    //  twn_blockseq's cycle counters are frame-scoped (cleared by cyc_clr,
    //  driven by ap_start), so the per-block values are recovered by sampling
    //  at the rising edge of each block's done and differencing. The why_*
    //  counters are cleared on each block's start and are read, not
    //  differenced.
    // =====================================================================
    integer bc_tot [0:31], bc_arr [0:31], bc_dw  [0:31], bc_stl [0:31];
    integer bc_pre [0:31], bc_post[0:31], bc_blk [0:31];
    integer bc_wel [0:31], bc_wet [0:31], bc_wpd [0:31], bc_wpo [0:31];
    integer bc_n, bc_i;
    integer bc_ptot, bc_parr, bc_pdw, bc_pstl, bc_ppre, bc_ppost;
    reg [4:0] bc_curblk;
    reg       bc_done_q;

    // ---- issue, as opposed to grant ----
    // cyc_array counts the cycles E or P held the array. bc_issue counts
    // DUT.ARR.tag_w[22], the registered "S_RUN and not stalled" bit (the one
    // the datapath consumes as d_run): a MAC beat retired. Because tag_w is
    // registered, a block boundary can attribute one beat to the neighbouring
    // block; the total is exact.
    integer bc_iss [0:31];
    integer bc_issue, bc_piss;

    // ---- gather duty: busy cycles (gath_busy) and row-buffer reads (rb_re) ----
    integer bc_gb [0:31];
    integer bc_gbusy, bc_pgb;
    // Row-buffer reads of the gather, one count per rb_re pulse.
    integer bc_rd [0:31];
    integer bc_read, bc_prd;
    // Array stall (DUT.ARR.stall) split by whether a request is outstanding
    // (ARR.pend); the two buckets sum to the stall count by construction.
    integer bc_sp [0:31];   // stall while a request is outstanding
    integer bc_sw [0:31];   // stall while a request is still un-issued

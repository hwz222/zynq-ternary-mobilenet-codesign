// ============================================================================
//  tb_fuse_frame.v -- whole-frame bit-exact gate for twn_fuse_top.
//
//  Scores every byte twn_fuse_top writes to the activation window, as it is
//  written, against gold_out.hex: the seventeen block output tensors of the C
//  reference, transposed CHW -> HWC by tools/gen_fuse_ddr.py. Scoring is at
//  write time because the arena has two slots, so block b+2 overwrites block
//  b's output and a comparison after the frame would see only two tensors.
//
//  Run:   rtl/fuse/sim/run_fuse_axi_boost.ps1 -Only tb_fuse_frame
//         [-Cycles N] [-Defines "A,B"] [-Break DEFINE]
//  Reads (generated by tools/gen_fuse_ddr.py): gold_out.hex, ddr_w.hex,
//  ddr_in_b??.hex, tb_fuse_map.vh, gold_index.vh.
//  Verdict: "=== tb_fuse_frame: N checks, M errors, FRAME PASS|FAIL ===".
//  A block that stores fewer bytes than its tensor is a failure, and a frame
//  with no bit-exact block fails whatever else is excused.
//
//  Modes
//    default             chain: block 0's input is loaded and every later
//                        block reads the design's own previous output.
//    FUSE_FRAME_ISOLATE  (alias FUSE_FRAME_INJECT) each block is fed the C
//                        reference's own input, reloaded into its input slot
//                        when the frame sequencer advances to it, so every
//                        block answers for itself. It cannot see a block that
//                        writes the wrong slot, short, or late; run the chain
//                        as well. The injection itself is checked: image
//                        probes, a read-side classification of every
//                        activation read beat, writes into the running
//                        block's input slot, and in_slot != out_slot.
//
//  Other defines
//    FUSE_FRAME_CYCLES=N   cycle budget, default 4000000 (the runner's -Cycles).
//    FUSE_FRAME_STAGE      split one block (block 0, or FUSE_STAGE_BNN for
//                          block NN) into expand / depthwise / project by
//                          snooping the row-buffer write ports. Needs
//                          gold_stage.vh (gold_stage_bNN.vh) and
//                          gold_bNN_e.hex / gold_bNN_d.hex; no script in this
//                          tree generates them.
//    FUSE_FRAME_BB2HD      BB2HD: enable A_BB2HD and check that the last
//                          block writes only the head's input slot.
//    FUSE_RINGA_PROBE      RingA read-window measurement; FUSE_RINGA_BLK=N
//                          selects the block (default 0).
//    FUSE_SCAT_TRACE       block 0: pulse counts along array -> scatter ->
//                          res_add -> RB_OU.
//    FUSE_STEM_ACT         includes stem_act_probe.vh / stem_act_report.vh
//                          (not in this tree).
//    FUSE_RBC_READ         with ISOLATE: score RB_C's read port at four lags.
//    FUSE_BLK_CYC          per-block cycle attribution; FUSE_IDLE_SPLIT adds
//                          the array-state split.
//    FUSE_OBS              print the design's pix_nz / arr_cap registers.
//    FRAME_ZERO_ACMEM      zero the shared ring array at time 0 instead of X.
//    FUSE_CC_ROWS3, FUSE_ARING_D4, FUSE_ARING_D8
//                          mirror the design defines of the same name
//                          (RingC depth 3; RingA depth 4 or 8).
//
//  Arms that must turn the gate red (runner: -Break)
//    FUSE_NEG_INJECT_ZERO  injection writes zeros to the right address
//    FUSE_NEG_INJECT_SLOT  injection writes the right bytes to the other slot
//    FUSE_NEG_RESPROBE     residual-operand probe reads one row late
//  Other arms
//    FRAME_NEG_GAP0        excuses block 0 as a known gap
//    FUSE_NEG_TAILPACK     design define (tail packing off); see the issue-beat
//                          check under FUSE_BLK_CYC
// ============================================================================
`timescale 1ns/1ps
`ifndef FUSE_FRAME_CYCLES
`define FUSE_FRAME_CYCLES 4000000
`endif
// FUSE_FRAME_INJECT is a second spelling of FUSE_FRAME_ISOLATE.
`ifdef FUSE_FRAME_INJECT
`define FUSE_FRAME_ISOLATE
`endif
`default_nettype none

module tb_fuse_frame;

    `include "tb_fuse_map.vh"
    `include "gold_index.vh"
`ifdef FUSE_FRAME_STAGE
    // Block the stage split is pointed at: block 0 (gold_stage.vh) by default,
    // or -d FUSE_STAGE_BNN. One explicit include per block, because an include
    // name assembled from a define is not portable.
    `ifdef FUSE_STAGE_B01
        `include "gold_stage_b01.vh"
    `elsif FUSE_STAGE_B02
        `include "gold_stage_b02.vh"
    `elsif FUSE_STAGE_B03
        `include "gold_stage_b03.vh"
    `elsif FUSE_STAGE_B04

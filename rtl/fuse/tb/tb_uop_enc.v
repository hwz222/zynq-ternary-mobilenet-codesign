// ============================================================================
//  tb_uop_enc.v -- twn_uop_enc against two oracles, for all 17 blocks x both roles.
//
//  Oracle 1 (derived fields: role, n_pix, n_seg, n_ocg, pack, relu, otype): a
//  copy of build_uop() from tb_p4_block.v. The copy omits that function's
//  build_uop[90] line; [90] and [89:88] are set below from the case table.
//  Oracle 2 (the three bases, uop[81:34]): values computed by
//  gen_uop_cases.py from fuse_weights_index.json, the golden weight files and
//  the P5 gate's requant memory images, not by any expression in the encoder.
//  Inputs: tb_uop_cases.vh (generated by gen_uop_cases.py in this directory).
//  Also asserts that the packer's index and the gate's requant image agree on
//  the project's requant base for every block.
//  `ifdef UOPENC_TB_NEG_TIED_OFF: pack0 and msg are tied to zero, so every
//  stage that tail-packs or rotates must fail.
// ============================================================================
`timescale 1ns/1ps
`default_nettype none

module tb_uop_enc;
    `include "tb_uop_cases.vh"

    reg [9:0] c_mid, c_out;
    reg [8:0] w_in;
    reg       s_dw, stem, role;
    reg [2:0] pack_e, pack_p;
    reg [3:0] nseg_e, nseg_p;   // the descriptor's width, not the field's
    reg [1:0] pack0_e, pack0_p;
    reg       msg_e, msg_p;
    reg [13:0] mb_tern;
    reg [12:0] mb_rqa;
    wire [94:0] uop;

    twn_uop_enc DUT (
        .c_mid(c_mid), .c_out(c_out), .w_in(w_in), .s_dw(s_dw), .stem(stem),
        .pack_e(pack_e), .pack_p(pack_p), .nseg_e(nseg_e), .nseg_p(nseg_p),
        // the descriptor's tail-pack and mixed-segment fields, per block
`ifdef UOPENC_TB_NEG_TIED_OFF
        .pack0_e(2'd0), .pack0_p(2'd0),
        .msg_e(1'b0), .msg_p(1'b0),
`else
        .pack0_e(pack0_e), .pack0_p(pack0_p),
        .msg_e(msg_e), .msg_p(msg_p),
`endif
        .mb_tern(mb_tern), .mb_rqa(mb_rqa),
        .role(role), .uop(uop));

    // tb_p4_block.v's build_uop, verbatim -- including the zeros at [81:34]
    function [94:0] build_uop;
        input        f_role;
        input [8:0]  f_npix;
        input [2:0]  f_nseg;
        input [9:0]  f_nocg;
        input [1:0]  f_pack;
        input        f_relu;
        input [1:0]  f_otype;
        begin
            build_uop = 95'd0;
            build_uop[0]     = f_role;
            build_uop[18:10] = f_npix;
            build_uop[21:19] = f_nseg - 3'd1;
            build_uop[31:22] = f_nocg;
            build_uop[33:32] = f_pack;
            build_uop[82]    = f_relu;
            build_uop[84:83] = f_otype;
            build_uop[85]    = f_role;
            build_uop[86]    = 1'b1;
            build_uop[87]    = 1'b1;
        end
    endfunction

    integer errors = 0, checked = 0, i, b;
    integer err_derived = 0, err_base = 0, packer_disagrees = 0;
    integer n_p0 = 0, n_msg = 0, n_apx = 0;
    reg [94:0] want;
    reg [8:0]  npix;
    reg [9:0]  nocg;
    reg [17:0] exp_wb;
    reg [12:0] exp_rqb;

    task one;
        input       r;
        input [8:0] f_npix;
        input [2:0] f_nseg;
        input [9:0] f_nocg;
        input [1:0] f_pack;
        input       f_relu;
        input [1:0] f_otype;
        begin
            role = r;
            #1;
            // oracle 1 for everything build_uop decides ...
            want = build_uop(r, f_npix, f_nseg, f_nocg, f_pack, f_relu, f_otype);
            // ... and oracle 2, from the packed file, for the three bases.
            // act_base stays 0: the array's act_addr indexes nothing now that
            // twn_act_gather computes its own row-buffer offsets, and zero is
            // what keeps (xg, seg) recoverable from it. See twn_uop_enc.v.
            want[50:34] = 17'd0;
            want[68:51] = exp_wb;
            want[81:69] = exp_rqb;
            // segment 0's pack and the rotation flag: the issuing stage's own
            want[89:88] = r ? pack0_p : pack0_e;
            want[90]    = r ? msg_p   : msg_e;
            checked = checked + 1;
            if (uop !== want) begin
                errors = errors + 1;
                // Say WHICH half moved. A single "these 95 bits differ" sends
                // the reader to the wrong oracle half the time.
                if ((uop[81:34] !== want[81:34])) err_base = err_base + 1;
                if ((uop[33:0]  !== want[33:0]) ||
                    (uop[94:82] !== want[94:82])) err_derived = err_derived + 1;
                if (errors <= 8)
                    $display("  blk %0d %s: got %024h want %024h  (xor %024h)%s%s",
                             b, r ? "project" : "expand ", uop, want, uop ^ want,
                             (uop[81:34] !== want[81:34]) ? "  [bases]" : "",
                             ((uop[33:0] !== want[33:0]) ||
                              (uop[94:82] !== want[94:82])) ? "  [derived]" : "");
            end
        end
    endtask

    initial begin
        for (i = 0; i < NCASE; i = i + 1) begin
            b       = UC_BLK [i*8  +: 8];
            c_mid   = UC_CMID[i*16 +: 16];
            c_out   = UC_COUT[i*16 +: 16];
            w_in    = UC_WIN [i*16 +: 16];
            s_dw    = UC_SDW [i];
            stem    = UC_STEM[i];
            pack_e  = UC_PKE [i*4  +: 4];
            pack_p  = UC_PKP [i*4  +: 4];
            nseg_e  = UC_NSE [i*4  +: 4];
            nseg_p  = UC_NSP [i*4  +: 4];
            mb_tern = UC_MBT [i*16 +: 16];
            mb_rqa  = UC_MBR [i*16 +: 16];
            pack0_e = UC_P0E [i*2  +: 2];
            pack0_p = UC_P0P [i*2  +: 2];
            msg_e   = UC_MSGE[i];
            msg_p   = UC_MSGP[i];
            #1;
    // coverage counters for the pack0 / msg / tail-append fields
            n_p0  = n_p0  + (pack0_e != 2'd0) + (pack0_p != 2'd0);
            n_msg = n_msg + msg_e + msg_p;
            if (UC_WBP[i*18 +: 18] - UC_WBE[i*18 +: 18] !=
                ((c_mid >> pack_e) * nseg_e))
                n_apx = n_apx + 1;     // the expand's run is longer than n_ocg x n_seg

            if (UC_RQBP[i*13 +: 13] !== UC_RQBP_IDX[i*13 +: 13])
                packer_disagrees = packer_disagrees + 1;

            // The expand walks its OWN OUTPUT row, which is the input row for
            // every block but the stem, where the 3x3 stride-2 convolution
            // halves it. The project walks the block's output row, which is the
            // expand's output halved again if the depthwise strides.
            npix    = stem ? (w_in >> 1) : w_in;
            nocg    = c_mid >> pack_e;
            exp_wb  = UC_WBE [i*18 +: 18];
            exp_rqb = UC_RQBE[i*13 +: 13];
            one(1'b0, npix, nseg_e, nocg, pack_e[1:0], 1'b1, 2'd0);

            npix    = stem ? (s_dw ? (w_in >> 2) : (w_in >> 1))
                           : (s_dw ? (w_in >> 1) : w_in);
            nocg    = c_out >> pack_p;
            exp_wb  = UC_WBP [i*18 +: 18];
            exp_rqb = UC_RQBP[i*13 +: 13];
            one(1'b1, npix, nseg_p, nocg, pack_p[1:0], 1'b0, 2'd1);
        end

        if (errors != 0)
            $display("  of %0d wrong micro-ops: %0d have a bad base, %0d a bad derived field",
                     errors, err_base, err_derived);
        // Coverage line: zero is not a failure, but means those fields were
        // not exercised by this case table.
        $display("  covered: %0d stages with pack0 != 0, %0d with msg, %0d blocks whose expand appends words before the project",
                 n_p0, n_msg, n_apx);
        // UC_RQBP is counted off the bit-exact gate's requant memory image;
        // UC_RQBP_IDX is read from pack_fuse_weights.py's index. A mismatch is
        // an error: tb_p4_block builds its image from the array's own walk, so
        // it cannot detect a packer layout change.
        if (packer_disagrees != 0) begin
            errors = errors + packer_disagrees;
            $display("  the packed file's index and the gate's requant image disagree on %0d of %0d blocks",
                     packer_disagrees, NCASE);
            $display("  -- regenerate the weights, or the array and the packer have been separated again");
        end else
            $display("  packed-file index and the array's requant walk agree on all %0d blocks", NCASE);
        $display("=== tb_uop_enc: %0d blocks, %0d micro-ops, %0d errors, %s ===",
                 NCASE, checked, errors,
                 (errors == 0 && checked > 0) ? "ALL PASS" : "FAIL");
        $finish;
    end
endmodule
`default_nettype wire

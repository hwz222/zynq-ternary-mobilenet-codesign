// ============================================================================
//  tb_dw_pack.v -- twn_dw_pack placement, checked by coverage for all 17 blocks.
//
//  For each block every (x, lane group) depthwise output is fed in with a
//  distinguishable payload. Per write the testbench requires exactly one lane
//  enabled and the payload on it; per block it marks each 8-byte lane written
//  and requires every lane of the output row (c_mid * w_out / 8) to be written
//  exactly once and nothing outside the row. w_out is derived from the stem and
//  s_dw flags as twn_fuse_top's dw_w_out_m1 does.
//  Inputs: tb_uop_cases.vh (generated by gen_uop_cases.py in this directory).
//  `ifdef DWP_TB_NEG_WORD6: the DUT gets a 6-bit word index, so rows longer
//  than 64 words wrap onto their own head and coverage must fail on them.
// ============================================================================
`timescale 1ns/1ps
`default_nettype none

module tb_dw_pack;
    `include "tb_uop_cases.vh"

    localparam integer DW_LANES  = 8;
    localparam integer ROW_BYTES = 128;
    localparam integer NLANE     = ROW_BYTES / DW_LANES;      // 16
    localparam integer MAXW      = 96;

    reg clk = 0; always #5 clk = ~clk;
    reg rst = 1;

    reg [9:0]  c_mid;
    reg        in_valid;
    reg [7:0]  in_x, in_tag;
    reg [DW_LANES*8-1:0] in_data;

    wire            wr_en;
    wire [15:0]     wr_word;
    wire [NLANE-1:0] wr_lane;
    wire [ROW_BYTES*8-1:0] wr_data;

    // see the header for DWP_TB_NEG_WORD6
`ifdef DWP_TB_NEG_WORD6
    localparam integer DUT_WORD_BITS = 6;
`else
    localparam integer DUT_WORD_BITS = 16;
`endif
    wire [DUT_WORD_BITS-1:0] wr_word_dut;
    twn_dw_pack #(.DW_LANES(DW_LANES), .ROW_BYTES(ROW_BYTES), .WORD_BITS(DUT_WORD_BITS)) DUT (
        .clk(clk), .rst(rst),
        .c_mid(c_mid), .in_valid(in_valid), .in_x(in_x), .in_tag(in_tag),
        .in_data(in_data),
        .wr_en(wr_en), .wr_word(wr_word_dut), .wr_lane(wr_lane), .wr_data(wr_data));
    // zero-extended explicitly: a narrower port on a wider net leaves the upper
    // bits undriven (z)
    assign wr_word = {{(16-DUT_WORD_BITS){1'b0}}, wr_word_dut};

    // coverage map: one counter per 8-byte lane of the row. Named `seen`
    // because `cover` is a SystemVerilog keyword (the sim scripts pass -sv).
    integer seen [0:MAXW*NLANE-1];
    integer i, b, x, g, k, li, w;
    integer errors = 0, writes = 0, tot_writes = 0;
    integer c_m, w_mid, w_out, n_lg, row_lanes;
    reg [DW_LANES*8-1:0] want_data;

    task check_one;
        begin
            if (!wr_en) begin
                errors = errors + 1;
                if (errors <= 8) $display("  blk %0d: no write for x=%0d g=%0d", b, x, g);
            end else begin
                // exactly one lane enabled
                k = 0;
                for (li = 0; li < NLANE; li = li + 1) if (wr_lane[li]) k = k + 1;
                if (k != 1) begin
                    errors = errors + 1;
                    if (errors <= 8)
                        $display("  blk %0d x=%0d g=%0d: %0d lanes enabled, want 1", b, x, g, k);
                end
                for (li = 0; li < NLANE; li = li + 1) if (wr_lane[li]) begin
                    w = wr_word * NLANE + li;
                    if (w >= MAXW*NLANE) begin
                        errors = errors + 1;
                        if (errors <= 8)
                            $display("  blk %0d x=%0d g=%0d: word %0d past the buffer", b, x, g, wr_word);
                    end else begin
                        seen[w] = seen[w] + 1;
                        writes = writes + 1;
                    end
                    // the enabled lane must carry the data
                    if (wr_data[li*DW_LANES*8 +: DW_LANES*8] !== want_data) begin
                        errors = errors + 1;
                        if (errors <= 8)
                            $display("  blk %0d x=%0d g=%0d: lane %0d carries %016h want %016h",
                                     b, x, g, li,
                                     wr_data[li*DW_LANES*8 +: DW_LANES*8], want_data);
                    end
                end
            end
        end
    endtask

    initial begin
        $display("=== tb_dw_pack: RingC placement, %0d blocks ===", NCASE);
        in_valid = 0; in_x = 0; in_tag = 0; in_data = 0; c_mid = 0;
        repeat (3) @(negedge clk); rst = 0;

        for (i = 0; i < NCASE; i = i + 1) begin
            b     = UC_BLK [i*8  +: 8];
            c_m   = UC_CMID[i*16 +: 16];
            // The depthwise's output row: the expand's output width (halved by
            // the stem) halved again if the depthwise strides.
            w_mid = UC_STEM[i] ? (UC_WIN[i*16 +: 16] / 2) : UC_WIN[i*16 +: 16];
            w_out = UC_SDW[i] ? (w_mid / 2) : w_mid;
            n_lg  = (c_m + DW_LANES - 1) / DW_LANES;
            row_lanes = (c_m * w_out) / DW_LANES;

            // c_mid must be a multiple of DW_LANES (8-byte alignment)
            if (c_m % DW_LANES != 0) begin
                errors = errors + 1;
                $display("  blk %0d: c_mid %0d is not a multiple of %0d -- the 8-byte alignment the design assumes does not hold", b, c_m, DW_LANES);
            end

            for (k = 0; k < MAXW*NLANE; k = k + 1) seen[k] = 0;
            writes = 0;
            c_mid = c_m[9:0];

            for (g = 0; g < n_lg; g = g + 1)
                for (x = 0; x < w_out; x = x + 1) begin
                    @(negedge clk);
                    in_valid  = 1;
                    in_x      = x[7:0];
                    in_tag    = g[7:0];
                    in_data   = {{(DW_LANES*8-32){1'b0}},
                                 x[15:0], g[7:0], 8'hA5};   // distinguishable
                    want_data = in_data;
                    @(negedge clk);
                    in_valid = 0;
                    check_one;
                end

            // ---- the coverage verdict for this block ----
            k = 0;                       /* lanes written more than once */
            li = 0;                      /* lanes in the row never written */
            w  = 0;                      /* lanes written OUTSIDE the row */
            for (x = 0; x < MAXW*NLANE; x = x + 1) begin
                if (x < row_lanes) begin
                    if (seen[x] == 0) li = li + 1;
                    else if (seen[x] > 1) k = k + 1;
                end else if (seen[x] != 0) w = w + 1;
            end
            if (k != 0 || li != 0 || w != 0) begin
                errors = errors + 1;
                $display("  blk %2d COVERAGE: %0d lanes written twice, %0d never, %0d past the row (row is %0d lanes)", b, k, li, w, row_lanes);
            end else begin
                $display("  blk %2d  c_mid %4d  w_out %3d  %4d writes cover %4d lanes exactly once",
                         b, c_m, w_out, writes, row_lanes);
            end
            tot_writes = tot_writes + writes;
        end

        $display("=== tb_dw_pack: %0d blocks, %0d writes, %0d errors, %s ===",
                 NCASE, tot_writes, errors,
                 (errors == 0 && tot_writes > 0) ? "ALL PASS" : "FAIL");
        $finish;
    end
endmodule
`default_nettype wire

# -*- coding: utf-8 -*-
"""gen_scatter_cases.py -- the (C, W, pack) triples tb_act_scatter.v sweeps.

One triple per distinct (C, W, pack) over every block's expand (C_mid, pack_e) and
project (C_out, pack_p). C against the row buffer's word size decides whether a word
holds several pixels, one pixel spreads over several words, or a word straddles two
pixel groups.

Reads:   golden/p1_golden/vec/p1_manifest.json (from golden/p1_golden/run_p1.sh)
Writes:  tb_act_scatter_cases.vh next to this file
Run:     python rtl/fuse/tb/gen_scatter_cases.py
"""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
VEC = os.path.join(ROOT, "golden", "p1_golden", "vec")

man = json.load(io.open(os.path.join(VEC, "p1_manifest.json"), encoding="utf-8"))
seen, uniq = set(), []
for b in man["blocks"]:
    for C, W, P, what in ((b["mid"]["c"], b["in"]["w"],  b["pack_e"]["pack"], "expand"),
                          (b["out"]["c"], b["out"]["w"], b["pack_p"]["pack"], "project")):
        if (C, W, P) not in seen:
            seen.add((C, W, P))
            uniq.append((C, W, P, b["block"], what))

L = ["// generated by gen_scatter_cases.py -- do not edit",
     "localparam integer NCASE = %d;" % len(uniq)]
for name, i in (("SC_C", 0), ("SC_W", 1), ("SC_P", 2)):
    L.append("localparam [16*NCASE-1:0] %s = {%s};" % (
        name, ", ".join("16'd%d" % t[i] for t in reversed(uniq))))
io.open(os.path.join(HERE, "tb_act_scatter_cases.vh"), "w", newline="\n").write(
    "\n".join(L) + "\n")

print("%d distinct (C, W, pack) triples" % len(uniq))
for C, W, P, bi, what in uniq:
    print("   C %4d  W %4d  pack %d   first seen: block %2d %s" % (C, W, P, bi, what))

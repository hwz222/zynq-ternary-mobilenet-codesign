# run_engine_tests.ps1 -- one unit-test suite per hardware engine of the fused accelerator.
#
# Each engine is simulated on its own, with stimulus and expected output produced by software: the
# P1 golden vectors (golden\p1_golden\run_p1.sh), the head reference tools\hd_ref_export.py, and the
# generators in rtl\fuse\tb. Where a testbench has break tests, the same test is compiled with one
# deliberate defect (a -d define) and passes only if the gate fails.
#
#   engine      RTL under test                                tests
#   ---------   -------------------------------------------   ---------------------------------
#   ternary     twn_fuse_select, twn_fuse_tree,               datapath sweep (+2 breaks),
#               twn_fuse_requant, twn_fuse_array              full-array golden rows (+1 break),
#                                                             requant rounding window
#   depthwise   twn_dw_array, twn_dwseq, twn_dw_pack,         run_p3.ps1 (+1 break), walk, packing,
#               twn_rowbuf (lane writes, mod-3)               row-buffer units
#   head        twn_hd_seq, twn_hd_compute, twn_csr           run_hd_seq, run_csr_hd, run_hd_frame,
#               (head windows), twn_axi_rd/wr                 run_hd_int (each with breaks)
#   residual    twn_res_add, twn_res_buf                      saturation sweep, row ring
#   movers      twn_act_rd/wr, twn_ring_warb,                 AXI masters, arbiter, gather, scatter,
#               twn_act_gather, twn_act_scatter, twn_rowbuf   ring pointers
#   weights     twn_wfetch (with twn_axi_rd)                  fetch of the packed weight file
#   control     twn_csr, twn_desctab, twn_frameseq,           descriptor table, frame loop,
#               twn_uop_enc, twn_uop_issue, twn_blockseq      micro-op fields, issue rule, schedule
#
# Usage (PowerShell, from anywhere):
#   .\run_engine_tests.ps1                   all seven engines, with break tests
#   .\run_engine_tests.ps1 -Engine ternary   one engine (a name from the table; others exit 2)
#   .\run_engine_tests.ps1 -NoBreak          skip break tests
#   .\run_engine_tests.ps1 -AllStages        ternary full-array test on every stage, not 8 cases
#   .\run_engine_tests.ps1 -Integration      also run_p5.ps1 (17 blocks) and the whole-frame gate
#                                            (run_fuse_axi_boost.ps1 -Only tb_fuse_frame)
# Prerequisites: Vivado xvlog.bat / xelab.bat / xsim.bat; Python; the other scripts of this
#   directory (they are started as child powershell processes).
# Generated inputs (checked by a guard at the start; it prints the commands when one is missing):
#   golden\p1_golden\vec\b00_in.bin, b16_out.bin   from `bash run_p1.sh` in golden/p1_golden (Git Bash)
#   with -Integration also rtl\fuse\tb\ddr_w.hex and gold_out.hex, from tools\pack_fuse_weights.py,
#   tools\gen_desctab.py and tools\gen_fuse_ddr.py, in that order.
#   Regenerated by this script when needed: rtl\fuse\tb\hd_vec (tools\hd_ref_export.py),
#   tb_res_add_vec.hex (gen_res_add.py), tb_wfetch_ddr.hex (gen_wfetch_tb.py).
# Environment: VIVADO_BIN = Vivado bin directory (default C:\Xilinx\Vivado\2023.2\bin);
#   PYTHON = interpreter (default `python`).
# Work directory: %TEMP%\twn_sim\engines_<pid> (not deleted).
# Result: one line per test ("ok" / "FAIL"), a per-engine summary, then
#   "=== ENGINE TESTS: all N ok ===" (exit 0) or "... N of M FAILED ..." (exit 1). Exit 2 for an
#   unknown -Engine; exit 1 if generated inputs are missing or no test ran.
param([string]$Engine = "all", [switch]$NoBreak, [switch]$AllStages, [switch]$Integration)

$env:PATH = "$(if ($env:VIVADO_BIN) { $env:VIVADO_BIN } else { 'C:\Xilinx\Vivado\2023.2\bin' });$env:PATH"
$tree = (Resolve-Path (Join-Path $PSScriptRoot "..\..\..")).Path
$fuse = Join-Path $tree "rtl\fuse"
$rsrc = Join-Path $tree "rtl\src"
$sim  = $PSScriptRoot
$py   = if ($env:PYTHON) { $env:PYTHON } else { "python" }
$work = Join-Path $env:TEMP ("twn_sim\engines_" + $PID)

# -Engine is checked against the list, so a typo cannot skip every group.
$engineNames = @("all", "ternary", "depthwise", "head", "residual", "movers", "weights", "control")
if ($engineNames -notcontains $Engine) {
    Write-Output ("UNKNOWN -Engine '{0}'. Valid: {1}" -f $Engine, ($engineNames -join ", "))
    exit 2
}
New-Item -ItemType Directory -Force $work | Out-Null

# The guard checks generated outputs, not tracked files; a missing one means the step that
# produces it was never run in this tree.
$need = @("golden\p1_golden\vec\b00_in.bin", "golden\p1_golden\vec\b16_out.bin")
if ($Integration) { $need += @("rtl\fuse\tb\ddr_w.hex", "rtl\fuse\tb\gold_out.hex") }
$missing = @($need | Where-Object { -not (Test-Path (Join-Path $tree $_)) })
if ($missing.Count -gt 0) {
    Write-Output ("MISSING generated inputs: " + ($missing -join ", "))
    Write-Output "  They are gitignored. Produce them in this order (README.md, step 1),"
    Write-Output "  from $tree :"
    Write-Output "    1. ( cd golden/p1_golden && bash run_p1.sh )            # Git Bash; must end 'P1 GATE: PASS'"
    Write-Output "    2. cd tools; $py pack_fuse_weights.py"
    Write-Output "    3. $py gen_desctab.py"
    Write-Output "    4. $py gen_fuse_ddr.py                            # must print 'gen_fuse_ddr verify: ALL PASS'"
    Write-Output "  Steps 2 and 3 write TRACKED files (fuse_weights*.*, tb_desctab_words.vh, tools/fuse_desctab.h):"
    Write-Output "  after a weight change re-run them too, or tb_wfetch / tb_desctab test the previous model."
    exit 1
}

$results = New-Object System.Collections.ArrayList
function Add-Result($eng, $test, $kind, $ok, $detail) {
    [void]$results.Add([pscustomobject]@{ Engine = $eng; Test = $test; Kind = $kind; Ok = $ok; Detail = $detail })
    $mark = if ($ok) { "ok  " } else { "FAIL" }
    Write-Output ("  [{0}] {1,-10} {2,-34} {3}" -f $mark, $eng, $test, $detail)
}

# ---- helpers -----------------------------------------------------------------
# Compile, elaborate and run one self-contained testbench. Returns the xsim text,
# or a string beginning with COMPILE/ELAB ERROR.
function Invoke-Tb($dir, $tbfile, $srcs, $defs, $sv) {
    $name = [IO.Path]::GetFileNameWithoutExtension($tbfile)
    $mod  = (Select-String -Path $tbfile -Pattern "^\s*module\s+(\w+)" | Select-Object -First 1).Matches[0].Groups[1].Value
    $tag  = $name + (($defs | ForEach-Object { "_" + $_ }) -join "")
    $lib  = "w_" + $tag
    Push-Location $dir
    foreach ($d in @($lib, "s_$lib")) { if (Test-Path $d) { Remove-Item -Recurse -Force -LiteralPath $d } }
    $a = @("--nolog")
    if ($sv) { $a += "-sv" }
    $a += @("-work", $lib)
    foreach ($d in $defs) { $a += @("-d", "`"$d`"") }
    $a += $srcs + @($tbfile)
    $c = & xvlog.bat @a 2>&1 | Out-String
    if ($c -match "ERROR") { Pop-Location; return "COMPILE ERROR " + (($c -split "`n" | Select-String "ERROR" | Select-Object -First 1) -join "") }
    $e = & xelab.bat --nolog -debug off -L $lib -s "s_$lib" "$lib.$mod" 2>&1 | Out-String
    if ($e -match "ERROR") { Pop-Location; return "ELAB ERROR " + (($e -split "`n" | Select-String "ERROR" | Select-Object -First 1) -join "") }
    $r = & xsim.bat --nolog "s_$lib" -runall 2>&1 | Out-String
    Pop-Location
    return $r
}

# One run_units.ps1 target; returns $true when it passes and every break test bites.
function Invoke-Unit($eng, $name) {
    $args2 = @("-NoProfile", "-ExecutionPolicy", "Bypass", "-File", (Join-Path $sim "run_units.ps1"), "-Quiet", "-Only", $name)
    if ($NoBreak) { $args2 += "-NoBreak" }
    $o = & powershell @args2 2>&1 | Out-String
    if ($o -match "fuse unit gates: (\d+) pass, (\d+) fail; break tests (\d+) bite, (\d+) did not") {
        # copy the groups first: the next -match overwrites $Matches
        $np = [int]$Matches[1]; $nf = [int]$Matches[2]; $nb = [int]$Matches[3]; $nd = [int]$Matches[4]
        $meas = $o -match "MEAS"
        # a measurement prints a number, not a verdict: it only has to produce its line
        $ok = ($nf -eq 0) -and ($nd -eq 0) -and ($meas -or $np -ge 1)
        $kind = if ($meas) { "measure" } else { "unit" }
        Add-Result $eng $name $kind $ok ($(if ($meas) { "measurement printed" } else { "{0} pass, {1} fail; breaks {2} bite, {3} did not" -f $np, $nf, $nb, $nd }))
    } else {
        Add-Result $eng $name "unit" $false "no summary line from run_units.ps1"
    }
}

# A runner whose own self-test prints a marker line when the gate passes and its
# break arms all fail as required.
function Invoke-Runner($eng, $script, $marker, $extra) {
    $args2 = @("-NoProfile", "-ExecutionPolicy", "Bypass", "-File", (Join-Path $sim $script)) + $extra
    $o = & powershell @args2 2>&1 | Out-String
    $ok = $o -match [regex]::Escape($marker)
    $line = ($o -split "`n" | Select-String -Pattern "intact|=== P3|PASS|FAIL" | Select-Object -Last 1)
    Add-Result $eng $script "gate" $ok ($(if ($ok) { $marker } else { "marker not printed: " + ($line -join "").Trim() }))
    # nothing is returned: a PowerShell function returns ALL of its output, so a
    # caller capturing a return value would also swallow Add-Result's line
}

function Want($e) { return ($Engine -eq "all") -or ($Engine -eq $e) }

Write-Output "=== engine unit tests: tree $tree"
Write-Output "    work $work"
Write-Output ""

# ============================================================================
# 1. TERNARY ARRAY
# ============================================================================
if (Want "ternary") {
    Write-Output "--- ternary array: twn_fuse_select / twn_fuse_tree / twn_fuse_requant / twn_fuse_array"
    $d = Join-Path $work "ternary"; New-Item -ItemType Directory -Force $d | Out-Null
    Push-Location $d
    $gen = & $py (Join-Path $fuse "tb\gen_fuse_dp.py") --sweep 2>&1 | Out-String
    Pop-Location
    $dp = Get-ChildItem (Join-Path $d "tb_fuse_dp_*.v") | Sort-Object Name
    $packOf = @{}; $negOf = @{}
    foreach ($m in [regex]::Matches($gen, "wrote (tb_fuse_dp_\w+)\.v\s.*?pack (\d+)\s+(\d+) negative")) {
        $packOf[$m.Groups[1].Value] = [int]$m.Groups[2].Value; $negOf[$m.Groups[1].Value] = [int]$m.Groups[3].Value
    }
    $dpsrc = @((Join-Path $fuse "twn_fuse_select.v"), (Join-Path $fuse "twn_fuse_tree.v"))
    # (a) datapath: select + adder tree against accumulators decoded independently
    #     from the same packed words. Plain Verilog: the generated bench uses
    #     `expect` as an identifier, which is a SystemVerilog keyword.
    $arms = @(@{ name = "datapath"; defs = @() })
    if (-not $NoBreak) {
        $arms += @{ name = "break NO_REPLICATE"; defs = @("FUSE_NEG_NO_REPLICATE") }
        $arms += @{ name = "break CORRECT_AT_ROOT"; defs = @("FUSE_NEG_CORRECT_AT_ROOT") }
    }
    foreach ($arm in $arms) {
        $good = 0; $bad = 0; $sig = @()
        foreach ($f in $dp) {
            $r = Invoke-Tb $d $f.FullName $dpsrc $arm.defs $false
            $pass = $r -match "PASS --"
            # a build error is never a bite, whatever the case expects
            if ($r -match "^(COMPILE|ELAB) ERROR") { $bad++; $sig += ($f.BaseName + "(build)"); continue }
            if ($arm.defs.Count -eq 0) { if ($pass) { $good++ } else { $bad++; $sig += $f.BaseName } }
            else {
                # Both mechanisms only act when pack > 1, so the expected signature is
                # "pack > 1 cases FAIL, pack-1 cases still PASS". The tap correction
                # additionally needs a -1 weight to correct: the stem's case has none, so it
                # must PASS under CORRECT_AT_ROOT.
                $mustFail = ($packOf[$f.BaseName] -gt 1) -and
                            (($arm.defs[0] -ne "FUSE_NEG_CORRECT_AT_ROOT") -or ($negOf[$f.BaseName] -gt 0))
                if ($mustFail -ne $pass) { $good++ } else { $bad++; $sig += $f.BaseName }
            }
        }
        $kind = if ($arm.defs.Count -eq 0) { "golden" } else { "break" }
        $detail = if ($arm.defs.Count -eq 0) { "$good of $($dp.Count) cases PASS" } else { "expected signature (pack>1 FAIL, pack 1 PASS) on $good of $($dp.Count)" }
        if ($sig.Count) { $detail += "; off: " + ($sig -join ",") }
        Add-Result "ternary" $arm.name $kind ($bad -eq 0 -and $good -gt 0) $detail
    }
    # (b) the whole array against P1's golden output row, at RQ_SPLIT = ACC_SPLIT = 1 (the
    #     module defaults, which twn_fuse_top does not override).
    $man = Get-Content (Join-Path $tree "golden\p1_golden\vec\p1_manifest.json") -Raw | ConvertFrom-Json
    if ($AllStages) {
        $cases = @(); for ($i = 0; $i -lt $man.blocks.Count; $i++) { $cases += ,@($i, "e"); $cases += ,@($i, "p") }
    } else {
        # one case per distinct configuration: stem (3 passes, pack 4), pack 4, pack 1,
        # two segments, pack 2, mixed segment, n_ocg 960, eight segments
        $cases = @(@(0,"e"), @(0,"p"), @(1,"p"), @(2,"p"), @(7,"e"), @(11,"e"), @(14,"e"), @(16,"p"))
    }
    $arsrc = @((Join-Path $fuse "twn_fuse_select.v"), (Join-Path $fuse "twn_fuse_tree.v"), (Join-Path $fuse "twn_fuse_requant.v"),
               (Join-Path $rsrc "bram_sdp.v"), (Join-Path $rsrc "bram_sdp_bw.v"), (Join-Path $fuse "twn_fuse_array.v"))
    $good = 0; $bad = @(); $skipped = 0; $elems = 0
    foreach ($c in $cases) {
        $n = "tb_fuse_ar_b{0:d2}{1}" -f $c[0], $c[1]
        Push-Location $d
        $g = & $py (Join-Path $fuse "tb\gen_fuse_array.py") $c[0] $c[1] --split 1 --asplit 1 -o "$n.v" 2>&1 | Out-String
        Pop-Location
        if ($g -match "skipped") { $skipped++; continue }
        $r = Invoke-Tb $d (Join-Path $d "$n.v") $arsrc @() $true
        if ($r -match "PASS -- (\d+) of (\d+) elements") { $good++; $elems += [int]$Matches[1] } else { $bad += $n }
    }
    Add-Result "ternary" "full array, golden rows" "golden" ($bad.Count -eq 0 -and $good -gt 0) ("$good stages PASS, $elems elements" + $(if ($skipped) { ", $skipped skipped (n_ocg < 2)" } else { "" }) + $(if ($bad.Count) { "; failing: " + ($bad -join ",") } else { "" }))
    if (-not $NoBreak) {
        # requant without rounding: every golden row must notice
        $r = Invoke-Tb $d (Join-Path $d "tb_fuse_ar_b07e.v") $arsrc @("RQ_NO_ROUND") $true
        if (-not (Test-Path (Join-Path $d "tb_fuse_ar_b07e.v"))) { $r = "" }
        Add-Result "ternary" "break RQ_NO_ROUND (b07e)" "break" ($r -match "FAIL --") ($(if ($r -match "FAIL -- (\d+) mismatches") { "caught: $($Matches[1]) mismatches" } else { "NOT caught" }))
    }
    # (c) the requant rounding window at its edges (the 2.5e-6 overflow)
    Invoke-Unit "ternary" "tb_fuse_rq_round"
    Write-Output ""
}

# ============================================================================
# 2. DEPTHWISE ENGINE
# ============================================================================
if (Want "depthwise") {
    Write-Output "--- depthwise: twn_dw_array / twn_dwseq / twn_dw_pack / row buffer"
    Invoke-Runner "depthwise" "run_p3.ps1" "8 pass, 0 fail" @("-Label", "engines")
    if (-not $NoBreak) {
        # A break case bites only if it compiled, ran and failed its check; build errors are
        # counted separately in the summary line matched below.
        $o = & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $sim "run_p3.ps1") -Defines RQ_NO_ROUND -Label break 2>&1 | Out-String
        $bite = $o -match "0 pass, 8 fail \(8 ran and failed, 0 build errors, 0 no result\)"
        Add-Result "depthwise" "break RQ_NO_ROUND (8 rows)" "break" $bite ($(if ($o -match "(\d+) pass, (\d+) fail \((\d+) ran and failed, (\d+) build errors, (\d+) no result\)") { "$($Matches[1]) pass, $($Matches[3]) ran and failed, $($Matches[4]) build errors, $($Matches[5]) no result (must be 0 / 8 / 0 / 0)" } else { "no summary" }))
    }
    foreach ($u in "tb_dwseq", "tb_dw_pack", "tb_rowbuf_lanewr", "tb_rowbuf_mod3") { Invoke-Unit "depthwise" $u }
    Write-Output ""
}

# ============================================================================
# 3. HEAD ENGINE
# ============================================================================
if (Want "head") {
    Write-Output "--- head: twn_hd_seq / twn_hd_compute / twn_csr head windows / HP2 masters"
    & $py (Join-Path $tree "tools\hd_ref_export.py") | Out-Null
    Invoke-Runner "head" "run_hd_seq.ps1"   "HD_SEQ_GATE_SELFTEST_PASS"   @()
    Invoke-Runner "head" "run_csr_hd.ps1"   "CSR_HD_GATE_SELFTEST_PASS"   @()
    Invoke-Runner "head" "run_hd_frame.ps1" "HD_FRAME_GATE_SELFTEST_PASS" @()
    Invoke-Runner "head" "run_hd_int.ps1"   "HD_INT_GATE_PASS"            @()
    Write-Output ""
}

# ============================================================================
# 4-7. RESIDUAL, ACTIVATION MOVERS, WEIGHT FETCH, CONTROL
# ============================================================================
if (Want "residual") {
    Write-Output "--- residual: twn_res_add / twn_res_buf"
    & $py (Join-Path $fuse "tb\gen_res_add.py") | Out-Null
    foreach ($u in "tb_res_add", "tb_res_buf") { Invoke-Unit "residual" $u }
    Write-Output ""
}
if (Want "movers") {
    Write-Output "--- activation movers: twn_act_rd/wr, twn_ring_warb, twn_act_gather, twn_act_scatter, twn_rowbuf"
    foreach ($u in "tb_act_rt", "tb_ring_warb", "tb_act_gather", "tb_act_scatter", "tb_rowbuf_ring", "tb_rowbuf_slice", "tb_rowbuf_extmem", "tb_rowptr_rule") { Invoke-Unit "movers" $u }
    Write-Output ""
}
if (Want "weights") {
    Write-Output "--- weight fetch: twn_wfetch (into twn_wmem's four regions)"
    & $py (Join-Path $fuse "tb\gen_wfetch_tb.py") | Out-Null
    Invoke-Unit "weights" "tb_wfetch"
    Write-Output ""
}
if (Want "control") {
    Write-Output "--- control: twn_desctab / twn_frameseq / twn_uop_enc / twn_uop_issue / twn_blockseq"
    foreach ($u in "tb_desctab", "tb_csr_axil_b2b", "tb_frameseq", "tb_uop_enc", "tb_uop_issue", "tb_p4_schedule") { Invoke-Unit "control" $u }
    Write-Output ""
}

# ============================================================================
# INTEGRATION (opt-in): the engines wired together
# ============================================================================
if ($Integration) {
    Write-Output "--- integration: 17 blocks through the real sequencer and arrays; then the whole frame"
    $o = & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $sim "run_p5.ps1") -Quiet 2>&1 | Out-String
    $ok = $o -match "17 pass, 0 fail"
    Add-Result "integration" "run_p5.ps1 (17 blocks)" "gate" $ok ((($o -split "`n" | Select-String "===" | Select-Object -Last 1) -join "").Trim())
    $o = & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $sim "run_fuse_axi_boost.ps1") -Only tb_fuse_frame -Cycles 3000000 -Defines "FUSE_CC_ROWS3,FUSE_BLK_CYC" -Label engines 2>&1 | Out-String
    $ok = ($o -match "issue beats = 853,760 exactly") -and ($o -match "17 of 17 blocks bit-exact") -and ($o -match "0 errors, FRAME PASS")
    Add-Result "integration" "tb_fuse_frame (whole frame)" "gate" $ok ((($o -split "`n" | Select-String "=== tb_fuse_frame:" | Select-Object -Last 1) -join "").Trim())
    Write-Output ""
}

# ---- summary -----------------------------------------------------------------
Write-Output "=== summary ==="
$results | Group-Object Engine | ForEach-Object {
    $n = @($_.Group).Count; $p = @($_.Group | Where-Object { $_.Ok }).Count
    Write-Output ("  {0,-12} {1,2} of {2,2} ok" -f $_.Name, $p, $n)
}
$failed = @($results | Where-Object { -not $_.Ok })
# A run that checked nothing is not a pass.
if ($results.Count -eq 0) {
    Write-Output "=== ENGINE TESTS: FAIL -- 0 results; nothing was tested ==="
    exit 1
}
if ($failed.Count -gt 0) {
    Write-Output ("=== ENGINE TESTS: {0} of {1} FAILED: {2} ===" -f $failed.Count, $results.Count, (($failed | ForEach-Object { $_.Engine + "/" + $_.Test }) -join "; "))
    exit 1
}
Write-Output ("=== ENGINE TESTS: all {0} ok ===" -f $results.Count)
exit 0
